* SORT OBJECTS
*
SORTOBJECTS@
		MOVEIB	1,STARTDATABASE+00	;INIT GROUND POLY

		MOVEW	VIEWX,STARTDATABASE+01	;
		MOVEW	VIEWY,STARTDATABASE+03	;
		LDA	VIEWZ+0			;
		SEC				;
		SBC	#<HORIZONZ		;
		STA	STARTDATABASE+05	;
		LDA	VIEWZ+1			;
		SBC	#>HORIZONZ		;
		STA	STARTDATABASE+06	;

		CLRB	STARTDATABASE+07	;NO XROT OR YROT
		CLRB	STARTDATABASE+08	;

		LDA	#<$400			;COMPLIMENT OF ZROT
		SEC				;
		SBC	VIEWZROT+0		;
		STA	STARTDATABASE+09	;
		LDA	#>$400			;
		SBC	VIEWZROT+1		;
		AND	#>$3FF			;
		STA	STARTDATABASE+10	;

		PUSHW	VIEWZROT		;SAVE VIEW ZROT

		LDA	VIEWZROT+0		;ROTATE FOR VIEW IN X,Y +
		SEC				;	QUADRANT
		SBC	#$80			;
		STA	VIEWZROT+0		;
		LDA	VIEWZROT+1		;
		SBC	#$00			;
		AND	#>$3FF			;
		STA	VIEWZROT+1		;

		LDA	VIEWZROT+0		;ANY ROTATION?
		ORA	VIEWZROT+1		;
		BEQ	SKIPVIEWZROT1		;NO

		LDX	VIEWZROT+0		;
		LDY	VIEWZROT+1		;
		JSR	ANGLECS			;

		MOVEIB	FALSE,INENEMYRADAR	;INIT FLAGS
		MOVEIB	$EA,LEFTTURN		;
SKIPVIEWZROT1
		SIGNEDACCMATH			;SET SIGNED ACCUMULATE MATH

		LEA	STARTDATABASE,OBJPTR	;POINT TO DATABASE

		LDX	#00			;INIT SORT INDEX
SORTOBJECTSLOOP
		LDA	(OBJPTR)		;END OF TABLE?
		CMP	#EOT			;
		BNE	SORTOBJECTSCONT		;NO
		JMP	SORTOBJECTSDONE		;YES
SORTOBJECTSCONT
		STA	FLAGS			;SAVE FLAGS

		AND	#%00000010		;SKIP BIT SET?
		BEQ	?1			;NO
		JMP	SORTOBJECTSNEXT		;YES - SKIP
?1
		LDY	#OBJ_FLAGS		;INIT FLAG TO SHOOT AT US
		LDA	(OBJPTR),Y		;
		AND	#$7F			;
		STA	(OBJPTR),Y		;

		LDY	#OBJ_FILE		;SAVE FILE NUMBER
		LDA	(OBJPTR),Y		;
		STA	INENEMYRADARW		;

		CMP	#RING_FILE		;RING?
		BNE	?11			;NO
		LDA	MISSION			;TRAINING?
		BEQ	?11			;YES

		JMP	SORTOBJECTSNEXT		;SKIP THIS OBJECT
?11
		LDY	#OBJ_X			;
		LDA	(OBJPTR),Y		;GET OBJECT'S X
		SEC				;
		SBC	VIEWXLO			;
		STA	XDIFF+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		SBC	VIEWXHI			;
	IF	HALFPTS
		AND	#%01111111		;
		STA	XDIFF+1			;
		ASL	A			;
		AND	#%10000000		;
		ORA	XDIFF+1			;
		STA	XDIFF+1			;
	ELSE
		STA	XDIFF+1			;
	ENDIF
		BPL	?XPOS1			;
		CMP	#-SIGHTDISTANCE		;
		BGE	?XOK1			;
?XBAD1
		JMP	SORTOBJECTSNEXT		;SKIP THIS OBJECT
?XPOS1
		CMP	#SIGHTDISTANCE+1	;
		BGE	?XBAD1
?XOK1
		LDY	#OBJ_Y			;
		LDA	(OBJPTR),Y		;GET OBJECT'S Y
		SEC				;
		SBC	VIEWYLO			;
		STA	YDIFF+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		SBC	VIEWYHI			;
	IF	HALFPTS
		AND	#%01111111		;
		STA	YDIFF+1			;
		ASL	A			;
		AND	#%10000000		;
		ORA	YDIFF+1			;
		STA	YDIFF+1			;
	ELSE
		STA	YDIFF+1			;
	ENDIF
		BPL	?YPOS1			;
		CMP	#-SIGHTDISTANCE		;
		BGE	?YOK1			;
?YBAD1
		JMP	SORTOBJECTSNEXT		;SKIP THIS OBJECT
?YPOS1
		CMP	#SIGHTDISTANCE+1	;
		BGE	?YBAD1
?YOK1
		LDA	VIEWZROT+0		;ANY ROTATION?
		ORA	VIEWZROT+1		;
		BEQ	SKIPVIEWZROT2		;NO

		JSR	SORTROTZ@		;
SKIPVIEWZROT2
		LDY	#OBJ_DEFPTR		;GET SIZE OF OBJECT
		LDA	(OBJPTR),Y		;
		STA	WRKPTR+0		;
		INY				;
		LDA	(OBJPTR),Y		;
		STA	WRKPTR+1		;

		LDY	#1			;
		LDA	(WRKPTR),Y		;
	IF	HALFPTS
		LSR	A			;
	ENDIF
		INC	A			;
		EOR	#$FF			;
		INC	A			;
		STA	WORK1			;
;;
;; SHIT - GET VP DISTANCE AND CHECK HERE?
;;
		LDA	INENEMYRADARW		;ENEMY HAS RADAR?
		CMP	#STARTSTARGETS		;
		BLT	NOTINERADAR		;NO

		LDA	FLAGS			;EXPLODING?
		AND	#4			;
		BNE	NOTINERADAR		;YES

		LDA	CRASHFLAG		;CRASHING?
		BEQ	?111			;NO
		BPL	NOTINERADAR		;YES
		CMP	#-1			;
		BEQ	NOTINERADAR		;YES
?111
		LDY	#((1*OBJUSESIZE)+OBJ_FLAGS) ;ARE WE EXPLODING?
		LDA	(POSPTR),Y		;
		AND	#4			;
		BNE	NOTINERADAR		;YES

		LDA	XDIFF+1			;X IN RANGE?
		BPL	?1			;
		EOR	#$FF			;
		INC	A			;
?1
		CMP	#$40			;
		BGE	NOTINERADAR		;NO

		LDA	YDIFF+1			;Y IN RANGE
		BPL	?2			;
		EOR	#$FF			;
		INC	A			;
?2
		CMP	#$2C			;
		BGE	NOTINERADAR		;NO

		MOVEIB	TRUE,INENEMYRADAR	;YES - SET FLAG

		LDA	LEFTTURN		;ALREADY SET?
		CMP	#$EA			;
		BNE	?123			;YES

		MOVEIB	TRUE,LEFTTURN		;

		LDA	YDIFF+1			;
		BMI	?123			;

		MOVEIB	FALSE,LEFTTURN		;
?123
		LDY	#OBJ_FLAGS		;SET FLAG TO SHOOT AT US
		LDA	(OBJPTR),Y		;
		ORA	#$80			;
		STA	(OBJPTR),Y		;
NOTINERADAR
		LDA	XDIFF+1			;X IN SIGHT?
		BPL	?XPOS			;
?XNEG
		CMP	WORK1			;
		BGE	?XOK			;YES
?XBAD
		JMP	SORTOBJECTSNEXT		;SKIP THIS OBJECT
?XPOS
	IF	HALFPTS
		CMP	#$33			;
	ELSE
		CMP	#SIGHTDISTANCE		;
	ENDIF
		BGE	?XBAD			;NO
?XOK
		LDA	YDIFF+1			;Y IN SIGHT?
		BPL	?YPOS			;
?YNEG
		CMP	WORK1			;
		BGE	?YOK			;YES
?YBAD
		JMP	SORTOBJECTSNEXT		;SKIP THIS OBJECT
?YPOS
	IF	HALFPTS
		CMP	#$33			;
	ELSE
		CMP	#SIGHTDISTANCE		;
	ENDIF
		BGE	?YBAD			;NO
?YOK
		
;;		LDA	XDIFF+1			;CHECK FOR SIGHT DISTANCE
;;		BPL	?12			;
;;		CMP	#-SIGHTDISTANCE		;
;;		BGE	?13			;
;;?11
;;		JMP	SORTOBJECTSNEXT		;
;;?12
;;		CMP	#SIGHTDISTANCE+1	;
;;		BGE	?11			;
;;?13
;;		LDA	YDIFF+1			;
;;		BPL	?22			;
;;		CMP	#-SIGHTDISTANCE		;
;;		BGE	?23			;
;;?21
;;		JMP	SORTOBJECTSNEXT		;
;;?22
;;		CMP	#SIGHTDISTANCE+1	;
;;		BGE	?21			;
;;?23

		LDY	#OBJ_Z			;
		LDA	(OBJPTR),Y		;GET OBJECT'S Z
		SEC				;
		SBC	VIEWZLO			;
		STA	ZDIFF+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		SBC	VIEWZHI			;
		STA	ZDIFF+1			;

		LDA	FLAGS			;NON SORTING?
		AND	#%00000001		;
		BEQ	?123
		JMP	SKIPCALCDIST		;YES
?123
		CLEARACCUM			;(SIGNED ACCUMULATE MATH IS ON)
		LDA	XDIFF+0			;X SQUARED +
		STA	MATHD			;
		STA	MATHB			;
		LDA	XDIFF+1			;
		STA	MATHC			;
		STA	MATHA			;START
		LDY	YDIFF+1			;GET NEXT OPERAND WHILE IT RUNS
		WAITMATH			;
		LDA	YDIFF+0			;Y SQUARED +
		STA	MATHD			;
		STA	MATHB			;
		STY	MATHC			;
		STY	MATHA			;START
		LDY	ZDIFF+1			;GET NEXT OPERAND WHILE IT RUNS
		WAITMATH			;
		LDA	ZDIFF+0			;Z SQUARED
		STA	MATHD			;
		STA	MATHB			;
		STY	MATHC			;
		STY	MATHA			;START
		LDA	FLAGS			;SAVE FLAGS WHILE IT RUNS
		STA	SORTBUFFFLAGS,X		;
		WAITMATH			;

		LDA	MATHM			;SAVE DISTANCE RESULT
		STA	SORTBUFFDVL,X		;
		LDA	MATHL			;
		STA	SORTBUFFDLO,X		;
		LDA	MATHK			;
		STA	SORTBUFFDHI,X		;
		LDA	MATHJ			;
		STA	SORTBUFFDVH,X		;
SKIPCALCDIST
		LDA	FLAGS			;SAVE FLAGS
		STA	SORTBUFFFLAGS,X		;

		LDA	OBJPTR+0		;SAVE OBJPTR
		STA	SORTBUFFLO,X		;
		LDA	OBJPTR+1		;
		STA	SORTBUFFHI,X		;

		TXA				;INIT SORTED INDEX
		STA	SORTBUFFINX,X		;

		INX				;
SORTOBJECTSNEXT
		ADDBW	#OBJUSESIZE,OBJPTR	;NEXT OBJECT USE
		JMP	SORTOBJECTSLOOP		;
SORTOBJECTSDONE
		STX	SORTTOTAL		;SAVE TOTAL OBJECTS TO SORT
		NOACCMATH			;SET NO ACCUMULATE

		LDA	SORTTOTAL		;MORE THAN 2?
		CMP	#2			;
		BLT	SORTBUFFDONE		;NO

		DEC	A			;COUNT - 1 TO SORT
		STA	COUNTER1		;

		STZ	SORTINDEX		;
		STZ	COUNTER2		;INIT FURTHEST INDEX
SORTBUFFLOOP
		LDY	SORTINDEX		;SAVE INDEX

		LDX	SORTBUFFINX+0,Y		;GET FIRST INDEX

		LDA	SORTBUFFFLAGS,X		;NON SORTING?
		AND	#%00000001		;
		BNE	SORTBUFFNEXT		;YES

		LDA	SORTBUFFINX+1,Y		;GET SECOND INDEX
		TAY				;

		LDA	SORTBUFFDVH,X		;DIST IN DESCENDING ORDER?
		CMP	SORTBUFFDVH,Y		;
		BNE	?1			;
		LDA	SORTBUFFDHI,X		;
		CMP	SORTBUFFDHI,Y		;
		BNE	?1			;
		LDA	SORTBUFFDLO,X		;
		CMP	SORTBUFFDLO,Y		;
		BNE	?1			;
		LDA	SORTBUFFDVL,X		;
		CMP	SORTBUFFDVL,Y		;
?1
		BGE	SORTBUFFNEXT		;YES
SORTBUFFSWAP
		LDX	SORTINDEX		;SWAP INDEXES
		LDA	SORTBUFFINX+0,X		;
		PHA				;
		LDA	SORTBUFFINX+1,X		;
		STA	SORTBUFFINX+0,X		;
		PLA				;
		STA	SORTBUFFINX+1,X		;

		LDA	SORTINDEX		;TOP OF LIST?
		BEQ	SORTBUFFNEXT		;YES

		DEC	SORTINDEX		;PREV OBJECT USE
		BRA	SORTBUFFLOOP		;
SORTBUFFNEXT
		INC	COUNTER2		;NEXT OBJECT USE
		LDA	COUNTER2		;
		STA	SORTINDEX		;
		DEC	COUNTER1		;
		BNE	SORTBUFFLOOP		;
SORTBUFFDONE
		POPW	VIEWZROT		;

		RTS
*
* END SORTOBJ.ASM

SGETSCREENXYS@
**
** SCREEN X
**
SGETSCREENXYSX1
		LDA	#COLS/2			;INIT SIGN VARIABLES
		STA	SIGNADD			;
		STZ	SIGNFLAG		;

		STZ	MATHH			;

		LDA	YDIFF+1			;YDIFF NEGATIVE?
		BPL	?1			;NO

		INC	SIGNADD			;TOGGLE SIGN FLAG
		DEC	SIGNFLAG		;

		LDA	YDIFF+0			;NEGATE AND SET UP FACTOR 1
		EOR	#$FF			;
		CLC				;
		ADC	#$01			;
		STA	MATHG			;
		LDA	YDIFF+1			;
		EOR	#$FF			;
		ADC	#$00			;
		STA	MATHF			;
		BRA	?2			;
?1
		MOVEW	YDIFF,MATHG		;SET UP FACTOR 1
?2
	IF	HALFXYS
		LDA	XDIFF+0			;
		ASL	A			;
		STA	MATHP			;
		LDA	XDIFF+1			;
		ROL	A			;
		STA	MATHN			;
	ELSE
	  IF	HALFPTS
		LDA	XDIFF+1			;
		LSR	A			;
		PHA				;
		LDA	XDIFF+0			;
		ROR	A			;
		STA	MATHP			;
		PLA				;
		STA	MATHN			;
	  ELSE
		LDA	XDIFF+0			;
		STA	MATHP			;
		LDA	XDIFF+1			;
		STA	MATHN			;
	  ENDIF
	ENDIF
		STZ	MATHE			;START THE DIVIDE
SGETSCREENXYSX2
		WAITMATH			;WAIT FOR DIVIDE
SGETSCREENXYSX3
		LDA	MATHA			;REAL HIGH QUOTIENT?
		ORA	MATHB			;
		BNE	?91			;YES
		LDA	MATHC			;
		CMP	#>MAXCOORD		;
		BLT	?93			;NO
?91
		LDA	SIGNFLAG		;
		BEQ	?92			;

		MOVEIW	MINCOORD,X1		;FAR LEFT
		BRA	?3			;
?92
		MOVEIW	MAXCOORD,X1		;FAR RIGHT
		BRA	?3			;
?93
		LDA	MATHD			;SET SCREEN COORDINATE
		EOR	SIGNFLAG		;
		CLC				;
		ADC	SIGNADD			;
		STA	X1+0			;

		LDA	MATHC			;
		EOR	SIGNFLAG		;
		ADC	#0			;
		STA	X1+1			;
?3

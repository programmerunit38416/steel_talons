*
* SPECIAL GET SCREENX AND SCREENY
*
* ENTRY:
*	XDIFF,YDIFF,ZDIFF - 3D POINT
* EXIT:
*	X1,Y1 - SCREEN POINT
*
SGETSCREENXYS@
		MOVEW	XDIFF,PX		;
		MOVEW	YDIFF,PY		;
		MOVEW	ZDIFF,PZ		;
		JMP	PROJECT@		;
*
* GET X1,Y1 FROM WX1,WY1,WZ1
*
GETSCREENXY1@
		MOVEW	WX1,PX			;
		MOVEW	WY1,PY			;
		MOVEW	WZ1,PZ			;
		JMP	PROJECT@		;
*
* GET X2,Y2 FROM WX2,WY2,WZ2
*
GETSCREENXY2@
		PUSHW	X1			;
		PUSHW	Y1			;
		MOVEW	WX2,PX			;
		MOVEW	WY2,PY			;
		MOVEW	WZ2,PZ			;
		JSR	PROJECT@		;
		MOVEW	X1,X2			;
		MOVEW	Y1,Y2			;
		POPW	Y1			;
		POPW	X1			;
		RTS
*
* END WINDOW.ASM

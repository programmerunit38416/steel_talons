* INIT INTERRUPTS
*
INITINTS@
		LDA	sysIntTable+(2*2)+0	;GET RETURN ADDRESS
		STA	VBL_EXIT+1		;
		LDA	sysIntTable+(2*2)+1	;
		STA	VBL_EXIT+2		;

		LDA	#<VBL_INT@		;SET INTERRUPT ADDRESS
		STA	sysIntTable+(2*2)+0	;
		LDA	#>VBL_INT@		;
		STA	sysIntTable+(2*2)+1	;

		RTS
*
* VERTICAL BLANK INTERRUPT
*
VBL_INT@
		PHA				;SAVE REGS
		PHX				;
		PHY				;

		CLD				;CLEAR DECIMAL MODE

		TIMEOUT				;CHECK FOR TIME OUT
		DISPLAY				;TURN ON THE DISPLAY

		LDA	DisplayFlags		;SET FLAG FOR EOF
		ORA	#DISPLAY_EOFFLAG	;
		STA	DisplayFlags		;

		INC	VBTIME			;INCREMENT REVOLVING COUNTER

		JSR	IGETJOY@		;READ CONTROLLER
		JSR	SPECIALINPUT@		;CHECK FOR SPECIAL INPUT

	IF	USEHSOUNDS=FALSE
		JSR	PLAYSOUNDS@		;PLAY SOUND EFFECTS
	ENDIF

		CMPIB	TRUE,PAUSEDFLAG		;PAUSED?
		BEQ	VBL_DONE		;YES
		LDA	VBCOUNTER		;ALREADY ONE FRAME LATE?
		CMP	#-DEFFRAMETIME		;
		BEQ	VBL_DONE		;YES - STOP COUNTING

		DEC	VBCOUNTER		;DECREMENT VB COUNTER DELAY
VBL_DONE
		PLY				;RESTORE REGS
		PLX				;
		PLA				;
VBL_EXIT
		JMP	IntReturn		;SMC JUMP IN INSTALL
*
* END INTS.ASM

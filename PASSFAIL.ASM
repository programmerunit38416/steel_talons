PASSFAIL
		MOVEIW	PASSFAILSPR,FIRSTSPRITE	;POINT TO FIRST SCB

		LDA	#STARTPFFILES		;
		CLC				;
		ADC	MISSION			;POINT TO CORRECT TITLE
		GETDIR				;GET DIRECTORY ENTRY
		MYOPENFILE			;OPEN THE FILE
		LDA	#1			;DEST ADDRESS
		LDX	#<PFBUFFER		;
		LDY	#>PFBUFFER		;
		READFILE			;READ THE FILE
;;
;; SHOW YOUR TIME
;;
		LDA	PFYTIME1+CONTROL1	;
		ORA	#SKIP_SPRITE		;
		STA	PFYTIME1+CONTROL1	;

		LDX	TIMER+0			;
		BEQ	?1			;

		LDA	PFYTIME1+CONTROL1	;
		AND	#\SKIP_SPRITE		;
		STA	PFYTIME1+CONTROL1	;

		LDA	XDIGITLO,X		;
		STA	PFYTIME1+IMAGEDATA+0	;
		LDA	XDIGITHI,X		;
		STA	PFYTIME1+IMAGEDATA+1	;
?1
		LDX	TIMER+1			;
		LDA	XDIGITLO,X		;
		STA	PFYTIME2+IMAGEDATA+0	;
		LDA	XDIGITHI,X		;
		STA	PFYTIME2+IMAGEDATA+1	;

		LDX	TIMER+2			;
		LDA	XDIGITLO,X		;
		STA	PFYTIME3+IMAGEDATA+0	;
		LDA	XDIGITHI,X		;
		STA	PFYTIME3+IMAGEDATA+1	;

		LDX	TIMER+3			;
		LDA	XDIGITLO,X		;
		STA	PFYTIME4+IMAGEDATA+0	;
		LDA	XDIGITHI,X		;
		STA	PFYTIME4+IMAGEDATA+1	;
;;
;; CHECK FOR NEW BEST TIME
;;
		LDA	#FALSE			;INIT FLAG
		STA	ADDBONUSFLAG		;

		LDA	MISSION			;
		ASL	A			;
		ASL	A			;
		TAY				;

		LDA	BTIMERS+0,Y		;
		CMP	TIMER+0			;
		BLT	?3			;
		BEQ	?21			;
		BGE	?24			;
?21
		LDA	BTIMERS+1,Y		;
		CMP	TIMER+1			;
		BLT	?3			;
		BEQ	?22			;
		BGE	?24			;
?22
		LDA	BTIMERS+2,Y		;
		CMP	TIMER+2			;
		BLT	?3			;
		BEQ	?23			;
		BGE	?24			;
?23
		LDA	BTIMERS+3,Y		;
		CMP	TIMER+3			;
		BLT	?3			;
		BEQ	?3			;
?24
;;
;; NEW BEST TIME
;;
		LDA	TIMER+0			;
		STA	BTIMERS+0,Y		;
		LDA	TIMER+1			;
		STA	BTIMERS+1,Y		;
		LDA	TIMER+2			;
		STA	BTIMERS+2,Y		;
		LDA	TIMER+3			;
		STA	BTIMERS+3,Y		;

		LDA	#<TRUE			;SET FLAG
		STA	ADDBONUSFLAG		;
?3
;;
;; SHOW BEST TIME
;;
		LDA	PFBTIME1+CONTROL1	;
		ORA	#SKIP_SPRITE		;
		STA	PFBTIME1+CONTROL1	;

		LDX	BTIMERS+0,Y		;
		BEQ	?4			;

		LDA	PFBTIME1+CONTROL1	;
		AND	#\SKIP_SPRITE		;
		STA	PFBTIME1+CONTROL1	;

		LDA	XDIGITLO,X		;
		STA	PFBTIME1+IMAGEDATA+0	;
		LDA	XDIGITHI,X		;
		STA	PFBTIME1+IMAGEDATA+1	;
?4
		LDX	BTIMERS+1,Y		;
		LDA	XDIGITLO,X		;
		STA	PFBTIME2+IMAGEDATA+0	;
		LDA	XDIGITHI,X		;
		STA	PFBTIME2+IMAGEDATA+1	;

		LDX	BTIMERS+2,Y		;
		LDA	XDIGITLO,X		;
		STA	PFBTIME3+IMAGEDATA+0	;
		LDA	XDIGITHI,X		;
		STA	PFBTIME3+IMAGEDATA+1	;

		LDX	BTIMERS+3,Y		;
		LDA	XDIGITLO,X		;
		STA	PFBTIME4+IMAGEDATA+0	;
		LDA	XDIGITHI,X		;
		STA	PFBTIME4+IMAGEDATA+1	;
;;
;; CALC ACE,PASS OR FAIL
;;
		LDA	MISSION			;
		ASL	A			;
		ASL	A			;
		TAY				;

		LDA	ATIMERS+0,Y		;ACE?
		CMP	TIMER+0			;
		BLT	?ACE3			;
		BEQ	?ACE21			;
		BGE	?ACE24			;
?ACE21
		LDA	ATIMERS+1,Y		;
		CMP	TIMER+1			;
		BLT	?ACE3			;
		BEQ	?ACE22			;
		BGE	?ACE24			;
?ACE22
		LDA	ATIMERS+2,Y		;
		CMP	TIMER+2			;
		BLT	?ACE3			;
		BEQ	?ACE23			;
		BGE	?ACE24			;
?ACE23
		LDA	ATIMERS+3,Y		;
		CMP	TIMER+3			;
		BLT	?ACE3			;
?ACE24
		MOVEIB	2,PFFLAG		;ACE
		MOVEIW	ACE.BBMDATA,PFSPR+IMAGEDATA
		INC	LIVESLEFT		;ADD A LIFE FOR ACE!!
		JMP	?APFDONE		;
?ACE3
		LDA	PTIMERS+0,Y		;PASS?
		CMP	TIMER+0			;
		BLT	?PASS3			;
		BEQ	?PASS21			;
		BGE	?PASS24			;
?PASS21
		LDA	PTIMERS+1,Y		;
		CMP	TIMER+1			;
		BLT	?PASS3			;
		BEQ	?PASS22			;
		BGE	?PASS24			;
?PASS22
		LDA	PTIMERS+2,Y		;
		CMP	TIMER+2			;
		BLT	?PASS3			;
		BEQ	?PASS23			;
		BGE	?PASS24			;
?PASS23
		LDA	PTIMERS+3,Y		;
		CMP	TIMER+3			;
		BLT	?PASS3			;
?PASS24
		MOVEIB	1,PFFLAG		;PASS
		MOVEIW	PASS.BBMDATA,PFSPR+IMAGEDATA
		JMP	?APFDONE		;
?PASS3
		MOVEIB	0,PFFLAG		;FAIL
		MOVEIW	FAIL.BBMDATA,PFSPR+IMAGEDATA
?APFDONE
;;
;; CHECK MISSION LIST
;;
		LDX	MISSION			;GET MISSION NUMBER

		LDA	PFFLAG			;SAVE STATUS FOR THIS MISSION
		INC	A			;
		STA	MISSIONLIST,X		;

		CPX	#12			;MISSION 12?
		BEQ	?SKIPADD		;YES - DON'T ADD MISSION

		LDA	MISSIONLIST+1,X		;THIS MISSION PREV SELECTED?
		CMP	#-1			;
		BNE	?SKIPADD		;YES - DON'T ADD MISSION

		LDA	#00			;SET TO SELECTABLE
		STA	MISSIONLIST+1,X		;
?SKIPADD
		MOVEIB	$04,PAUSEDSPR+PALETTE	;FOREGROUND

		LDA	PFSPR+CONTROL1		;HIDE PASS/FAIL SPRITE
		ORA	#SKIP_SPRITE		;
		STA	PFSPR+CONTROL1		;

		LDA	BONUSSPR+CONTROL1	;HIDE BONUS SPRITE
		ORA	#SKIP_SPRITE		;
		STA	BONUSSPR+CONTROL1	;

		MYSPRITES			;DRAW SPRITES

		MYDBUF_DISPLAY			;"PAGE FLIP"
		MYWAITEOF			;
		MYRGB16	PASSFAILPAL		;UPDATE PALETTE

		LDX	#45			;SHORT DELAY
PASSFAILWAITLOOP1
		MYWAITEOF			;
		DEX				;
		BNE	PASSFAILWAITLOOP1	;
;;
;; SHOW RESULTS HERE
;;
		LDA	PFSPR+CONTROL1		;SHOW PASS/FAIL SPRITE
		AND	#\SKIP_SPRITE		;
		STA	PFSPR+CONTROL1		;

		LDX	PFFLAG			;
		BNE	SKIPWOW			;

		LDX	#WOW_SOUND		;MAKE NOISE
		JSR	STARTSOUND@		;
SKIPWOW
		LDA	ADDBONUSFLAG		;FLAG SET?
		CMP	#<TRUE			;
		BNE	?1			;NO

		LDA	BONUSSPR+CONTROL1	;SHOW BONUS SPRITE
		AND	#\SKIP_SPRITE		;
		STA	BONUSSPR+CONTROL1	;

		JSR	ADDBONUS		;ADD 1000 POINTS
?1
		MYSPRITES			;DRAW SPRITES

		MYDBUF_DISPLAY			;"PAGE FLIP"

		LDX	#15			;SHORT DELAY
PASSFAILWAITLOOP2
		MYWAITEOF			;
		DEX				;
		BNE	PASSFAILWAITLOOP2	;

		LDX	PFFLAG			;
		BEQ	SKIPSPEECH		;

		CPX	#2			;
		BEQ	?1			;

		LDA	#PGOOD_FILE		;
		BRA	?2			;
?1
		LDA	#EFLYING_FILE		;
?2
		GETDIR				;GET DIRECTORY ENTRY
		MYOPENFILE			;OPEN THE FILE
		LDA	#1			;DEST ADDRESS
		LDX	#<SPRBUFFER		;
		LDY	#>SPRBUFFER		;
		READFILE			;READ THE FILE

		STX	DIGCNT+0		;SAVE ENDING ADDRESS
		STY	DIGCNT+1		;

		LEA	SPRBUFFER,DIGPTR	;START
		SUBW	DIGPTR,DIGCNT		;CONVERT ENDING ADDR TO COUNT
		JSR	PLAYDIG			;PLAY DIGITIZED EFFECT
SKIPSPEECH
		LDX	#240			;4 SECONDS
PASSFAILLOOP
		MYWAITEOF			;
		JSR	GETJOY@			;READ CONTROLLER

		LDA	JOYVALUE		;GET UNDEBOUNCED

		BIT	#B_BUTTON		;B BUTTON PRESSED?
		BNE	PASSFAILDONE		;YES
		BIT	#A_BUTTON		;A BUTTON PRESSED?
		BNE	PASSFAILDONE		;YES

		PHX				;
		JSR	CHECKOTHERFLAGS@	;CHECK FLAGS FOR SPECIAL INPUT
		JSR	SELCHECKPAUSED@		;SELECT CHECK FOR PAUSE REQUEST
		PLX				;

		DEX				;
		BNE	PASSFAILLOOP		;
PASSFAILDONE
		RTS
*
* ADD BONUS POINTS
*
ADDBONUS
		LDA	#10			;1000 POINTS
		CLC				;
		ADC	SCORE+4			;
		STA	SCORE+4			;

		LDX	#4			;
		JMP	CHECKSCORE@		;
*

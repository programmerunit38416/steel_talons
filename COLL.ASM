* CLIFF COLLISION CHECK
*
CLIFFCOLLIDE@
		JSR	CALCDIST@		;CALCULATE DISTANCE
		BCS	CLIFFCOLLIDECONT	;CONTINUE IF CLOSE ENOUGH

		RTS				;TOO FAR AWAY
CLIFFCOLLIDECONT
		CMPIW	($C80+(CERR*2)),ZDIFF	;ABOVE THE CLIFF?
		BLT	?Z1			;NO

		CLC				;YES - ABOVE THE CLIFF

		RTS				;
?Z1
		CLRW	WXROTATION		;ROTATE XDIFF,YDIFF BY ZROT
		CLRW	WYROTATION		;

		LDY	#OBJ_ZROTLO		;
		LDA	#<$400			;
		SEC				;
		SBC	(OBJPTR),Y		;
		STA	WZROTATION+0		;
		LDY	#OBJ_ROTHI		;
		LDA	#>$400			;
		SBC	(OBJPTR),Y		;
		AND	#>$3FF			;
		STA	WZROTATION+1		;

		JSR	GETCOSSIN1@		;
		DOROTATE1			;

		LDX	COLLINDEX		;

		LDA	XDIFF+1			;
		BPL	?X1			;

		NEGW	XDIFF			;
?X1
		LDA	XDIFF+1			;INSIDE CLIFF'S LENGTH?
		CMP	CLIFFLENSHI,X		;
		BNE	?X2			;
		LDA	XDIFF+0			;
		CMP	CLIFFLENSLO,X		;
?X2
		BLT	?X3			;YES

		CLC				;NO - DONE
		RTS				;
?X3
		LDA	YDIFF+1			;RIGHT OF CLIFF?
		BMI	?Y1			;NO

		CMPIW	CERR*4,YDIFF		;INSIDE CLIFF?
		BLT	?Y2			;YES - COLLIDE

		CLC				;NO - DONE
		RTS				;
?Y1
		CMPIW	$FE00,YDIFF		;INSIDE CLIFF?
		BGE	?Y2			;YES - COLLIDE

		CLC				;NO - DONE
		RTS				;
?Y2
	IF	USEHSOUNDS=FALSE
		LDX	#EXPLODE_SOUND		;MAKE NOISE
		JSR	STARTSOUND@		;
	ENDIF

		SEC				;INSIDE CLIFF
		RTS				;

CHECKCOLL@
		CLRW	WCMINZ			;INIT CURRENT MINZ

		LEA	STARTDATABASE,OBJPTR	;POINT TO DATABASE
CHECKCOLLLOOP
		LDA	WCMINZ+0		;ABOVE AN OBJECT?
		ORA	WCMINZ+1		;
		BNE	?1			;YES - DONE

		LDY	#OBJ_FLAGS		;EOT?
		LDA	(OBJPTR),Y		;
		CMP	#EOT			;
		BNE	?NOTDONE		;NO - NOT DONE
?1
		JMP	CHECKCOLLDONE		;ALL DONE
?NOTDONE
		STA	FLAGS			;SAVE FLAGS

		BIT	#1			;NON-SORTING?
		BNE	?SKIP			;YES
		BIT	#2			;SKIP THIS OBJECT?
		BNE	?SKIP			;YES
		BIT	#4			;EXPLODING?
		BEQ	?NOSKIP			;NO
?SKIP
		JMP	CHECKCOLLNEXT		;
?NOSKIP
		LDY	#OBJ_FILE		;GET FILE NUMBER
		LDA	(OBJPTR),Y		;

		CMP	#RING_FILE		;RING?
		BNE	NOTARING		;NO

		CMPIB	SBLACKHA_FILE,WTYPE	;US?
		BNE	?SKIPRING		;NO

		JSR	RINGCOLLIDE@		;
?SKIPRING
		JMP	CHECKCOLLNEXT		;
NOTARING
		CMP	#HILL1_FILE		;<HILL1?
		BLT	NOTAHILL		;YES
		CMP	#HILL3TTT_FILE+1	;>HILL3TTT?
		BGE	NOTAHILL		;YES

		SEC				;SET INDEX
		SBC	#HILL1_FILE		;
		STA	COLLINDEX		;

		JSR	HILLCOLLIDE@		;
		BCS	?1			;
		JMP	CHECKCOLLNEXT		;
?1
		RTS				;COLLIDED WITH A HILL
NOTAHILL
		CMP	#SCLIFF1_FILE		;<SCLIFF1?
		BLT	NOTACLIFF		;YES
		CMP	#SCLIFF4_FILE+1		;>SCLIFF4?
		BGE	NOTACLIFF		;YES

		SEC				;SET INDEX
		SBC	#SCLIFF1_FILE		;
		STA	COLLINDEX		;

		JSR	CLIFFCOLLIDE@		;
		BCS	?1			;
		JMP	CHECKCOLLNEXT		;
?1
		RTS				;COLLIDE WITH A CLIFF
NOTACLIFF
		CMP	#MESA5_FILE		;MESA5?
		BEQ	?1			;YES
		CMP	#MESA1_FILE		;MESA1?
		BEQ	?2			;YES
		CMP	#MESA2_FILE		;MESA2?
		BEQ	?3			;YES
		CMP	#SPINNAC1_FILE		;<SPINNAC1?
		BLT	NOTAPINNAC		;YES
		CMP	#SPINNAC4_FILE+1	;>SPINNAC4?
		BGE	NOTAPINNAC		;YES

		SEC				;SET INDEX
		SBC	#SPINNAC1_FILE		;
		STA	COLLINDEX		;
		BRA	?4			;
?1
		LDA	#4			;
		STA	COLLINDEX		;
		BRA	?4
?2
		LDA	#5			;
		STA	COLLINDEX		;
		BRA	?4
?3
		LDA	#6			;
		STA	COLLINDEX		;
?4
		JSR	PINNACCOLLIDE@		;
		BCC	CHECKCOLLNEXT		;

		RTS				;COLLIDE WITH A PINNAC
NOTAPINNAC
		CMP	#MESA3_FILE		;<MESA3?
		BLT	NOTAMESA1		;YES
		CMP	#MESA4_FILE+1		;>MESA4?
		BGE	NOTAMESA1		;YES

		SEC				;SET INDEX
		SBC	#MESA3_FILE		;
		STA	COLLINDEX		;

		JSR	MESA1COLLIDE@		;
		BCC	CHECKCOLLNEXT		;

		RTS				;COLLIDE WITH A MESA1
NOTAMESA1
;;		CMP	#MESA1_FILE		;<MESA3?
;;		BLT	NOTAMESA2		;YES
;;		CMP	#MESA2_FILE+1		;>MESA4?
;;		BGE	NOTAMESA2		;YES
;;
;;		SEC				;SET INDEX
;;		SBC	#MESA1_FILE		;
;;		STA	COLLINDEX		;
;;
;;		JSR	MESA2COLLIDE@		;
;;		BCC	CHECKCOLLNEXT		;
;;
;;		RTS				;COLLIDE WITH A MESA2
;;NOTAMESA2
		CMP	#(STARTTARGETS-1)	;TARGET? (+ SBLACKHA)
		BLT	CHECKCOLLNEXT		;NO

		SEC				;SET INDEX
		SBC	#(STARTTARGETS-1)	;
		STA	COLLINDEX		;
		BNE	?1			;

		CMPIB	BULLET_FILE,WTYPE	;ONLY BULLETS CAN HURT US
		BNE	CHECKCOLLNEXT		;

		LDA	WFLAG			;FIRED BY US?
		BIT	#$40			;
		BNE	CHECKCOLLNEXT		;YES
;;NEW 04/30/92
		LDA	CRASHFLAG		;WE CRASHED?
		BEQ	?3			;NO
		CMP	#-2			;
		BNE	CHECKCOLLNEXT		;YES

		BRA	?3			;
?1
		LDA	WTYPE			;BULLET MOVING?
		CMP	#BULLET_FILE		;
		BNE	?2			;NO

		LDA	WHOSHOT			;DID THIS TARGET SHOOT IT?
		LDY	#OBJ_FILE		;
		CMP	(OBJPTR),Y		;
		BEQ	CHECKCOLLNEXT		;YES
?2
		LDA	WTYPE			;
		CMP	#SBLACKHA_FILE		;SBLACKHA SHOULD NOT COLLIDE
		BEQ	CHECKCOLLNEXT		;	WITH TARGETS

		CMP	#BULLET_FILE		;ONLY BULLETS,ROCKETS,MISSILES
		BEQ	?3			;
		CMP	#MISSILE1_FILE		;
		BEQ	?3			;
		CMP	#ROCKET_FILE		;
		BNE	CHECKCOLLNEXT		;
?3
		JSR	TARGETCOLLIDE@		;COLLIDE WITH A TARGET
		BCC	CHECKCOLLNEXT		;

		RTS				;
CHECKCOLLNEXT
		ADDBW	#OBJUSESIZE,OBJPTR	;NEXT OBJECT USE
		JMP	CHECKCOLLLOOP		;
CHECKCOLLDONE
		CLC				;NO COLLISIONS
		RTS				;

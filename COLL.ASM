MESA1COLLIDE@
		JSR	CALCDIST@		;CALCULATE DISTANCE
		BCS	MESA1COLLIDECONT	;CONTINUE IF CLOSE ENOUGH

		RTS				;TOO FAR AWAY
MESA1COLLIDECONT
		SIGNEDACCMATH			;SET SIGNED MATH

		CLEARACCUM			;CLEAR ACCUMULATOR

		LDA	XDIFF+0			;X SQUARED
		STA	MATHD			;
		STA	MATHB			;
		LDA	XDIFF+1			;
		STA	MATHC			;
		STA	MATHA			;

		WAITMATH			;

		LDA	YDIFF+0			;+ Y SQUARED
		STA	MATHD			;
		STA	MATHB			;
		LDA	YDIFF+1			;
		STA	MATHC			;
		STA	MATHA			;

		WAITMATH			;

		LDA	MATHJ			;
		BNE	?XY2			;

		LDX	COLLINDEX		;
		LDA	MATHK			;
		CMP	MESA1RVH,X		;
		BNE	?XY1			;
		LDA	MATHL			;
		CMP	MESA1RHI,X		;
?XY1
		BLT	?XY3			;
?XY2
		NOACCMATH			;REMOVE ACCUMULATION

		CLC				;NOT IN MESA
		RTS				;
?XY3
		NOACCMATH			;REMOVE ACCUMULATION

		LDX	COLLINDEX		;ABOVE THE MESA?

		LDA	MESA1ZHI,X		;
		STA	WCMINZ+1		;
		CMP	ZDIFF+1			;
		BNE	?Z1			;
		LDA	MESA1ZLO,X		;
		STA	WCMINZ+0		;
		CMP	ZDIFF+0			;
?Z1
		BGE	?Z2			;NO

		CLC				;YES - ABOVE THE MESA
		RTS				;
?Z2
	IF	USEHSOUNDS=FALSE
		LDX	#EXPLODE_SOUND		;MAKE NOISE
		JSR	STARTSOUND@		;
	ENDIF

		SEC				;INSIDE MESA
		RTS				;
*
* PINNACLE COLLISION CHECK
*
PINNACCOLLIDE@
		JSR	CALCDIST@		;CALCULATE DISTANCE
		BCS	PINNACCOLLIDECONT	;CONTINUE IF CLOSE ENOUGH

		RTS				;TOO FAR AWAY
PINNACCOLLIDECONT
		CLRW	WXROTATION		;ROTATE XDIFF,YDIFF BY ZROT
		CLRW	WYROTATION		;

		LDY	#OBJ_ZROTLO		;
		LDA	#<$400			;
		SEC				;
		SBC	(OBJPTR),Y		;
		STA	WZROTATION+0		;
		LDY	#OBJ_ROTHI		;
		LDA	#>$400			;
		SBC	(OBJPTR),Y		;
		AND	#>$3FF			;
		STA	WZROTATION+1		;

		JSR	GETCOSSIN1@		;
		DOROTATE1			;

		LDX	COLLINDEX		;

		LDA	XDIFF+1			;BEHIND THE PINNACLE?
		BMI	?X3			;
		CMP	PINNACBXHI,X		;
		BNE	?X1			;
		LDA	XDIFF+0			;
		CMP	PINNACBXLO,X		;
?X1
		BLT	?X5			;NO
?X2
		CLC				;NOT IN PINNACLE
		RTS				;
?X3
		CMP	PINNACFXHI,X		;IN FRONT OF THE PINNACLE?
		BNE	?X4			;
		LDA	XDIFF+0			;
		CMP	PINNACFXLO,X		;
?X4
		BLT	?X2			;NO
?X5
		LDA	YDIFF+1			;RIGHT OF THE PINNACLE?
		BMI	?Y3			;
		CMP	PINNACRYHI,X		;
		BNE	?Y1			;
		LDA	YDIFF+0			;
		CMP	PINNACRYLO,X		;
?Y1
		BLT	?Y5			;NO
?Y2
		CLC				;NOT IN PINNACLE
		RTS				;
?Y3
		CMP	PINNACLYHI,X		;LEFT OF THE PINNACLE?
		BNE	?Y4			;
		LDA	YDIFF+0			;
		CMP	PINNACLYLO,X		;
?Y4
		BLT	?Y2			;NO
?Y5
		LDX	COLLINDEX		;ABOVE THE PINNACLE?

		LDA	PINNACZHI,X		;
		STA	WCMINZ+1		;
		CMP	ZDIFF+1			;
		BNE	?Z1			;
		LDA	PINNACZLO,X		;
		STA	WCMINZ+0		;
		CMP	ZDIFF+0			;
?Z1
		BGE	?Z2			;NO

		CLC				;YES - ABOVE THE PINNACLE
		RTS				;
?Z2
	IF	USEHSOUNDS=FALSE
		LDX	#EXPLODE_SOUND		;MAKE NOISE
		JSR	STARTSOUND@		;
	ENDIF

		SEC				;INSIDE PINNACLE
		RTS				;
*
* RING COLLISION CHECK
*
RINGCOLLIDE@
		JSR	CALCDIST@		;CALCULATE DISTANCE

		LDY	#OBJ_Z			;CALC Z DISTANCE
		LDA	WZCOORDINATE+0		;
		SEC				;
		SBC	(OBJPTR),Y		;
		STA	ZDIFF+0			;		
		INY				;
		LDA	WZCOORDINATE+1		;
		SBC	(OBJPTR),Y		;
		STA	ZDIFF+1			;

		CLRW	WXROTATION		;ROTATE XDIFF,YDIFF BY ZROT
		CLRW	WYROTATION		;

		LDY	#OBJ_ZROTLO		;
		LDA	#<$400			;
		SEC				;
		SBC	(OBJPTR),Y		;
		STA	WZROTATION+0		;
		LDY	#OBJ_ROTHI		;
		LDA	#>$400			;
		SBC	(OBJPTR),Y		;
		AND	#>$3FF			;
		STA	WZROTATION+1		;

		JSR	GETCOSSIN1@		;
		DOROTATE1			;

		LDA	XDIFF+1			;
		BPL	?XBAD			;

		NEGW	XDIFF			;
		CMPIW	(MAXSPEED*2),XDIFF	;
		BLT	?XGOOD			;
?XBAD
		CLC				;
		RTS				;
?XGOOD
		LDY	#OBJ_FLAGS		;HIDE THIS ONE
		LDA	(OBJPTR),Y		;
		ORA	#2			;
		STA	(OBJPTR),Y		;
;;
;; ACTIVATE NEXT FLAG HERE
;;
		LDY	#((1*OBJUSESIZE)+OBJ_FILE)
		LDA	(OBJPTR),Y		;
		CMP	#RING_FILE		;
		BEQ	?MORERINGS1		;
;;
;; ALL OUT OF RINGS HERE
;;
		MOVEIB	TRUE,MISSIONOVER	;SET FLAG
		LDA	#<COMPLETEDNL		;
		LDX	#>COMPLETEDNL		;
		PLAYMUSIC			;
		BRA	?ZCONT			;
?MORERINGS1
		LDY	#((1*OBJUSESIZE)+OBJ_FLAGS)
		LDA	(OBJPTR),Y		;
		AND	#%11111101		;
		STA	(OBJPTR),Y		;

		LDA	MISSION			;TRAINING?
		BNE	?ZCONT			;NO

		LDY	#((2*OBJUSESIZE)+OBJ_FILE)
		LDA	(OBJPTR),Y		;
		CMP	#RING_FILE		;
		BNE	?ZCONT			;

		LDY	#((2*OBJUSESIZE)+OBJ_FLAGS)
		LDA	(OBJPTR),Y		;
		AND	#%11111101		;
		STA	(OBJPTR),Y		;
?ZCONT
		LDA	ZDIFF+1			;
		BPL	?Z1			;

		NEGW	ZDIFF			;
?Z1
		CMPIW	($121+$20),ZDIFF	;
		BLT	?ZGOOD			;
;;
;; ABOVE OR BELOW THE RING
;;
		CLC				;
		RTS				;
?ZGOOD
		LDA	YDIFF+1			;
		BPL	?Y1			;

		NEGW	YDIFF			;
?Y1
		CMPIW	($4A6+$20),YDIFF	;
		BLT	?YGOOD			;
;;
;; LEFT OR RIGHT OF THE RING
;;
		CLC				;
		RTS				;
?YGOOD
		LDA	MISSION			;TRAINING?
		BNE	?RINGDONE		;NO

		LDA	#1			;ADD 100 POINTS
		JSR	ADDHUNDREDS@		;

		LDX	#RING_SOUND		;MAKE NOISE
		JSR	STARTSOUND@		;
?RINGDONE
		SEC				;
		RTS				;

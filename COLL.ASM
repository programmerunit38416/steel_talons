* HILL COLLISION CHECK
*
HILLCOLLIDE@
		JSR	CALCDIST@		;CALCULATE DISTANCE
		BCS	HILLCOLLIDECONT		;CONTINUE IF CLOSE ENOUGH

		RTS				;TOO FAR AWAY
HILLCOLLIDECONT
		LDX	COLLINDEX		;GET HILL INDEX

		LDA	MAXZDIFFSLO,X		;GET MAXZDIFF
		STA	MAXZDIFF+0		;
		LDA	MAXZDIFFSHI,X		;
		STA	MAXZDIFF+1		;

;;;		LDA	ZDIFF+1			;ABOVE MAXZDIFF?
;;;		CMP	MAXZDIFF+1		;
;;;		BEQ	?Z2			;
;;;		BLT	?Z3			;
;;;?Z1
;;;		CLC				;YES - ABOVE MAXZDIFF
;;;		RTS				;
;;;?Z2
;;;		LDA	ZDIFF+0			;
;;;		CMP	MAXZDIFF+1		;
;;;		BGE	?Z1			;
;;;?Z3
		LDA	LRDIFFSLO,X		;GET LEFT/RIGHT DIFF
		STA	LRDIFF+0		;
		LDA	LRDIFFSHI,X		;
		STA	LRDIFF+1		;

		LDA	MAXXDIFFSLO,X		;GET MAXXDIFF
		STA	MAXXDIFF+0		;
		LDA	MAXXDIFFSHI,X		;
		STA	MAXXDIFF+1		;

		LDA	MAXXDIFFSLO2,X		;GET MAXXDIFF
		STA	MAXXDIFF2+0		;
		LDA	MAXXDIFFSHI2,X		;
		STA	MAXXDIFF2+1		;

		LDA	SLOPESLO,X		;GET SLOPE
		STA	SLOPE+0			;
		LDA	SLOPESHI,X		;
		STA	SLOPE+1			;

		LDA	SLOPESLO2,X		;GET SLOPE2
		STA	SLOPE2+0		;
		LDA	SLOPESHI2,X		;
		STA	SLOPE2+1		;

		CLRW	WXROTATION		;ROTATE XDIFF,YDIFF BY ZROT
		CLRW	WYROTATION		;

		LDY	#OBJ_ZROTLO		;
		LDA	#<$400			;
		SEC				;
		SBC	(OBJPTR),Y		;
		STA	WZROTATION+0		;
		LDY	#OBJ_ROTHI		;
		LDA	#>$400			;
		SBC	(OBJPTR),Y		;
		AND	#>$3FF			;
		STA	WZROTATION+1		;

		JSR	GETCOSSIN1@		;
		DOROTATE1			;

		LDA	LRDIFF+0		;ANY LEFT/RIGHT DIFF?
		ORA	LRDIFF+1		;
		BNE	YESLRDIFF		;YES
		JMP	NOTQUAD45		;
YESLRDIFF
		NEGW	LRDIFF,WORK1		;CREATE LEFT DIFF

		LDA	YDIFF+1			;
		BPL	CHECKRDIFF		;

		CMPW	YDIFF,WORK1		;INSIDE LEFT LIMIT?
		BGE	NOTQUAD45		;NO
YESQUAD45
		LDA	XDIFF+1			;
		BMI	YESQUAD5		;
YESQUAD4
		CLRW	WZROTATION		;
		JMP	GOTQUAD			;
YESQUAD5
		NEGW	XDIFF			;SIMULATE ZROT=$200
		CLRW	WZROTATION		;
		BRA	GOTQUAD			;
CHECKRDIFF
		CMPW	YDIFF,LRDIFF		;INSIDE RIGHT LIMIT?
		BGE	YESQUAD45		;YES
NOTQUAD45
		MOVEW	SLOPE2,SLOPE		;SET ANGLE SLOPE
		MOVEW	MAXXDIFF2,MAXXDIFF	;SET ANGLE MAXXDIFF

		LDA	YDIFF+1			;
		BMI	NOTQUAD12		;
YESQUAD12
		SUBW	LRDIFF,YDIFF		;ADJUST YDIFF

		LDA	XDIFF+1			;
		BMI	YESQUAD2		;
YESQUAD1
		MOVEIW	$080,WZROTATION		;
		BRA	GOTQUAD			;
YESQUAD2
		MOVEIW	$180,WZROTATION		;
		BRA	GOTQUAD			;
NOTQUAD12
		ADDW	LRDIFF,YDIFF		;ADJUST YDIFF

		LDA	XDIFF+1			;

		LDA	OBJECTZ+0		;
		EOR	#$FF			;
		CLC				;
		ADC	#1			;
		LDA	OBJECTZ+1		;
		EOR	#$FF			;
		ADC	#0			;
		BRA	?8			;
?7
		LDA	OBJECTZ+1		;
?8
		CMP	VPDISTANCE		;
		BLT	?9			;

		STA	VPDISTANCE		;
?9
		PLY				;RESTORE REGS
		PLX				;

		RTS

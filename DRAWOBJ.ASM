EXPLODESCB	.BYTE	TWO_PER_PIXEL+NORMAL_SPRITE	; CONTROL 0
		.BYTE	RELOAD_HVST			; Control 1
		.BYTE	$00				; Control 2
		.WORD	$0000				; Next sprite's address
		.WORD	EXPLODEBUFFER			; ImageData
		.WORD	0				; HPos
		.WORD	0				; VPos
		.WORD	$0100				; HSize
		.WORD	$0100				; VSize
		.WORD	$0000				; Stretch
		.WORD	$0000				; Tilt
		.BYTE	$04,$70,$80			; Palette
*
* CHECK FOR TARGETING INFO
*
CHECKTARGET@
		LDY	#OBJ_FILE		;GET OBJECT TYPE
		LDA	(OBJPTR),Y		;TARGETABLE?
		CMP	#STARTTARGETS		;
		BLT	?TS0			;NO

		LDA	TARGETDELAY		;READY FOR TARGETING?
		BEQ	?TS1			;YES

		DEC	TARGETDELAY		;NO - DECREMENT DELAY
?TS0
		RTS				;
?TS1
		DOROTATEV			;ROTATE AROUND VIEW X,Y,Z

		LDA	XDIFF+1			;IN FRONT OF VIEW?
		BMI	?TS0			;NO
		CMP	#$01			;
		BLT	?TS0			;NO

		ADDBW	#TARGETZD,ZDIFF		;CENTER OF OBJECT

		JSR	SGETSCREENXYS@		;PROJECT THE POINT ONTO SCREEN

		LDA	X1+1			;OFF SCREEN?
		BNE	?TS0			;YES
		CMPIB	COLS,X1			;
		BGE	?TS0			;YES
		LDA	Y1+1			;
		BNE	?TS0			;YES
		CMPIB	CLIPROWS,Y1		;
		BGE	?TS0			;YES

		MOVEW	YDIFF,WORK1		;CALC DISTANCE TO THIS TARGET
		BPL	?TS3			;
		NEGW	WORK1			;
?TS3
		ADDW	XDIFF,WORK1		;

		LDA	TARGETSTATUS		;TARGET IDLING OR RETURNING?
		CMP	#IDLE			;
		BEQ	?TS2			;YES
		CMP	#RETURNING		;
		BEQ	?TS2			;YES
;;
;; CHECK PRIORITY OF TARGET?
;;
		CMPW	OBJPTR,TARGETPTR	;THIS OBJECT TARGETSPR?
		BEQ	?TS4			;YES - SET NEW X,Y
;;NEW 04/30/92
		LDA	WORK1+1			;USE 150% OF DISTANCE
		LSR	A			;	TO CHANGE TARGET
		PHA				;
		LDA	WORK1+0			;
		ROR	A			;
		CLC				;
		ADC	WORK1+0			;
		STA	WORK1+0			;
		PLA				;
		ADC	WORK1+1			;
		STA	WORK1+1			;

		CMPW	WORK1,CLOSETARGETXY	;IS THIS OBJECT CLOSER?
		BLT	?TS5			;NO

		MOVEIB	TRACKING,TARGETSTATUS	;CHANGE TARGETS
		BRA	?TS4			;YES
?TS2
		CMPW	WORK1,CLOSETARGETXY	;IS THIS OBJECT CLOSER?
		BGE	?TS4			;YES
?TS5
		RTS				;NOT CLOSER
?TS4
		MOVEW	WORK1,CLOSETARGETXY	;SET DISTANCE PARMS

		MOVEW	OBJPTR,TARGETPTR	;SAVE POINTER

		LDA	X1			;SET POSITION ON SCREEN
		SEC				;
		SBC	#TARGETCX		;
		STA	NTARGETX		;

		LDA	Y1			;
		SEC				;
		SBC	#TARGETCY		;
		STA	NTARGETY		;

		MOVEIB	TRUE,TARGETONSCREEN	;SET FLAG

		RTS
*
* DRAW THE POLYGONS
*
DRAWPOLYGONS@
		JSR	GETCOSSIN1@		;GET COSINE AND SINE
DRAWPOLYGONSLOOP
		CMPIW	MAXSPR,SPRITECOUNT	;AT MAX?
		BLT	DRAWPOLYGONSCONT	;NO

		JMP	DRAWPOLYGONSDONE	;YES - ABORT
DRAWPOLYGONSCONT
		LDY	#00			;
		LDA	(DEFPTR),Y		;GET DISTANCE PARAMETER
	IF	HALFPTS
		LSR	A			;
	ENDIF
		STA	WORK1			;
		INY				;
		LDA	(DEFPTR),Y		;GET NORMAL
		STA	NORMALINDEX		;
		INY				;
		LDA	(DEFPTR),Y		;GET COLOR
		STA	COLOR			;
		INY				;
		LDA	(DEFPTR),Y		;GET POINT COUNT
		STA	NPOINTS			;
		INY				;

		CMPIB	RING_FILE,FILENUMBER	;RING?
		BNE	?NOTRING		;NO

		LDX	RINGCYCLE		;
		LDA	RINGCOLORS,X		;
		STA	COLOR			;
?NOTRING
		LDX	#00			;
READPNTSLOOP
		CPX	NPOINTS			;DONE?
		BGE	READPNTSDONE		;

		LDA	(DEFPTR),Y		;READ POINT NUMBER
		STA	POINTBUFF,X		;

		INY				;
		INX				;
		BRA	READPNTSLOOP		;
READPNTSDONE
		TYA				;ADVANCE POINTER
		CLC				;
		ADC	DEFPTR+0		;
		STA	DEFPTR+0		;
		BCC	?1			;
		INC	DEFPTR+1		;
?1
		LDA	WORK1			;WITHIN VIEW POLY DISTANCE?
		CMP	VPDISTANCE		;
		BGE	?2			;YES ($FF ALWAYS SEEN)
		JMP	SKIPPOLY		;NO - SKIP THIS POLY
?2
		LDX	NORMALINDEX		;NORMAL ROTATED?
		LDA	NORMALUSE,X		;
		BNE	NORMALOK		;YES

		PHY				;
		JSR	FIXNORMAL@		;NO - CORRECT NORMAL
		PLY				;
NORMALOK
		LDX	NORMALINDEX		;CHECK FOR HIDDEN SURFACE

		LDA	NPOINTS			;JUST TWO POINTS?
		CMP	#2			;
		BNE	?1			;NO
		LDA	NORMALUSE,X		;PRIOR SURFACE HIDDEN?
		CMP	#-2			;
		BNE	?1			;NO
		JMP	SKIPPOLY		;YES
?1
		LDA	#-1			;INIT FLAG
		STA	VISIFLAG		;

		LDY	#00			;CORRECT POINTS IF NECCESSARY
FIXPOINTSLOOP
		CPY	NPOINTS			;DONE?
		BNE	FIXPOINTSCONT		;NO
		JMP	FIXPOINTSDONE		;
FIXPOINTSCONT
		LDA	POINTBUFF,Y		;GET POINT NUMBER
		TAX				;
		STX	POINTINDEX		;

		LDA	POINTUSE,X		;FIXED?
		BNE	POINTOK			;YES

		PHY				;ROTATE,TRANSLATE, AND PROJECT
		JSR	FIXPOINT@		;	THIS POINT
		PLY				;
POINTOK
		CPY	#0			;FIRST POINT?
		BNE	DONEHIDDENCHECK		;NO

		LDX	NORMALINDEX		;GET NORMAL INDEX

		LDA	NPOINTS			;JUST TWO POINTS?
		CMP	#2			;
		BNE	?1			;NO
		LDA	NORMALUSE,X		;PRIOR USE OKAY?
		CMP	#-3			;
		BEQ	DONEHIDDENCHECK		;YES
?1
		LDA	#-2			;INIT TO HIDDEN
		STA	NORMALUSE,X		;

		LDY	POINTINDEX		;GET POINT INDEX
		JSR	CHECKHIDDEN@		;CHECK FOR HIDDEN SURFACE
		BCS	SKIPPOLY		;ABORT IF HIDDEN

		LDA	#-3			;SET PRIOR USE OKAY
		STA	NORMALUSE,X		;

		LDY	#00			;ONLY Y POSSIBLE
DONEHIDDENCHECK
		LDX	POINTINDEX		;CHECK FOR X AND Y ON SCREEN
;;
;; NOTE:
;;	NOT COMPLETELY VALID CHECK - 3D CLIPPING MAY PRODUCE
;;	A POINT ON THE SCREEN (I.E. A ROAD)
;;
		LDA	POINTLISTXH,X		;
		BMI	?1			;
;;;		BNE	?1			;
;;;		LDA	POINTLISTYH,X		;
;;;		BNE	?1			;

		STZ	VISIFLAG		;
?1
		INY				;
		JMP	FIXPOINTSLOOP		;
FIXPOINTSDONE
		LDA	VISIFLAG		;VISIBLE?
		BNE	SKIPPOLY		;NO - SKIP DRAWING

		LDX	MISSION			;
		LDA	COLOR			;
		AND	#$0F			;
		CLC				;
		ADC	MISSIONPALTYPES,X	;
		TAX				;

		LDA	COLORMAPPING,X		;REMAP THE COLOR
		STA	COLOR			;

		LDA	COLORSHADING,X		;GET NUMBER OF SHADES
		BEQ	DONESHADED		;

		CMP	#3			;
		BNE	YESSHADED6		;
YESSHADED3
		LDX	NORMALINDEX		;SHADED 3
		LDA	NORMALSHADE,X		;
		LSR	A			;%11111000
		LSR	A			;
		LSR	A			;
		TAX				;
		LDA	COLOR			;
		CLC				;
		ADC	SHADED3TABLE,X		;
		STA	COLOR			;
		BRA	DONESHADED		;
YESSHADED6
		LDX	NORMALINDEX		;SHADED 6
		LDA	NORMALSHADE,X		;
		LSR	A			;%11111100
		LSR	A			;
		TAX				;
		LDA	COLOR			;
		CLC				;
		ADC	SHADED6TABLE,X		;
		STA	COLOR			;
DONESHADED
		JSR	DRAWONEPOLY@		;DRAW ONE POLYGON
SKIPPOLY
		DEC	POLYGONCOUNT		;
		BEQ	DRAWPOLYGONSDONE	;
		JMP	DRAWPOLYGONSLOOP	;
DRAWPOLYGONSDONE
		RTS

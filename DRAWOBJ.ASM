* DRAW OBJECTS
*
DRAWOBJECTS@
		LDA	#<SPRBUFFER		;INIT LIST POINTERS
		STA	SKYSPRITE+NEXTSPRITE+0	;
		STA	SPRPTR+0		;
		LDA	#>SPRBUFFER		;
		STA	SKYSPRITE+NEXTSPRITE+1	;
		STA	SPRPTR+1		;

		JSR	GETCOSSINV@		;GET SINES AND COSINES
		JSR	GETCOSSIN2@		;

		CLRW	SPRITECOUNT		;INIT NUMBER OF SPRITES

		STZ	SORTINDEX		;INIT INDEX

		LDA	RINGCYCLE		;
		INC	A			;
		AND	#3			;
		STA	RINGCYCLE		;

		MOVEIB	FALSE,TARGETONSCREEN	;INIT FLAG FOR TARGETING
		MOVEIW	MAXCOORD,CLOSETARGETXY	;
DRAWOBJECTSLOOP
		LDX	SORTINDEX		;DONE?
		CPX	SORTTOTAL		;
		BLT	DRAWOBJECTSCONT		;NO

		JMP	DRAWOBJECTSDONE		;YES
DRAWOBJECTSCONT
		LDA	SORTBUFFINX,X		;GET SORTED INDEX
		TAY				;

		LDA	SORTBUFFLO,Y		;
		STA	OBJPTR+0		;
		LDA	SORTBUFFHI,Y		;
		STA	OBJPTR+1		;

		CMPIB	TRUE,VIEWSELF		;WANT TO VIEW SELF?
		BEQ	DONECHECKSELF		;YES

		CMPW	POSPTR,OBJPTR		;VIEWING SELF?
		BEQ	VIEWINGSELF		;YES
		BLT	DONECHECKSELF		;NO

		LDA	POSPTR+0		;CHECK ROTORS
		CLC				;	AND SHADOW
		ADC	#<(OBJUSESIZE*3)	;
		STA	WORK1+0			;
		LDA	POSPTR+1		;
		ADC	#>(OBJUSESIZE*3)	;
		STA	WORK1+1			;

		CMPW	WORK1,OBJPTR		;
		BGE	DONECHECKSELF		;NO
VIEWINGSELF
		JMP	DRAWOBJECTSNEXT		;SKIP
DONECHECKSELF
		LDY	#OBJ_FLAGS		;GET FLAGS
		LDA	(OBJPTR),Y		;
		STA	FLAGS			;

		JSR	CALCXYZ@		;

		LDY	#OBJ_FILE		;XROT VALID?
		LDA	(OBJPTR),Y		;
		CMP	#SBLACKHA_FILE+1	;
		BGE	?1			;NO
		CMP	#ROTOR1_FILE		;
		BGE	?2			;YES
?1
		CLRW	WXROTATION		;NO - CLEAR
		BRA	?3			;
?2
		LDY	#OBJ_XROTLO		;GET OBJECT'S XROT
		LDA	(OBJPTR),Y		;
		STA	WXROTATION+0		;
		LDY	#OBJ_ROTHI		;
		LDA	(OBJPTR),Y		;
		LSR	A			;
		LSR	A			;
		LSR	A			;
		LSR	A			;
		AND	#3			;
		STA	WXROTATION+1		;
?3
		LDY	#OBJ_YROTLO		;GET OBJECT'S YROT
		LDA	(OBJPTR),Y		;
		STA	WYROTATION+0		;
		LDY	#OBJ_ROTHI		;
		LDA	(OBJPTR),Y		;
		LSR	A			;
		LSR	A			;
		AND	#3			;
		STA	WYROTATION+1		;

		CLRW	WZROTATION		;INIT YAW

		LDA	SORTINDEX		;GROUND.TSK?
		BEQ	ITSGROUND1		;YES

		LDY	#OBJ_ZROTLO		;GET OBJECT'S ZROT
		LDA	(OBJPTR),Y		;
		STA	WZROTATION+0		;
		LDY	#OBJ_ROTHI		;
		LDA	(OBJPTR),Y		;
		AND	#3			;
		STA	WZROTATION+1		;
ITSGROUND1
		LDY	#OBJ_DEFPTR		;SET OBJECT DEF POINTER
		LDA	(OBJPTR),Y		;
		STA	DEFPTR+0		;
		INY				;
		LDA	(OBJPTR),Y		;
		STA	DEFPTR+1		;

		LDY	#OBJ_FILE		;SAVE FILE NUMBER
		LDA	(OBJPTR),Y		;
		STA	FILENUMBER		;
		
		MOVEW	XDIFF,OBJECTX		;SAVE UNROTATED OBJECT X,Y,Z
		MOVEW	YDIFF,OBJECTY		;
		MOVEW	ZDIFF,OBJECTZ		;

		LDY	#OBJ_FLAGS		;
		LDA	(OBJPTR),Y		;
		AND	#4			;
		BEQ	?NOTEXPLODING		;

		JSR	SHOWEXPLODE@		;SHOW EXPLOSION
		BRA	DRAWOBJECTSNEXT		;
?NOTEXPLODING
		JSR	CHECKTARGET@		;

		JSR	READOBJFILE@		;READ UP TO START OF POLYS
		JSR	DRAWPOLYGONS@		;DRAW THE POLYGONS
DRAWOBJECTSNEXT
		INC	SORTINDEX		;NEXT OBJECT USE
		JMP	DRAWOBJECTSLOOP		;
DRAWOBJECTSDONE
		CMPIW	SPRBUFFER,SPRPTR	;START OF BUFFER?
		BNE	?1			;NO

		CLRW	SKYSPRITE+NEXTSPRITE	;
		LEA	SKYSPRITE,SPRPTR	;
		RTS				;
?1
		SUBIW	SPRSIZE,SPRPTR		;POINT TO LAST SPRITE IN LIST

		LDY	#NEXTSPRITE		;REMOVE LAST LINK
		LDA	#00			;
		STA	(SPRPTR),Y		;
		INY				;
		STA	(SPRPTR),Y		;

		LDA	TARGETSTATUS		;LOCKED OR TRACKING STATUS?
		CMP	#LOCKED			;
		BEQ	?TS1			;YES
		CMP	#TRACKING		;
		BNE	?TS2			;NO
?TS1
		CMPIB	TRUE,TARGETONSCREEN	;TARGET STILL ON SCREEN?
		BEQ	?TS3			;YES

		MOVEIB	RETURNING,TARGETSTATUS	;NO - SET STATUS TO RETURNING
		MOVEIB	TARGETRD,TARGETDELAY	;SET DELAY BEFORE TRACKING
?TS2
		CMPIB	TRUE,TARGETONSCREEN	;NEW TARGET ON SCREEN?
		BNE	?TS3			;NO

		MOVEIB	TRACKING,TARGETSTATUS	;SET STATUS TO TRACKING
?TS3
		RTS
*
* SHOW AS EXPLOSION INSTEAD
*
SHOWEXPLODE@
		DOROTATEV			;ROTATE AROUND VIEW X,Y,Z

		LDA	XDIFF+1			;IN FRONT OF VIEW?
		BMI	?EXPBAD			;NO
		CMP	#$01			;
		BGE	?EXPCNT			;YES
?EXPBAD
		RTS
?EXPCNT
		ADDBW	#TARGETZD,ZDIFF		;CENTER OF OBJECT

		JSR	SGETSCREENXYS@		;PROJECT THE POINT ONTO SCREEN

		LDY	#CONTROL1		;SET CONTROL1
		LDA	#RELOAD_HVST+SKIP_SPRITE
		STA	(SPRPTR),Y		;

		LDY	#NEXTSPRITE+0		;POINT TO EXPLODE SCB
		LDA	#<EXPLODESCB		;
		STA	(SPRPTR),Y		;
		INY				;
		LDA	#>EXPLODESCB		;
		STA	(SPRPTR),Y		;

		LDY	#OBJ_ANIM		;GET EXPLOSION ANIMATION
		LDA	(OBJPTR),Y		;
		ASL	A			;
		TAX				;
		LDA	EXPLOSIONC0S,X		;
		STA	EXPLODESCB+CONTROL0	;

		LDA	EXPLOSIONPS+0,X		;
		STA	EXPLODESCB+PALETTE+0	;
		LDA	EXPLOSIONPS+1,X		;
		STA	EXPLODESCB+PALETTE+1	;

		TXA				;
		LSR	A			;
		CLC				;
		ADC	#STARTEXPLODES		;
		GETDIR				;GET DIRECTORY ENTRY
		MYOPENFILE			;OPEN THE FILE
		LDA	#1			;DEST ADDRESS
		LDX	#<EXPLODEBUFFER		;
		LDY	#>EXPLODEBUFFER		;
		READFILE			;READ THE FILE

		ADDBW	#SPRSIZE,SPRPTR		;
		INCW	SPRITECOUNT		;INCREMENT SPRITE COUNT

		MOVEW	SPRPTR,EXPLODESCB+NEXTSPRITE

		MOVEW	X1,EXPLODESCB+HPOS	;SET HPOS
		MOVEW	Y1,EXPLODESCB+VPOS	;SET VPOS

		CMPIW	$1800,XDIFF		;
		BLT	?1			;

		MOVEIW	1,WORK1			;
		BRA	?2			;
?1
		LDA	#<$1800			;($1800-XDIFF)
		SEC				;
		SBC	XDIFF+0			;
		STA	WORK1+0			;
		LDA	#>$1800			;
		SBC	XDIFF+1			;
		STA	WORK1+1			;

		LSR	WORK1+1			;/16
		ROR	WORK1+0			;
		LSR	WORK1+1			;
		ROR	WORK1+0			;
		LSR	WORK1+1			;
		ROR	WORK1+0			;
		LSR	WORK1+1			;
		ROR	WORK1+0			;
?2
		ADDBW	#128,WORK1		;

		MOVEW	WORK1,EXPLODESCB+HSIZE	;
		MOVEW	WORK1,EXPLODESCB+VSIZE	;

		LDY	#CONTROL1		;SET CONTROL1
		LDA	#RELOAD_HVST+SKIP_SPRITE
		STA	(SPRPTR),Y		;

		JSR	LINKNEXT@		;

		RTS

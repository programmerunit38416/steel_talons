* CHECK FOR TARGETING INFO
*
CHECKTARGET@
		LDY	#OBJ_FILE		;GET OBJECT TYPE
		LDA	(OBJPTR),Y		;TARGETABLE?
		CMP	#STARTTARGETS		;
		BLT	?TS0			;NO

		LDA	TARGETDELAY		;READY FOR TARGETING?
		BEQ	?TS1			;YES

		DEC	TARGETDELAY		;NO - DECREMENT DELAY
?TS0
		RTS				;
?TS1
		LDA	XDIFF+1			;IN FRONT OF VIEW?
		BMI	?TS0			;NO
		CMP	#$01			;
		BLT	?TS0			;NO

		ADDBW	#TARGETZD,ZDIFF		;CENTER OF OBJECT

		JSR	SGETSCREENXYS@		;PROJECT THE POINT ONTO SCREEN

		LDA	X1+1			;OFF SCREEN?
		BNE	?TS0			;YES
		CMPIB	COLS,X1			;
		BGE	?TS0			;YES
		LDA	Y1+1			;
		BNE	?TS0			;YES
		CMPIB	CLIPROWS,Y1		;
		BGE	?TS0			;YES

		MOVEW	YDIFF,WORK1		;CALC DISTANCE TO THIS TARGET
		BPL	?TS3			;
		NEGW	WORK1			;
?TS3
		ADDW	XDIFF,WORK1		;

		LDA	TARGETSTATUS		;TARGET IDLING OR RETURNING?
		CMP	#IDLE			;
		BEQ	?TS2			;YES
		CMP	#RETURNING		;
		BEQ	?TS2			;YES
;;
;; CHECK PRIORITY OF TARGET?
;;
		CMPW	OBJPTR,TARGETPTR	;THIS OBJECT TARGETSPR?
		BEQ	?TS4			;YES - SET NEW X,Y
;;NEW 04/30/92
		LDA	WORK1+1			;USE 150% OF DISTANCE
		LSR	A			;	TO CHANGE TARGET
		PHA				;
		LDA	WORK1+0			;
		ROR	A			;
		CLC				;
		ADC	WORK1+0			;
		STA	WORK1+0			;
		PLA				;
		ADC	WORK1+1			;
		STA	WORK1+1			;

		CMPW	WORK1,CLOSETARGETXY	;IS THIS OBJECT CLOSER?
		BLT	?TS5			;NO

		MOVEIB	TRACKING,TARGETSTATUS	;CHANGE TARGETS
		BRA	?TS4			;YES
?TS2
		CMPW	WORK1,CLOSETARGETXY	;IS THIS OBJECT CLOSER?
		BGE	?TS4			;YES
?TS5
		RTS				;NOT CLOSER
?TS4
		MOVEW	WORK1,CLOSETARGETXY	;SET DISTANCE PARMS

		MOVEW	OBJPTR,TARGETPTR	;SAVE POINTER

		LDA	X1			;SET POSITION ON SCREEN
		SEC				;
		SBC	#TARGETCX		;
		STA	NTARGETX		;

		LDA	Y1			;
		SEC				;
		SBC	#TARGETCY		;
		STA	NTARGETY		;

		MOVEIB	TRUE,TARGETONSCREEN	;SET FLAG

		RTS

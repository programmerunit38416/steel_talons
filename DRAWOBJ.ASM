* SET UP POINTERS FOR OBJECT DEF
*
* ENTRY:
*	DEFPTR		RAM ADDRESS OF FILE
* EXIT:
*	DEFPTR		POINTS TO POLYGONS
*	VPDISTANCE	HIGH BYTE DISTANCE TO OBJECT
*
READOBJFILE@
		PHX				;SAVE REGS
		PHY				;

		LDY	#4			;GET POINT COUNT
		LDA	(DEFPTR),Y		;
		STA	POINTCOUNT		;

		LDA	DEFPTR+0		;SAVE START OF POINTS
		CLC				;
		ADC	#6			;
		STA	STARTOFPOINTS+0		;
		LDA	DEFPTR+1		;
		ADC	#0			;
		STA	STARTOFPOINTS+1		;

		LDY	POINTCOUNT		;ADVANCE POINTER
		LDA	STARTOFPOINTS+0		;
		CLC				;
		ADC	MULT6LO,Y		;
		STA	DEFPTR+0		;
		LDA	STARTOFPOINTS+1		;
		ADC	MULT6HI,Y		;
		STA	DEFPTR+1		;

		LDA	(DEFPTR)		;READ NORMAL COUNT
		STA	NORMALCOUNT		;

		LDA	DEFPTR+0		;SAVE START OF NORMALS
		CLC				;
		ADC	#2			;
		STA	STARTOFNORMALS+0	;
		LDA	DEFPTR+1		;
		ADC	#0			;
		STA	STARTOFNORMALS+1	;

		LDY	NORMALCOUNT		;ADVANCE POINTER
		LDA	STARTOFNORMALS+0	;
		CLC				;
		ADC	MULT6LO,Y		;
		STA	DEFPTR+0		;
		LDA	STARTOFNORMALS+1	;
		ADC	MULT6HI,Y		;
		STA	DEFPTR+1		;

		LDA	(DEFPTR)		;READ POLYGON COUNT
		STA	POLYGONCOUNT		;

		ADDBW	#2,DEFPTR		;ADVANCE POINTER

		LDY	#00			;INIT POINT USE
		LDA	POINTCOUNT		;
		CLC				;
		ADC	#7			;
		LSR	A			;
		LSR	A			;
		LSR	A			;
		TAX				;
INITPOINTUSELOOP
		LDA	#00			;

		STA	POINTUSE+0,Y		;
		STA	POINTUSE+1,Y		;
		STA	POINTUSE+2,Y		;
		STA	POINTUSE+3,Y		;
		STA	POINTUSE+4,Y		;
		STA	POINTUSE+5,Y		;
		STA	POINTUSE+6,Y		;
		STA	POINTUSE+7,Y		;

		TYA				;
		CLC				;
		ADC	#8			;
		TAY				;
		DEX				;
		BNE	INITPOINTUSELOOP	;

		LDY	#00			;INIT NORMAL USE
		LDA	NORMALCOUNT		;
		CLC				;
		ADC	#7			;
		LSR	A			;
		LSR	A			;
		LSR	A			;
		TAX				;
INITNORMALUSELOOP
		LDA	#00			;

		STA	NORMALUSE+0,Y		;
		STA	NORMALUSE+1,Y		;
		STA	NORMALUSE+2,Y		;
		STA	NORMALUSE+3,Y		;
		STA	NORMALUSE+4,Y		;
		STA	NORMALUSE+5,Y		;
		STA	NORMALUSE+6,Y		;
		STA	NORMALUSE+7,Y		;
		STA	NORMALSHOK+0,Y		;
		STA	NORMALSHOK+1,Y		;
		STA	NORMALSHOK+2,Y		;
		STA	NORMALSHOK+3,Y		;
		STA	NORMALSHOK+4,Y		;
		STA	NORMALSHOK+5,Y		;
		STA	NORMALSHOK+6,Y		;
		STA	NORMALSHOK+7,Y		;

		TYA				;
		CLC				;
		ADC	#8			;
		TAY				;
		DEX				;
		BNE	INITNORMALUSELOOP	;

		LDA	OBJECTX+1		;CALC X DISTANCE
		BPL	?2			;

		LDA	OBJECTX+0		;
		EOR	#$FF			;
		CLC				;
		ADC	#1			;
		LDA	OBJECTX+1		;
		EOR	#$FF			;
		ADC	#0			;
		STA	VPDISTANCE		;
		BRA	?3			;
?2
		LDA	OBJECTX+1		;
		STA	VPDISTANCE		;
?3
		LDA	OBJECTY+1		;CALC Y DISTANCE
		BPL	?4			;

		LDA	OBJECTY+0		;
		EOR	#$FF			;
		CLC				;
		ADC	#1			;
		LDA	OBJECTY+1		;
		EOR	#$FF			;
		ADC	#0			;
		BRA	?5			;
?4
		LDA	OBJECTY+1		;
?5
		CMP	VPDISTANCE		;

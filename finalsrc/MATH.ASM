* 32 BIT = 32 BIT / 16 BIT DIVIDE
*	SDIVIDE - SIGNED
*	UDIVIDE - UNSIGNED
*
* QUOTIENT = DIVIDEND / DIVISOR
*
SDIVIDE@
		LDA	DIVISOR+0		;DIVIDE BY 0?
		ORA	DIVISOR+1		;
		BNE	?1			;NO

		MOVEW	DIVIDEND,QUOTIENT	;RETURN DIVIDEND
		MOVEW	DIVIDEND+2,QUOTIENT+2	;

		RTS				;ABORT
?1
		STZ	SIGNFLAG		;INIT SIGNED FLAG

		LDA	DIVISOR+1		;SIGNED?
		BPL	?2			;NO

		DEC	SIGNFLAG		;SET SIGNED FLAG

		LDA	DIVISOR+0		;SET UP DIVISOR
		EOR	#$FF			;
		CLC				;
		ADC	#$01			;
		STA	MATHP			;
		LDA	DIVISOR+1		;
		EOR	#$FF			;
		ADC	#$00			;
		STA	MATHN			;
		BRA	?3			;
?2
		LDA	DIVISOR+0		;SET UP DIVISOR
		STA	MATHP			;
		LDA	DIVISOR+1		;
		STA	MATHN			;
?3
		LDA	DIVIDEND+3		;SIGNED?
		BPL	?4			;NO

		LDA	SIGNFLAG		;TOGGLE FLAG
		EOR	#$FF			;
		STA	SIGNFLAG		;

		LDA	DIVIDEND+0		;
		EOR	#$FF			;
		CLC				;
		ADC	#$01			;
		STA	MATHH			;
		LDA	DIVIDEND+1		;
		EOR	#$FF			;
		ADC	#$00			;
		STA	MATHG			;
		LDA	DIVIDEND+2		;
		EOR	#$FF			;
		ADC	#$00			;
		STA	MATHF			;
		LDA	DIVIDEND+3		;
		EOR	#$FF			;
		ADC	#$00			;
		STA	MATHE			;START DIVIDE
		BRA	?5			;
?4
		LDA	DIVIDEND+0		;
		STA	MATHH			;
		LDA	DIVIDEND+1		;
		STA	MATHG			;
		LDA	DIVIDEND+2		;
		STA	MATHF			;
		LDA	DIVIDEND+3		;
		STA	MATHE			;START DIVIDE
?5
		WAITMATH			;WAIT UNTIL COMPLETE

		LDA	SIGNFLAG		;SIGNED QUOTIENT?
		BEQ	?6			;NO

		LDA	MATHD			;GET QUOTIENT
		EOR	#$FF			;
		CLC				;
		ADC	#$01			;
		STA	QUOTIENT+0		;
		LDA	MATHC			;
		EOR	#$FF			;
		ADC	#$00			;
		STA	QUOTIENT+1		;
		LDA	MATHB			;
		EOR	#$FF			;
		ADC	#$00			;
		STA	QUOTIENT+2		;
		LDA	MATHA			;
		EOR	#$FF			;
		ADC	#$00			;
		STA	QUOTIENT+3		;

		RTS				;
?6
		LDA	MATHD			;GET QUOTIENT
		STA	QUOTIENT+0		;
		LDA	MATHC			;
		STA	QUOTIENT+1		;
		LDA	MATHB			;
		STA	QUOTIENT+2		;
		LDA	MATHA			;
		STA	QUOTIENT+3		;

		RTS
*
* 32 BIT = 32 BIT / 16 BIT DIVIDE
*	SDIVIDE - SIGNED
*	UDIVIDE - UNSIGNED
*
* QUOTIENT = DIVIDEND / DIVISOR
*
UDIVIDE@
		LDA	DIVISOR+0		;DIVIDE BY 0?
		ORA	DIVISOR+1		;
		BNE	?1			;NO

		MOVEW	DIVIDEND+0,QUOTIENT+0	;RETURN DIVIDEND
		MOVEW	DIVIDEND+2,QUOTIENT+2	;

		RTS				;ABORT
?1
		LDA	DIVISOR+0		;SET UP DIVISOR
		STA	MATHP			;
		LDA	DIVISOR+1		;
		STA	MATHN			;

		LDA	DIVIDEND+0		;SET UP DIVIDEND
		STA	MATHH			;
		LDA	DIVIDEND+1		;
		STA	MATHG			;
		LDA	DIVIDEND+2		;
		STA	MATHF			;
		LDA	DIVIDEND+3		;
		STA	MATHE			;START DIVIDE

		WAITMATH			;WAIT UNTIL COMPLETE

		LDA	MATHD			;GET QUOTIENT
		STA	QUOTIENT+0		;
		LDA	MATHC			;
		STA	QUOTIENT+1		;
		LDA	MATHB			;
		STA	QUOTIENT+2		;
		LDA	MATHA			;
		STA	QUOTIENT+3		;

		RTS
*
* 16 BIT x 16 BIT = 32 BIT MUTLIPLY
*	SMULTIPLY - SIGNED
*	UMULTIPLY - UNSIGNED
*
* PRODUCT = FACTOR1 * FACTOR2
*
SMULTIPLY@
		SIGNEDMATH			;SET SIGNED MATH
		BRA	CMULTIPLY		;
UMULTIPLY
		UNSIGNEDMATH			;SET UNSIGNED MATH
CMULTIPLY
		LDA	FACTOR1+0		;SET UP FACTOR1
		STA	MATHD			;
		LDA	FACTOR1+1		;
		STA	MATHC			;

		LDA	FACTOR2+0		;SET UP FACTOR2
		STA	MATHB			;
		LDA	FACTOR2+1		;
		STA	MATHA			;START THE MULTIPLY

		WAITMATH			;WAIT UNTIL COMPLETE

		LDA	MATHH			;GET PRODUCT
		STA	PRODUCT+0		;
		LDA	MATHG			;
		STA	PRODUCT+1		;
		LDA	MATHF			;
		STA	PRODUCT+2		;
		LDA	MATHE			;
		STA	PRODUCT+3		;

		RTS

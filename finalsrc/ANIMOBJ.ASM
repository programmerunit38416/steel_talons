ANIMOBJECTS@
		LDA	#<$400			;GET VIEW OBJECT'S YAW
		SEC				;
		SBC	VIEWZROT+0		;
		STA	WVIEWROT+0		;
		LDA	#>$400			;
		SBC	VIEWZROT+1		;
		AND	#>$3FF			;
		STA	WVIEWROT+1		;

		LDA	WVIEWROT+1		;TURN OBJECT TOWARD VIEW
		CLC				;
		ADC	#>$200			;
		AND	#>$3FF			;
		STA	WVIEWROT+1		;

		LEA	STARTDATABASE,OBJPTR	;POINT TO DATABASE
ANIMOBJLOOP
		LDY	#OBJ_FLAGS		;
		LDA	(OBJPTR),Y		;EOT?
		CMP	#EOT			;
		BNE	ANIMOBJCONT1		;NO
		JMP	ANIMOBJDONE		;
ANIMOBJCONT1
		STA	FLAGS			;SAVE FLAGS

		AND	#%00000010		;SKIP THIS OBJECT?
		BEQ	ANIMOBJCONT2		;NO
		JMP	ANIMOBJNEXT		;
ANIMOBJCONT2
		LDA	FLAGS			;EXPLODING?
		AND	#%00000100		;
		BEQ	NOANIMEXPLODE		;NO

		LDY	#OBJ_ANIM		;ANIMATE EXPLOSION
		LDA	(OBJPTR),Y		;
		INC	A			;
		STA	(OBJPTR),Y		;

		CMP	#EXPLODEFRAMES		;DONE?
		BLT	?2			;NO

		LDA	OBJPTR+0		;BLACKHAWK'S ROTOR?
		SEC				;
		SBC	#<(1*OBJUSESIZE)	;
		PHA				;
		LDA	OBJPTR+1		;
		SBC	#>(1*OBJUSESIZE)	;
		CMP	POSPTR+1		;
		BEQ	?11			;

		PLA				;
		BRA	?1			;NO
?11		
		PLA				;
		CMP	POSPTR+0		;
		BNE	?1			;NO

;;;		LDY	#OBJ_FILE		;BLACKHAWK'S ROTOR1?
;;;		LDA	(OBJPTR),Y		;
;;;		CMP	#ROTOR1_FILE		;
;;;		BNE	?1			;NO

		LDY	#OBJ_FLAGS		;YES - STOP EXPLOSION
		LDA	(OBJPTR),Y		;
		AND	#%11111011		;
		ORA	#2			;AND HIDE
		STA	(OBJPTR),Y		;
		BRA	?2			;
?1
		JSR	HIDETARGET@		;YES - REMOVE OBJECT
?2
		JMP	ANIMOBJNEXT		;
NOANIMEXPLODE
		LDY	#OBJ_FILE		;GET FILE NUMBER
		LDA	(OBJPTR),Y		;

		CMP	#SBLACKHA_FILE		;SBLACKHA?
		BNE	NOTSBLACKHA		;NO

		MOVEW	CMINZ,WCMINZ		;GET CURRENT MINZ
		JSR	UPDATECSHADOW		;UPDATE CHOPPER SHADOW

		LDA	CRASHFLAG		;
		BEQ	?1			;
		BPL	?2			;
?1
		JSR	UPDATEROTORS		;UPDATE THE ROTORS
		JMP	ANIMOBJNEXT		;
?2
		LDY	#OBJ_Z			;COPY Z IN CASE EXPLOSION
		LDA	(OBJPTR),Y		;	ON ROTORS
		LDY	#(OBJUSESIZE+OBJ_Z)	;
		STA	(OBJPTR),Y		;
		LDY	#(OBJ_Z+1)		;
		LDA	(OBJPTR),Y		;
		LDY	#(OBJUSESIZE+OBJ_Z+1)	;
		STA	(OBJPTR),Y		;

		JMP	ANIMOBJNEXT		;
NOTSBLACKHA
		CMP	#TREE1_FILE		;TREE1?
		BEQ	SHOWASTREE		;YES
		CMP	#RING_FILE		;RING?
		BNE	NOTTREE1		;NO
		LDA	MISSION			;TRAINING?
		BEQ	SHOWASTREE		;YES

		JMP	ANIMOBJNEXT		;
SHOWASTREE
		LDY	#OBJ_ZROTLO		;FACE TOWARD VIEW
		LDA	WVIEWROT+0		;
		STA	(OBJPTR),Y		;
		LDY	#OBJ_ROTHI		;
		LDA	(OBJPTR),Y		;
		AND	#%11111100		;
		ORA	WVIEWROT+1		;
		STA	(OBJPTR),Y		;
		JMP	ANIMOBJNEXT		;
NOTTREE1
		CMP	#BUSH1_FILE		;BUSH1?
		BNE	NOTBUSH1		;NO

		LDY	#OBJ_ZROTLO		;FACE TOWARD VIEW
		LDA	WVIEWROT+0		;
		STA	(OBJPTR),Y		;
		LDY	#OBJ_ROTHI		;
		LDA	(OBJPTR),Y		;
		AND	#%11111100		;
		ORA	WVIEWROT+1		;
		STA	(OBJPTR),Y		;
		JMP	ANIMOBJNEXT		;
NOTBUSH1
		CMP	#SJET1_FILE		;SJET1?
		BNE	NOTSJET1		;NO

		JSR	MOVEJET			;MOVE JET
		JSR	UPDATEJSHADOW		;UPDATE JET SHADOW

		JMP	ANIMOBJNEXT		;
NOTSJET1
		CMP	#SCHOPPER_FILE		;SCHOPPER?
		BNE	NOTSCHOPPER		;NO

		CMPW	OBJPTR,CURCHOPPER	;CURRENT CHOPPER?
		BNE	?1			;NO

		JSR	MOVECHOPPER		;MOVE CHOPPER
?1
		JSR	UPDATECSHADOW		;UPDATE CHOPPER SHADOW
		JSR	UPDATEROTORS		;UPDATE THE ROTORS

		JMP	ANIMOBJNEXT		;
NOTSCHOPPER
		CMP	#BULLET_FILE		;BULLET?
		BNE	NOTBULLET		;NO

		JSR	MOVEBULLET		;MOVE THE BULLET

		JMP	ANIMOBJNEXT		;
NOTBULLET
		CMP	#ROCKET_FILE		;ROCKET?
		BNE	NOTROCKET		;NO

		JSR	MOVEROCKET		;MOVE THE ROCKET

		JMP	ANIMOBJNEXT		;
NOTROCKET
		CMP	#MISSILE1_FILE		;MISSILE1?
		BNE	NOTMISSILE		;NO

		JSR	MOVEMISSILE		;MOVE THE MISSILE

		JMP	ANIMOBJNEXT		;
NOTMISSILE
		CMP	#SJEEP_FILE		;
		BEQ	YESJEEPTRUCK		;
		CMP	#STRUCK_FILE		;
		BNE	NOTJEEPTRUCK		;
YESJEEPTRUCK
		JSR	MOVEJEEPTRUCK		;
		JMP	ANIMOBJNEXT		;
NOTJEEPTRUCK
		CMP	#SCUD_FILE		;
		BNE	NOTASCUD		;

		JSR	MOVESCUD		;
		JMP	ANIMOBJNEXT		;
NOTASCUD
		CMP	#STARTSTARGETS		;SMART TARGETS?
		BLT	ANIMOBJNEXT		;NO

		SEC				;SET INDEX
		SBC	#STARTSTARGETS		;
		STA	COLLINDEX		;

		LDA	MISSION			;TRAINING?
		BEQ	ANIMOBJNEXT		;YES - DON'T SHOOT

		JSR	SHOOTATUS		;CHECK FOR SHOOTING
ANIMOBJNEXT
		ADDBW	#OBJUSESIZE,OBJPTR	;NEXT OBJECT USE
		JMP	ANIMOBJLOOP		;
ANIMOBJDONE
		RTS
*
* SHOOT IF IN RANGE
*
* ENTRY:
*	OBJPTR		POINTS TO SATANK1..3,OR SAABATTE
*
SHOOTATUS
		LDY	#OBJ_XROTLO		;DONE RELOADING?
		LDA	(OBJPTR),Y		;
		BEQ	?RELOADED		;YES

		DEC	A			;
		STA	(OBJPTR),Y		;
		RTS				;
?RELOADED
		LDY	#OBJ_FLAGS		;FLAGGED IN RANGE?
		LDA	(OBJPTR),Y		;
		BMI	?INRANGE		;YES

		RTS				;
?INRANGE
		MOVEIW	SPINRATE,SPINAMOUNT	;SET SPIN RATE
		MOVEIW	REGARC,ARCOFFIRE	;SET ARC OF FIRE
		JSR	TURNTOUS		;TURN TO US
		BCC	?1			;

		JSR	FIRESHOT		;SHOOT WHEN IN ARC
?1
		RTS

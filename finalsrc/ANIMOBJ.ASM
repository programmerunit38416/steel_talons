*
TURNTOUS
		LDY	#OBJ_FILE		;
		LDA	(OBJPTR),Y		;
		STA	WTYPE			;

		CLRW	WORK3			;

		LDY	#OBJ_X			;GET STARTING X,Y,Z
		LDA	(OBJPTR),Y		;
		STA	XDIFF+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		STA	XDIFF+1			;
		BPL	?1			;

		DEC	WORK3+0			;
?1
		LDA	XCOORDINATEHI		;
		BPL	?2			;

		DEC	WORK3+1			;
?2
		CLRW	WORK4			;

		LDY	#OBJ_Y			;
		LDA	(OBJPTR),Y		;
		STA	YDIFF+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		STA	YDIFF+1			;
		BPL	?3			;

		DEC	WORK4+0			;
?3
		LDA	YCOORDINATEHI		;
		BPL	?4			;

		DEC	WORK4+1			;
?4
		LDY	#OBJ_Z			;
		LDA	(OBJPTR),Y		;
		STA	ZDIFF+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		STA	ZDIFF+1			;

		LDA	XDIFF+0			;
		SEC				;
		SBC	XCOORDINATELO		;
		STA	WORK1+0			;
		LDA	XDIFF+1			;
		SBC	XCOORDINATEHI		;
		STA	WORK1+1			;

		LDA	WORK3+0			;CHECK FOR OVERFLOW
		SBC	WORK3+1			;
		BMI	?5			;
		LDA	WORK1+1			;
		BPL	?5			;

		NEGW	WORK1			;
?5
		LDA	YDIFF+0			;
		SEC				;
		SBC	YCOORDINATELO		;
		STA	WORK2+0			;
		LDA	YDIFF+1			;
		SBC	YCOORDINATEHI		;
		STA	WORK2+1			;

		LDA	WORK4+0			;CHECK FOR OVERFLOW
		SBC	WORK4+1			;
		BMI	?6			;
		LDA	WORK2+1			;
		BPL	?6			;

		NEGW	WORK2			;
?6
		JSR	CALCYAW@		;CALC THE YAW TO TARGET

		LDY	#OBJ_ZROTLO		;
		LDA	(OBJPTR),Y		;
		STA	WZROTATION+0		;
		LDY	#OBJ_ROTHI		;
		LDA	(OBJPTR),Y		;
		AND	#3			;
		STA	WZROTATION+1		;

		MOVEW	SPINAMOUNT,WORK1	;

		JSR	MODIFYZROT@		;MODIFY ZROT

		LDY	#OBJ_ZROTLO		;SET NEW ZROT
		LDA	WZROTATION+0		;
		STA	(OBJPTR),Y		;

		LDY	#OBJ_ROTHI		;
		LDA	(OBJPTR),Y		;
		AND	#%11111100		;
		ORA	WZROTATION+1		;
		STA	(OBJPTR),Y		;

		CMPW	ARCOFFIRE,WORK2		;IN ARC OF FIRE?
		BGE	?SKIPSHOT		;NO

		SEC				;IN ARC
		RTS				;
?SKIPSHOT
		CLC				;NOT IN ARC
		RTS				;

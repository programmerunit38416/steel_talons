		LDY	#OBJ_XROTLO		;SET RELOAD DELAY
		LDA	#RELOADTIME		;
		STA	(OBJPTR),Y		;

		PUSHW	TARGETPTR		;SAVE POINTER
;;NEW 04/30/92
		MOVEW	POSPTR,TARGETPTR	;AIM AT US

		LDY	#OBJ_X			;SET SOURCE OF BULLET
		LDA	(OBJPTR),Y		;
		STA	XDIFF+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		STA	XDIFF+1			;

		LDY	#OBJ_Y			;
		LDA	(OBJPTR),Y		;
		STA	YDIFF+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		STA	YDIFF+1			;

		LDY	#OBJ_Z			;
		LDA	(OBJPTR),Y		;
		STA	ZDIFF+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		STA	ZDIFF+1			;

		LDY	#OBJ_FILE		;SET TYPE
		LDA	(OBJPTR),Y		;
		STA	WHOSHOT			;
;;NEW 04/30/92
		STA	WTYPE			;

		JSR	ADDBULLET@		;FIRE THE BULLET

		POPW	TARGETPTR		;

		RTS
*
* TURN TOWARD US
*
*
* ENTRY:
*	OBJPTR		POINTER TO ENEMY
*	SPINAMOUNT	MAX DELTA YAW

HISCORE
		STA	HSCOREFLAG		;SAVE PARAMETER

		LDA	HSCOREFLAG		;CHECK HIGH SCORE?
		CMP	#00			;
		BNE	?ENTERING		;
		JMP	JUSTSHOW		;
?ENTERING
		JSR	CHECKNEWHIGH		;NEW HIGH SCORE?
		BCS	?NEWHIGH		;YES

		JMP	HSCOREDONE		;
?NEWHIGH
		INITHMUSIC			;STOP MUSIC

		LDA	#INITIALDNL_FILE	;LOAD HISCORE SCREEN MUSIC
		GETDIR				;GET DIRECTORY ENTRY
		MYOPENFILE			;OPEN THE FILE
		LDA	#1			;DEST ADDRESS
		LDX	#<SPRBUFFER		;
		LDY	#>SPRBUFFER		;
		READFILE			;READ THE FILE

		LDA	#<SPRBUFFER		;START THE MUSIC
		LDX	#>SPRBUFFER		;
		PLAYMUSIC			;

		MOVEIW	ENTERT.BBMDATA,HSCORESPR2+IMAGEDATA
		MOVEIB	40,HSCORESPR2+HPOS
		MOVEIW	ENTERB.BBMDATA,HSCORESPR3+IMAGEDATA
		MOVEIB	3,HSCORESPR3+HPOS

		PUSHW	SRCPTR			;
		PUSHW	DSTPTR			;
		JSR	SETUPHSBUFF		;SET UP BUFFER
		POPW	DSTPTR			;
		POPW	SRCPTR			;

		PUSHW	DSTPTR			;

		LDX	#23			;23 CHARACTERS
		LDY	#PALETTE-8		;
?SETCOLORLOOP
		LDA	#$07			;BLUE
		STA	(DSTPTR),Y		;

		ADDBW	#13,DSTPTR		;
		DEX				;
		BNE	?SETCOLORLOOP		;

		POPW	DSTPTR			;

		LEA	HSCORESPR1,FIRSTSPRITE	;POINT TO LIST

		MYSPRITES			;DRAW SPRITES

		MYDBUF_DISPLAY			;"PAGE FLIP"
		MYWAITEOF			;
		MYRGB16	HSCOREPAL		;UPDATE PALETTE

		STZ	HSCOREINDEX		;INIT INDEXES
		STZ	HSCORECHAR		;
		STZ	REPEATDELAY		;INIT REPEAT DELAY
		STZ	ANIMHSCORE		;
?ENTERNAMELOOP
		JSR	SHOWCURRENT		;

		LDA	ANIMHSCORE		;
		INC	A			;
		AND	#15			;
		STA	ANIMHSCORE		;

		MYSPRITES			;DRAW SPRITES
		MYDBUF_DISPLAY			;"PAGE FLIP"
		MYWAITEOF			;

		JSR	GETJOY@			;READ CONTROLLER

		JSR	CHECKOTHERFLAGS@	;CHECK FLAGS FOR SPECIAL INPUT
		JSR	SELCHECKPAUSED@		;SELECT CHECK FOR PAUSE REQUEST

		LDA	DJOYVALUE		;GET DEBOUNCED
		BIT	#OPTION1_BUTTON		;OPTION1?
		BNE	?YESOPT12		;YES
		BIT	#OPTION2_BUTTON		;OPTION2?
		BEQ	?NOTOPT12		;NO
?YESOPT12
		MOVEIB	26,HSCORECHAR		;BLANK OUT LAST CHAR
		JSR	SHOWCURRENT		;
		JMP	?ENTERNAMEDONE		;
?NOTOPT12
		BIT	#B_BUTTON		;B BUTTON?
		BEQ	?NOTB			;NO
		LDA	HSCOREINDEX		;
		BEQ	?NOTB			;

		STZ	ANIMHSCORE		;
		PUSHB	HSCORECHAR		;
		MOVEIB	26,HSCORECHAR		;
		JSR	SHOWCURRENT		;
		POPB	HSCORECHAR		;
		DEC	HSCOREINDEX		;
		SUBBW	#13,DSTPTR		;
?NOTB
		LDA	DJOYVALUE		;GET DEBOUNCED
		BIT	#A_BUTTON		;A BUTTON?
		BEQ	?NOTA			;NO

		LDA	HSCOREINDEX		;
		CMP	#15			;
		BGE	?ENTERNAMEDONE		;

		STZ	ANIMHSCORE		;
		JSR	SHOWCURRENT		;
		INC	HSCOREINDEX		;ADVANCE POSITION
		ADDBW	#13,DSTPTR		;

		LDX	#MISSILE_SOUND		;FIRE OFF A MISSILE
		JSR	STARTSOUND@		;
?NOTA
		LDA	REPEATDELAY		;DELAY BEFORE REPEATING
		BEQ	?GETINPUT		;

		DEC	REPEATDELAY		;
		BRA	?NOTRIGHT		;
?GETINPUT
		LDA	JOYVALUE		;UNDEBOUNCED LEFT
		BIT	#JOY_LEFT		;
		BEQ	?NOTLEFT		;
		LDA	HSCORECHAR		;
		BEQ	?NOTLEFT		;

		DEC	HSCORECHAR		;
		MOVEIB	RREPEATDELAY,REPEATDELAY
?NOTLEFT
		LDA	JOYVALUE		;UNDEBOUNCED RIGHT
		BIT	#JOY_RIGHT		;
		BEQ	?NOTRIGHT		;
		CMPIB	MAXHSCORECHAR,HSCORECHAR
		BGE	?NOTRIGHT		;

		INC	HSCORECHAR		;
		MOVEIB	RREPEATDELAY,REPEATDELAY
?NOTRIGHT
		JMP	?ENTERNAMELOOP		;
?ENTERNAMEDONE
		LDX	#30			;SHORT DELAY
?ENDONELOOP
		MYWAITEOF			;
		DEX				;
		BNE	?ENDONELOOP		;

		JMP	HSCOREDONE		;
*
* SHOW CURRENT CHAR
*
SHOWCURRENT
		LDX	HSCORECHAR		;UPDATE CHARACTER
		LDA	HSCORECHARS,X		;
		LDY	HSCOREINDEX		;
		STA	(SRCPTR),Y		;

		LDX	ANIMHSCORE		;
		CPX	#8			;
		BLT	?SHOWIT			;

		LDA	#" "			;
?SHOWIT
		JMP	DISPHSCHAR		;
*
* JUST SHOW HIGH SCORE
*
JUSTSHOW
		MOVEIW	SHOWT.BBMDATA,HSCORESPR2+IMAGEDATA
		MOVEIB	49,HSCORESPR2+HPOS
		MOVEIW	SHOWB.BBMDATA,HSCORESPR3+IMAGEDATA
		MOVEIB	15,HSCORESPR3+HPOS

		JSR	SETUPHSBUFF		;SET UP BUFFER

		LEA	HSCORESPR1,FIRSTSPRITE	;POINT TO LIST

		MYSPRITES			;DRAW SPRITES

		MYDBUF_DISPLAY			;"PAGE FLIP"
		MYWAITEOF			;
		MYRGB16	HSCOREPAL		;UPDATE PALETTE

		LDX	#15			;SHORT DELAY
?HISCOREWAITLOOP
		MYWAITEOF			;
		DEX				;
		BNE	?HISCOREWAITLOOP	;

		MOVEIW	5*60,ATRACTTIMER	;5 SECONDS
?HSCORESHOWLOOP
		MYWAITEOF			;WAIT FOR JIFFY COUNTER TO CHANGE
		JSR	GETJOY@			;READ CONTROLLER

		LDA	JOYVALUE		;GET UNDEBOUNCED

		BIT	#B_BUTTON		;B BUTTON PRESSED?
		BNE	HSCOREDONE		;YES
		BIT	#A_BUTTON		;A BUTTON PRESSED?
		BNE	HSCOREDONE		;YES

		JSR	CHECKOTHERFLAGS@	;CHECK FLAGS FOR SPECIAL INPUT
		JSR	SELCHECKPAUSED@		;SELECT CHECK FOR PAUSE REQUEST

		DECW	ATRACTTIMER		;DECREMENT TIMER

		LDA	ATRACTTIMER+0		;TIMED OUT?
		ORA	ATRACTTIMER+1		;
		BNE	?HSCORESHOWLOOP		;NO
HSCOREDONE
		PHP				;
		JSR	FADEBLACK@		;FADE TO BLACK (COLOR 0)
		PLP				;

		RTS
*
* CHECK FOR NEW HIGH SCORE
*
* EXIT:
*	CARRY CLEAR - NOT NEW HIGH SCORE
*	CARRY SET - NEW HIGH SCORE
*		SRCPTR - POINTER TO CHARACTERS IN HIGHSCORES
*		DSTPTR - POINTER TO SCBS IN HSCOREBUFF
*
CHECKNEWHIGH
		LEA	(HSCOREBUFF+(9*23*13)),DSTPTR
		LEA	(HIGHSCORES+(9*23)),SRCPTR
		LEA	(HIGHSCORES+(10*23)),WRKPTR

		LDX	#10			;10 ENTRIES
?NEWHIGHLOOP
		LDY	#16			;
?CHECKONELOOP
		CPY	#23			;
		BGE	?CHECKINDEX		;

		LDA	(SRCPTR),Y		;
		CMP	SCORE-16,Y		;
		BEQ	?CHECKONENEXT		;
		BLT	?MOVEUP			;
		BGE	?CHECKINDEX		;
?CHECKONENEXT
		INY				;
		BRA	?CHECKONELOOP		;
?MOVEUP
		LDY	#22			;COPY THIS NAME TO SLOT BELOW
?1
		LDA	(SRCPTR),Y		;
		STA	(WRKPTR),Y		;
		DEY				;
		BPL	?1			;

		SUBIW	(23*13),DSTPTR		;
		SUBBW	#23,SRCPTR		;
		SUBBW	#23,WRKPTR		;

		DEX				;
		BNE	?NEWHIGHLOOP		;
?CHECKINDEX
		ADDIW	(23*13),DSTPTR		;
		ADDBW	#23,SRCPTR		;

		CPX	#10			;IN TOP TEN?
		BEQ	?NOTTOPTEN		;NO

		LDY	#00			;CLEAR NAME
		LDA	#" "			;
?CLEARLOOP
		CPY	#16			;
		BGE	?MOVEINLOOP		;

		STA	(SRCPTR),Y		;
		INY				;
		BRA	?CLEARLOOP		;
?MOVEINLOOP
		CPY	#23			;COPY SCORE IN
		BGE	?MOVEINDONE		;

		LDA	SCORE-16,Y		;
		STA	(SRCPTR),Y		;
		INY				;
		BRA	?MOVEINLOOP		;
?MOVEINDONE
		SEC				;IN TOP TEN
		RTS				;
?NOTTOPTEN
		CLC				;NOT IN TOP TEN
		RTS				;
*
* SET UP HSCORE BUFF
*
SETUPHSBUFF
		LEA	HIGHSCORES,SRCPTR	;POINT TO HIGH SCORES

		LEA	HSCOREBUFF,DSTPTR	;
		MOVEIB	10,COUNTER1		;10 ENTRIES
		MOVEIB	13,WORK2		;STARTING VPOS
?SETUPENTRYLOOP
		MOVEIB	16,COUNTER2		;16 CHARACTER NAME
		MOVEIB	6,WORK1			;STARTING HPOS
?SETUPNAMELOOP
		JSR	INITSCBPARTS		;INIT SCB

		LDA	(SRCPTR)		;GET CHARACTER
		JSR	DISPHSCHAR		;

		ADDBW	#13,DSTPTR		;NEXT CHARACTER
		ADDIB	5,WORK1			;
		INCW	SRCPTR			;
		DEC	COUNTER2		;
		BNE	?SETUPNAMELOOP		;

		ADDIB	5,WORK1			;SKIP A SPACE

		MOVEIB	7,COUNTER2		;7 DIGIT SCORE
		STZ	WORK3			;INIT FLAG
?SETUPSCORELOOP
		JSR	INITSCBPARTS		;INIT SCB

		LDA	(SRCPTR)		;GET CHARACTER
		CLC				;
		ADC	#"0"			;

		LDX	WORK3			;SKIP LEADING ZEROES
		BNE	?2			;
		LDX	COUNTER2		;
		CPX	#1			;
		BEQ	?2			;

		CMP	#"0"			;
		BEQ	?1			;

		INC	WORK3			;
		BRA	?2			;
?1
		LDA	#" "			;
?2
		JSR	DISPHSCHAR		;

		ADDBW	#13,DSTPTR		;NEXT CHARACTER
		ADDIB	5,WORK1			;
		INCW	SRCPTR			;
		DEC	COUNTER2		;
		BNE	?SETUPSCORELOOP		;

		ADDIB	7,WORK2			;NEXT ENTRY

		DEC	COUNTER1		;
		BEQ	?3			;
		JMP	?SETUPENTRYLOOP		;
?3
		SUBBW	#13,DSTPTR		;LINK TO PAUSED SPRITE

		LDY	#NEXTSPRITE+0		;
		LDA	#<PAUSEDSPR		;
		STA	(DSTPTR),Y		;
		INY				;
		LDA	#>PAUSEDSPR		;
		STA	(DSTPTR),Y		;

		RTS
*
* DISPLAY HIGH SCORE CHARACTER
*
DISPHSCHAR
		CMP	#" " 			;SPACE?
		BNE	?NOTSPACE		;NO

		LDY	#CONTROL1		;SKIP THIS CHAR
		LDA	(DSTPTR),Y		;
		ORA	#SKIP_SPRITE		;
		STA	(DSTPTR),Y		;

		RTS
?NOTSPACE
		CMP	#"9"+1			;NUMBER?
		BGE	?ITSALPHA		;NO

		SEC				;USE DIGITS
		SBC	#"0"			;
		TAX				;

		LDY	#IMAGEDATA+0		;
		LDA	XDIGITLO,X		;
		STA	(DSTPTR),Y		;
		INY				;
		LDA	XDIGITHI,X		;
		STA	(DSTPTR),Y		;

		LDY	#CONTROL1		;SHOW THIS CHAR
		LDA	(DSTPTR),Y		;
		AND	#\SKIP_SPRITE		;
		STA	(DSTPTR),Y		;

		RTS
?ITSALPHA
		SEC				;USE CHARS
		SBC	#"A"			;
		TAX				;

		LDY	#IMAGEDATA+0		;
		LDA	ALPHALO,X		;
		STA	(DSTPTR),Y		;
		INY				;
		LDA	ALPHAHI,X		;
		STA	(DSTPTR),Y		;

		LDY	#CONTROL1		;SHOW THIS CHAR
		LDA	(DSTPTR),Y		;
		AND	#\SKIP_SPRITE		;
		STA	(DSTPTR),Y		;

		RTS
*
* INIT PARTS OF SCB
*
INITSCBPARTS
		LDY	#CONTROL0		;
		LDA	#TWO_PER_PIXEL+NORMAL_SPRITE
		STA	(DSTPTR),Y		;

		LDY	#CONTROL1		;
		LDA	#RELOAD_NONE		;
		STA	(DSTPTR),Y		;

		LDY	#CONTROL2		;
		LDA	#00			;
		STA	(DSTPTR),Y		;

		LDY	#NEXTSPRITE+0		;
		LDA	DSTPTR+0		;
		CLC				;
		ADC	#13			;
		STA	(DSTPTR),Y		;
		INY				;
		LDA	DSTPTR+1		;
		ADC	#00			;
		STA	(DSTPTR),Y		;

		LDY	#HPOS+0			;
		LDA	WORK1			;
		STA	(DSTPTR),Y		;
		INY				;
		LDA	#00			;
		STA	(DSTPTR),Y		;

		LDY	#VPOS+0			;
		LDA	WORK2			;
		STA	(DSTPTR),Y		;
		INY				;
		LDA	#00			;
		STA	(DSTPTR),Y		;

		LDY	#PALETTE-8		;
		LDA	#$0F			;
		STA	(DSTPTR),Y		;
		INY				;
		LDA	#$00			;
		STA	(DSTPTR),Y		;

		RTS

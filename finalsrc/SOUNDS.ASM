		.BYTE	SOUND_STARTING	;FLAG
*
EXTRA2SOUND	.BYTE	$FF		;PRIORITY
		.BYTE	$00+$80+$00	;CONTROL : OCTAVE+FEEDBACK 7+INTEGRATE
		.BYTE	$FF,$F0		;SHIFT INIT
		.BYTE	$00		;FEEDBACK
		.BYTE	4		;NUMBER OF UPDATES
		.BYTE	0		;CURRENT COUNTER TO VBS BETWEEN UPDATES
		.BYTE	0		;VBS BETWEEN UPDATES
		.WORD	$8C00		;FREQUENCY
		.WORD	$0000		;DELTA TO FREQUENCY
		.WORD	$0000		;DELTA TO FREQUENCY DELTA
		.WORD	$5F00		;VOLUME
		.WORD	$F800		;DELTA TO VOLUME
		.WORD	$0040		;DELTA TO VOLUME DELTA
		.BYTE	EXTRA3_SOUND	;CHAIN TO SOUND # WHEN COMPLETE
		.BYTE	SOUND_STARTING	;FLAG
*
EXTRA3SOUND	.BYTE	$FF		;PRIORITY
		.BYTE	$00+$80+$00	;CONTROL : OCTAVE+FEEDBACK 7+INTEGRATE
		.BYTE	$FF,$F0		;SHIFT INIT
		.BYTE	$00		;FEEDBACK
		.BYTE	30		;NUMBER OF UPDATES
		.BYTE	0		;CURRENT COUNTER TO VBS BETWEEN UPDATES
		.BYTE	0		;VBS BETWEEN UPDATES
		.WORD	$6000		;FREQUENCY
		.WORD	$0000		;DELTA TO FREQUENCY
		.WORD	$0000		;DELTA TO FREQUENCY DELTA
		.WORD	$5F00		;VOLUME
		.WORD	$FC00		;DELTA TO VOLUME
		.WORD	$0020		;DELTA TO VOLUME DELTA
		.BYTE	$FF		;CHAIN TO SOUND # WHEN COMPLETE
		.BYTE	SOUND_STARTING	;FLAG
*
* SOUND EFFECT NUMBER EQUATES
*
DOINK_SOUND	EQU	0		;
EXPLODE_SOUND	EQU	1		;
SIGNBEND_SOUND	EQU	2		;
LANDING_SOUND	EQU	3		;
LANDING2_SOUND	EQU	4		;
EXTRA_SOUND	EQU	5		;
EXTRA2_SOUND	EQU	6		;
EXTRA3_SOUND	EQU	7		;
BIGHIT_SOUND	EQU	8		;
STARTB_SOUND	EQU	9		;
SHIFT_SOUND	EQU	10		;
OFFROAD_SOUND	EQU	11		;
EXPLODE_SOUND2	EQU	12		;
*
* SOUND EFFECT ADDRESSES
*
SOUNDSLO	.BYTE	<DOINKSOUND,<EXPLODESOUND,<SIGNBENDSOUND,<LANDINGSOUND
		.BYTE	<LANDING2SOUND,<EXTRASOUND,<EXTRA2SOUND,<EXTRA3SOUND
		.BYTE	<LANDING2SOUND,<STARTBSOUND,<SHIFTSOUND,<OFFROADSOUND
		.BYTE	<EXPLODESOUND2
SOUNDSHI	.BYTE	>DOINKSOUND,>EXPLODESOUND,>SIGNBENDSOUND,>LANDINGSOUND
		.BYTE	>LANDING2SOUND,>EXTRASOUND,>EXTRA2SOUND,>EXTRA3SOUND
		.BYTE	>LANDING2SOUND,>STARTBSOUND,>SHIFTSOUND,>OFFROADSOUND
		.BYTE	>EXPLODESOUND2
*
* START A SOUND EFFECT
*
* ENTRY:
*	X REG	SOUND EFFECT NUMBER
*
STARTSOUND@
		LDA	SOUNDSLO,X		;POINT TO SOUND
		STA	WRKPTR+0		;
		LDA	SOUNDSHI,X		;
		STA	WRKPTR+1		;

		LDX	#00			;INIT SOUND BUFFER INDEX
STARTSOUNDLOOP
		CPX	#(2*SOUND_LENGTH)	;DONE?
		BGE	STARTSOUNDDONE		;YES - PRIORITY NOT HIGH ENOUGH

		LDA	SOUNDFLAGS,X		;SOUND ACTIVE?
		CMP	#SOUND_OFF		;
		BEQ	INITTHESOUND		;NO - USE THIS CHANNEL
		CMP	#SOUND_STOPPING		;SOUND ENDING?
		BEQ	INITTHESOUND		;YES - USE THIS CHANNEL

		LDA	SOUND0FLAG		;ANY OTHER CHANNELS OPEN?
		AND	SOUND1FLAG		;
		BEQ	STARTSOUNDNEXT		;YES

		LDY	#_PRIORITY		;CHECK PRIORITIES
		LDA	(WRKPTR),Y		;
		CMP	SOUNDBUFFS,X		;
		BLT	STARTSOUNDNEXT		;
INITTHESOUND
		LDA	#SOUND_STOPPING		;STOP OLD SOUND
		STA	SOUNDFLAGS,X		;

		LDY	#00			;INIT BUFFER
INITSOUNDLOOP
		CPY	#SOUND_LENGTH		;DONE?
		BGE	INITSOUNDDONE		;YES

		LDA	(WRKPTR),Y		;COPY DATA
		STA	SOUNDBUFFS,X		;

		INX				;ALSO WILL SET FLAG
		INY				;
		BRA	INITSOUNDLOOP		;
INITSOUNDDONE
		BRA	STARTSOUNDDONE		;
STARTSOUNDNEXT
		TXA				;NEXT SOUND
		CLC				;
		ADC	#SOUND_LENGTH		;
		TAX				;
		BRA	STARTSOUNDLOOP		;
STARTSOUNDDONE
		RTS
*
* STOP ALL SOUND EFFECTS (THROUGH SOFTWARE STATUS)
*
STOPSOUNDS@
		LDA	SOUND0FLAG		;SOUND OFF?
		BEQ	?1			;YES

		LDA	#SOUND_STOPPING		;NO - SET FLAG TO STOP IT
		STA	SOUND0FLAG		;
?1
		LDA	SOUND1FLAG		;SOUND OFF?
		BEQ	?2			;YES

		LDA	#SOUND_STOPPING		;NO - SET FLAG TO STOP IT
		STA	SOUND1FLAG		;
?2
		RTS
*
* INIT SOUNDS (CALL AT RESET)
*
INITSOUNDS@
		LDA	#SOUND_OFF		;INIT FLAGS
		STA	SOUND0FLAG		;
		STA	SOUND1FLAG		;

		LDA	#00			;CLEAR HARDWARE VOLUMES
		STA	AUDIO0+VOLCNTRL		;
		STA	AUDIO0+OUTPUT		;
		STA	AUDIO1+VOLCNTRL		;
		STA	AUDIO1+OUTPUT		;

		LDA	AUDIO0+CONTROL		;DISABLE RELOAD AND COUNT
		AND	#\$18			;
		STA	AUDIO0+CONTROL		;
		LDA	AUDIO1+CONTROL		;
		AND	#\$18			;
		STA	AUDIO1+CONTROL		;

		RTS
*
* PLAY SOUNDS (CALL DURING VERTICAL BLANK)
*
PLAYSOUNDS@
		CMPIB	TRUE,PAUSEDFLAG		;PAUSED?
		BNE	PS_NOTPAUSED		;NO

		RTS				;JUST EXIT
PS_NOTPAUSED
		LDX	#00			;INIT RAM SOUND BUFFER INDEX
		LDY	#00			;INIT HARDWARE "BUFFER" INDEX
PLAYSOUNDSLOOP
		CPX	#(2*SOUND_LENGTH)	;DONE?
		BLT	PLAYSOUNDSCONT		;NO - CONTINUE

		RTS				;YES - EXIT
PLAYSOUNDSCONT
		LDA	SOUNDFLAGS,X		;GET SOUND CHANNEL STATUS

		CMP	#SOUND_OFF		;SOUND ACTIVE?
		BNE	PS_NOTOFF		;YES

		JMP	PLAYSOUNDSNEXT		;NEXT CHANNEL
PS_NOTOFF
		CMP	#SOUND_STARTING		;JUST STARTING?
		BEQ	PS_STARTING		;YES
		JMP	PS_NOTSTARTING		;
PS_STARTING
		LDA	AUDIOBUFFS+CONTROL,Y	;SHUT OLD SOUND OFF FIRST
		AND	#\$18			;
		STA	AUDIOBUFFS+CONTROL,Y	;

		LDA	SOUNDBUFFS+_VBRELOAD,X	;INIT VBCOUNTER
		STA	SOUNDBUFFS+_VBCOUNTER,X	;

		LDA	SOUNDBUFFS+_SHIFT1,X	;INIT SHIFT REGISTER
		STA	AUDIOBUFFS+SHIFT,Y	;
		LDA	AUDIOBUFFS+OTHER,Y	;
		AND	#$0F			;
		ORA	SOUNDBUFFS+_SHIFT2,X	;
		STA	AUDIOBUFFS+OTHER,Y	;

		LDA	SOUNDBUFFS+_FEEDBACK,X	;INIT FEEDBACK REGISTER
		STA	AUDIOBUFFS+FEEDBACK,Y	;

		LDA	SOUNDBUFFS+_VOLUME+1,X	;INIT VOLUME
		STA	AUDIOBUFFS+VOLCNTRL,Y	;
		STA	AUDIOBUFFS+OUTPUT,Y	;

		LDA	SOUNDBUFFS+_FREQ+1,X	;INIT FREQUENCY
		STA	AUDIOBUFFS+BACKUP,Y	;
		STA	AUDIOBUFFS+COUNTER,Y	;

		LDA	SOUNDBUFFS+_CONTROL,X	;INIT CONTROL
		ORA	#$18			;ENABLE RELOAD AND COUNT
		STA	AUDIOBUFFS+CONTROL,Y	;

		LDA	#SOUND_RUNNING		;SET TO RUNNING
		STA	SOUNDFLAGS,X		;
		JMP	PLAYSOUNDSNEXT		;NEXT CHANNEL
PS_NOTSTARTING
		CMP	#SOUND_RUNNING		;RUNNING?
		BEQ	PS_RUNNING		;YES
		JMP	PS_NOTRUNNING		;
PS_RUNNING
		LDA	SOUNDBUFFS+_VBCOUNTER,X	;TIME TO UPDATE?
		BEQ	PS_UPDATE		;YES

		DEC	A			;NO - JUST DECREMENT COUNTER
		STA	SOUNDBUFFS+_VBCOUNTER,X	;
		JMP	PLAYSOUNDSNEXT		;NEXT CHANNEL
PS_UPDATE
		LDA	SOUNDBUFFS+_UPDATES,X	;MORE UPDATES REMAINING?
		BNE	PS_MUPDATES		;YES

		LDA	SOUNDBUFFS+_CHAIN,X	;NEED TO CHAIN?
		CMP	#$FF			;
		BEQ	PS_NOCHAIN		;NO

		PUSHW	WRKPTR			;SAVE ZERO PAGE POINTER
		PHX				;SAVE INDEXES
		PHY				;

		LDA	SOUNDBUFFS+_CHAIN,X	;INIT THE CHAINED TO SOUND
		TAY				;
		LDA	SOUNDSLO,Y		;
		STA	WRKPTR+0		;
		LDA	SOUNDSHI,Y		;
		STA	WRKPTR+1		;

		JSR	INITTHESOUND		;

		PLY				;RESTORE INDEXES
		PLX				;
		POPW	WRKPTR			;RESTORE ZERO PAGE POINTER
		JMP	PS_STARTING		;AND START THIS CHAINED SOUND
PS_NOCHAIN
		JMP	PS_STOPPING		;END THE SOUND
PS_MUPDATES
		CMP	#$FF			;CONTINUOUS?
		BEQ	PS_CONTINUOUS		;YES

		DEC	A			;DECREMENT UPDATES REMAINING
		STA	SOUNDBUFFS+_UPDATES,X	;
PS_CONTINUOUS
		LDA	SOUNDBUFFS+_VBRELOAD,X	;RELOAD VBCOUNTER
		STA	SOUNDBUFFS+_VBCOUNTER,X	;

		LDA	SOUNDBUFFS+_DVOLUME+0,X	;APPLY DELTA TO DELTA IF ANY
		CLC				;
		ADC	SOUNDBUFFS+_DDVOLUME+0,X
		STA	SOUNDBUFFS+_DVOLUME+0,X	;
		LDA	SOUNDBUFFS+_DVOLUME+1,X	;
		ADC	SOUNDBUFFS+_DDVOLUME+1,X
		STA	SOUNDBUFFS+_DVOLUME+1,X	;

		LDA	SOUNDBUFFS+_DVOLUME+0,X	;CHANGE IN VOLUME?
		ORA	SOUNDBUFFS+_DVOLUME+1,X	;
		BNE	PS_NEWVOL		;YES
		JMP	PS_SKIPVOL		;NO
PS_NEWVOL
		LDA	SOUNDBUFFS+_DVOLUME+1,X	;CHECK SIGN FOR CLIPPING
		BPL	PS_POSVOL		;

		LDA	SOUNDBUFFS+_VOLUME+0,X	;APPLY NEG DELTA
		CLC				;
		ADC	SOUNDBUFFS+_DVOLUME+0,X	;
		STA	SOUNDBUFFS+_VOLUME+0,X	;
		LDA	SOUNDBUFFS+_VOLUME+1,X	;
		ADC	SOUNDBUFFS+_DVOLUME+1,X	;
		STA	SOUNDBUFFS+_VOLUME+1,X	;
		BCS	?1			;

		LDA	#$00			;CLIP AT $0000
		STA	SOUNDBUFFS+_VOLUME+0,X	;
		STA	SOUNDBUFFS+_VOLUME+1,X	;
?1
		BRA	PS_SETNEWVOL		;
PS_POSVOL
		LDA	SOUNDBUFFS+_VOLUME+0,X	;APPLY POS DELTA
		CLC				;
		ADC	SOUNDBUFFS+_DVOLUME+0,X	;
		STA	SOUNDBUFFS+_VOLUME+0,X	;
		LDA	SOUNDBUFFS+_VOLUME+1,X	;
		ADC	SOUNDBUFFS+_DVOLUME+1,X	;
		STA	SOUNDBUFFS+_VOLUME+1,X	;
		BMI	?1			;
		BCC	PS_SETNEWVOL		;
?1
		LDA	#$7F			;CLIP AT $7FFF
		STA	SOUNDBUFFS+_VOLUME+0,X	;
		LDA	#$FF			;
		STA	SOUNDBUFFS+_VOLUME+1,X	;
PS_SETNEWVOL
		LDA	SOUNDBUFFS+_VOLUME+1,X	;SET NEW VOLUME
		STA	AUDIOBUFFS+VOLCNTRL,Y	;
PS_SKIPVOL
		LDA	SOUNDBUFFS+_DFREQ+0,X	;APPLY DELTA TO DELTA IF ANY
		CLC				;
		ADC	SOUNDBUFFS+_DDFREQ+0,X	;
		STA	SOUNDBUFFS+_DFREQ+0,X	;
		LDA	SOUNDBUFFS+_DFREQ+1,X	;
		ADC	SOUNDBUFFS+_DDFREQ+1,X	;
		STA	SOUNDBUFFS+_DFREQ+1,X	;

		LDA	SOUNDBUFFS+_DFREQ+1,X	;CHANGE IN FREQUENCY?
		ORA	SOUNDBUFFS+_DFREQ+0,X	;
		BNE	PS_NEWFREQ		;YES
		JMP	PS_SKIPFREQ		;NO
PS_NEWFREQ
		MOVEIB	FALSE,PS_WORK		;INIT FLAG FOR NEW OCTAVE

		LDA	SOUNDBUFFS+_DFREQ+1,X	;CHECK FOR SIGN FOR CLIPPING
		BPL	PS_POSDFREQ		;

		LDA	SOUNDBUFFS+_FREQ+0,X	;APPLY NEG DELTA
		CLC				;
		ADC	SOUNDBUFFS+_DFREQ+0,X	;
		STA	SOUNDBUFFS+_FREQ+0,X	;
		LDA	SOUNDBUFFS+_FREQ+1,X	;
		ADC	SOUNDBUFFS+_DFREQ+1,X	;
		STA	SOUNDBUFFS+_FREQ+1,X	;
		BCS	?2			;

		LDA	SOUNDBUFFS+_CONTROL,X	;AT LOWEST OCTAVE?
		AND	#7			;
		BNE	?1			;NO

		LDA	#$00			;CLIP AT $00
		STA	SOUNDBUFFS+_FREQ+0,X	;
		STA	SOUNDBUFFS+_FREQ+1,X	;
		BRA	?2			;
?1
		DEC	A			;LOWER OCTAVE
		STA	PS_WORK			;

		LDA	SOUNDBUFFS+_CONTROL,X	;
		AND	#$F8			;
		ORA	PS_WORK			;
		STA	SOUNDBUFFS+_CONTROL,X	;

		ASL	SOUNDBUFFS+_FREQ+0,X	;DOUBLE FREQUENCIES
		ROL	SOUNDBUFFS+_FREQ+1,X	;
		ASL	SOUNDBUFFS+_DFREQ+0,X	;
		ROL	SOUNDBUFFS+_DFREQ+1,X	;
		ASL	SOUNDBUFFS+_DDFREQ+0,X	;
		ROL	SOUNDBUFFS+_DDFREQ+1,X	;

		MOVEIB	TRUE,PS_WORK		;SET FLAG FOR NEW OCTAVE
?2
		BRA	PS_SETNEWFREQ		;
PS_POSDFREQ
		LDA	SOUNDBUFFS+_FREQ+0,X	;APPLY POS DELTA
		CLC				;
		ADC	SOUNDBUFFS+_DFREQ+0,X	;
		STA	SOUNDBUFFS+_FREQ+0,X	;
		LDA	SOUNDBUFFS+_FREQ+1,X	;
		ADC	SOUNDBUFFS+_DFREQ+1,X	;
		STA	SOUNDBUFFS+_FREQ+1,X	;
		BCC	PS_SETNEWFREQ		;

		LDA	SOUNDBUFFS+_CONTROL,X	;AT HIGHEST OCTAVE?
		AND	#7			;
		CMP	#6			;
		BLT	?1			;NO

		LDA	#$FF			;CLIP AT $FF
		STA	SOUNDBUFFS+_FREQ+0,X	;
		STA	SOUNDBUFFS+_FREQ+1,X	;
		BRA	PS_SETNEWFREQ		;
?1
		INC	A			;HIGHER OCTAVE
		STA	PS_WORK			;

		LDA	SOUNDBUFFS+_CONTROL,X	;
		AND	#$F8			;
		ORA	PS_WORK			;
		STA	SOUNDBUFFS+_CONTROL,X	;

		SEC				;HALVE FREQUENCIES
		ROR	SOUNDBUFFS+_FREQ+1,X	;
		ROR	SOUNDBUFFS+_FREQ+0,X	;
		LDA	SOUNDBUFFS+_DFREQ+1,X	;
		ASL	A			;
		ROR	SOUNDBUFFS+_DFREQ+1,X	;
		ROR	SOUNDBUFFS+_DFREQ+0,X	;
		LDA	SOUNDBUFFS+_DDFREQ+1,X	;
		ASL	A			;
		ROR	SOUNDBUFFS+_DDFREQ+1,X	;
		ROR	SOUNDBUFFS+_DDFREQ+0,X	;

		MOVEIB	TRUE,PS_WORK		;SET FLAG FOR NEW OCTAVE
PS_SETNEWFREQ
		LDA	SOUNDBUFFS+_FREQ+1,X	;SET NEW FREQUENCY
		STA	AUDIOBUFFS+BACKUP,Y	;

		CMPIB	TRUE,PS_WORK		;NEED NEW OCTAVE?
		BNE	PS_SKIPFREQ		;NO

		LDA	SOUNDBUFFS+_CONTROL,X	;SET NEW CONTROL (OCTAVE)
		ORA	#$18			;ENABLE RELOAD AND COUNT
		STA	AUDIOBUFFS+CONTROL,Y	;
PS_SKIPFREQ
		JMP	PLAYSOUNDSNEXT		;NEXT CHANNEL
PS_NOTRUNNING
		CMP	#SOUND_STOPPING		;STOPPING?
		BEQ	PS_STOPPING		;YES
		JMP	PS_NOTENDING		;
PS_STOPPING
		LDA	#SOUND_OFF		;SET STATUS TO OFF
		STA	SOUNDFLAGS,X		;

		LDA	#00			;CLEAR HARDWARE VOLUME
		STA	AUDIOBUFFS+VOLCNTRL,Y	;
		STA	AUDIOBUFFS+OUTPUT,Y	;

		LDA	AUDIOBUFFS+CONTROL,Y	;DISABLE RELOAD AND COUNT
		AND	#\$18			;
		STA	AUDIOBUFFS+CONTROL,Y	;
		JMP	PLAYSOUNDSNEXT		;
PS_NOTENDING
PLAYSOUNDSNEXT
		TXA				;NEXT SOUND
		CLC				;
		ADC	#SOUND_LENGTH		;
		TAX				;
		TYA				;
		CLC				;
		ADC	#08			;
		TAY				;
		JMP	PLAYSOUNDSLOOP		;
	ENDIF

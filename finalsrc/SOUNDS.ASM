		CMPIB	TRUE,ERADARSTARTED	;
		BEQ	?1			;

		MOVEIB	TRUE,ERADARSTARTED	;

		LDX	#ERADAR_SOUND		;
		BRA	STARTSOUND@		;
?1
		RTS
*
* STOP ENEMY RADAR SOUND
*

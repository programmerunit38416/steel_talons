* START SOUND EFFECT
*
STARTSOUND@
		LDY	SOUNDSPR,X		;GET PRIORITY
		LDA	SOUNDSHI,X		;GET ADDRESS
		PHA				;
		LDA	SOUNDSLO,X		;
		PLX				;
		PLAYHSFX			;

		RTS
*
* START MACHINE GUN
*
STARTGUN@
		LDA	CRASHFLAG		;
		BEQ	?1			;
		CMP	#-2			;
		BNE	STOPGUN@		;
?1
		CMPIB	TRUE,GUNSTARTED		;
		BEQ	?2			;

		MOVEIB	TRUE,GUNSTARTED		;

		LDX	#GUNC_SOUND		;
		BRA	STARTSOUND@		;
?2
		RTS
*
* STOP MACHINE GUN
*
STOPGUN@
		MOVEIB	FALSE,GUNSTARTED	;

		LDY	#124			;PRIORITY
		JMP	StopHSFX		;
*
* START ENEMY RADAR SOUND
*

* SHOW A HIGH SCORE TABLE ENTRY
*
* ENTRY:
*	WORK1		UP TO 24-BIT VALUE TO DISPLAY
*	WORK2		NUMBER OF DIGITS (1-8)
*	WRKPTR		POINTER TO SCBS
*
PRINTDEC
		LDA	SPRSYS_RAM		;SET UNSIGNED MATH
		AND	#\SIGNMATH		;
		ORA	#ACCUMULATE		;AND ACCUMULATE
		STA	SPRSYS_RAM		;
		STA	SPRSYS			;

		LDX	#00			;INIT INDEX
		LDY	WORK2			;GET COUNT
PRINTDECLOOP
		MOVEIW	10,MATHP		;DIVIDE BY TEN
		MOVET	WORK1,MATHH		;
		STZ	MATHE			;
		WAITMATH			;

		MOVET	MATHD,WORK3		;GET QUOTIENT

		STZ	MATHM			;ZERO OUT ACCUMULATOR
		STZ	MATHK			;

		MOVEW	WORK3,MATHD		;CALC REMAINDER
		MOVEIW	10,MATHB		;
		WAITMATH			;
		STZ	MATHD			;
		MOVEB	WORK3+2,MATHC		;
		MOVEIW	2560,MATHB		;
		WAITMATH			;

		LDA	WORK1+0			;GET REMAINDER (0-9)
		SEC				;
		SBC	MATHM			;
		STA	PRINTDECBUFF,X		;

		MOVET	WORK3,WORK1		;SET NEW TOTAL

		INX				;NEXT DIGIT
		DEY				;
		BEQ	PRINTDECDONE		;
		JMP	PRINTDECLOOP		;
PRINTDECDONE
		LDA	SPRSYS_RAM		;CLEAR ACCUMULATE
		AND	#\ACCUMULATE		;
		STA	SPRSYS_RAM		;
		STA	SPRSYS			;

		LDX	WORK2			;GET COUNT
		DEX				;USE AS INDEX
PRINTITLOOP
		PHX				;

		LDA	PRINTDECBUFF,X		;GET DIGIT
		TAX				;

		LDY	#IMAGEDATA		;PRINT INTO IMAGEDATA
		LDA	XDIGITLO,X		;
		STA	(WRKPTR),Y		;
		INY				;
		LDA	XDIGITHI,X		;
		STA	(WRKPTR),Y		;

		LDY	#NEXTSPRITE		;POINT TO NEXT LINK
		LDA	(WRKPTR),Y		;
		PHA				;
		INY				;
		LDA	(WRKPTR),Y		;
		STA	WRKPTR+1		;
		PLA				;
		STA	WRKPTR+0		;

		PLX				;
		DEX				;
		BPL	PRINTITLOOP		;

		RTS

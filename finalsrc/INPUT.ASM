*
* READ JOYSTICK AND SWITCH
*
GETJOY@
		LDA	JOYSTICK		;GET JOYSTICK INPUT
		STA	JOYVALUE		;

		LDA	OJOYVALUE		;DEBOUNCE
		AND	JOYVALUE		;
		EOR	JOYVALUE		;
		STA	DJOYVALUE		;

		LDA	JOYVALUE		;SAVE FOR NEXT TIME
		STA	OJOYVALUE		;

		LDA	SWITCHES		;GET SWITCH INPUT
		STA	SWVALUE			;

		LDA	OSWVALUE		;DEBOUNCE
		AND	SWVALUE			;
		EOR	SWVALUE			;
		STA	DSWVALUE		;

		LDA	SWVALUE			;SAVE FOR NEXT TIME
		STA	OSWVALUE		;

		RTS
*
* READ JOYSTICK AND SWITCH DURING VERTICAL BLANK
*
IGETJOY@
		LDA	JOYSTICK		;GET JOYSTICK INPUT
		STA	IJOYVALUE		;

		LDA	IOJOYVALUE		;DEBOUNCE
		AND	IJOYVALUE		;
		EOR	IJOYVALUE		;
		STA	IDJOYVALUE		;

		LDA	IJOYVALUE		;SAVE FOR NEXT TIME
		STA	IOJOYVALUE		;

		LDA	SWITCHES		;GET SWITCH INPUT
		STA	ISWVALUE		;

		LDA	IOSWVALUE		;DEBOUNCE
		AND	ISWVALUE		;
		EOR	ISWVALUE		;
		STA	IDSWVALUE		;

		LDA	ISWVALUE		;SAVE FOR NEXT TIME
		STA	IOSWVALUE		;

		RTS
*
* CHECK FOR SPECIAL INPUT
*
SPECIALINPUT@
		LDA	IDJOYVALUE		;RESTART?
		BIT	#RESTART_BUTTON		;
		BEQ	NOTRESTART1		;NO
		LDA	ISWVALUE		;
		BIT	#PAUSE_SWITCH		;
		BEQ	NOTRESTART1		;NO

		MOVEIB	TRUE,RESTARTFLAG	;SET FLAG TO RESTART
		BRA	NOTPAUSED		;AVOID PAUSE
NOTRESTART1
		LDA	IJOYVALUE		;RESTART?
		BIT	#RESTART_BUTTON		;
		BEQ	NOTRESTART2		;NO
		LDA	IDSWVALUE		;
		BIT	#PAUSE_SWITCH		;
		BEQ	NOTRESTART2		;NO

		MOVEIB	TRUE,RESTARTFLAG	;SET FLAG TO RESTART
		BRA	NOTPAUSED		;AVOID PAUSE
NOTRESTART2
		LDA	CRASHFLAG		;CRASHING?
		BEQ	?1			;NO
		CMP	#-2			;
		BNE	NOTABUTTON		;YES
?1
		LDA	IDJOYVALUE		;OPTION1?
		BIT	#OPTION1_BUTTON		;
		BEQ	NOTOPTION1		;NO

		MOVEIB	TRUE,OPTION1FLAG	;SET FLAG
NOTOPTION1
		LDA	IDJOYVALUE		;OPTION2?
		BIT	#OPTION2_BUTTON		;
		BEQ	NOTOPTION2		;NO

		MOVEIB	TRUE,OPTION2FLAG	;SET FLAG
NOTOPTION2
		LDA	IDJOYVALUE		;ABUTTON?
		BIT	#A_BUTTON		;
		BEQ	NOTABUTTON		;NO

		MOVEIB	TRUE,ABUTTONFLAG	;SET FLAG
NOTABUTTON
		LDA	IJOYVALUE		;FLIP?
		BIT	#FLIP_BUTTON		;
		BEQ	NOTFLIP1		;NO
		LDA	IDSWVALUE		;
		BIT	#PAUSE_SWITCH		;
		BEQ	NOTFLIP1		;NO

		MOVEIB	TRUE,FLIPFLAG		;SET FLAG TO FLIP THE DISPLAY
		BRA	NOTPAUSED		;AVOID PAUSE
NOTFLIP1
		LDA	ISWVALUE		;FLIP?
		BIT	#PAUSE_SWITCH		;
		BEQ	NOTFLIP2		;NO
		LDA	IDJOYVALUE		;
		BIT	#FLIP_BUTTON		;
		BEQ	NOTFLIP2		;NO

		MOVEIB	TRUE,FLIPFLAG		;SET FLAG TO FLIP THE DISPLAY
		BRA	NOTPAUSED		;AVOID PAUSE
NOTFLIP2
		LDA	IDSWVALUE		;PAUSE?
		BIT	#PAUSE_SWITCH		;
		BEQ	NOTPAUSED		;NO

		MOVEIB	TRUE,TOGPAUSEDFLAG	;SET FLAG TO TOGGLE PAUSED
NOTPAUSED
		RTS

		CLC				;
		ADC	#<(OBJUSESIZE*(MAXBULLETS+MAXROCKETS+MAXMISSILES))
		STA	OBJPTR+0		;
		LDA	OBJPTR+1		;
		ADC	#>(OBJUSESIZE*(MAXBULLETS+MAXROCKETS+MAXMISSILES))
		STA	OBJPTR+1		;


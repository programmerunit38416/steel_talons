*
* CALC SCREEN X,Y
*
* ENTRY:
*	OBJPTR	POINTER TO OBJECT
* EXIT:
*	WORK2	SCREEN X
*	WORK1	SCREEN Y
*
CALCSXY@
		MOVEIB	$FF,SIGNFLAG		;CALC SCREEN Y COORDINATE

		LDY	#OBJ_X			;
		LDA	(OBJPTR),Y		;
		STA	WORK1+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		STA	WORK1+1			;
		BPL	?1			;

		INC	SIGNFLAG		;
		NEGW	WORK1			;
?1
		MOVEIW	862,MATHP		;32768/(77/2)
		MOVEW	WORK1,MATHH		;
		CLRW	MATHF			;START

		STZ	WORK3			;CALC SCREEN X COORDINATE
						;	WHILE IT RUNS
		LDY	#OBJ_Y			;
		LDA	(OBJPTR),Y		;
		STA	WORK2+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		STA	WORK2+1			;
		BPL	?3			;

		DEC	WORK3			;
		NEGW	WORK2			;
?3
		WAITMATH			;
		MOVEW	MATHD,WORK1		;

		MOVEIW	585,MATHP		;32768/(112/2)
		MOVEW	WORK2,MATHH		;
		CLRW	MATHF			;START

		LDA	SIGNFLAG		;FINISH SCREEN Y WHILE IT RUNS
		BEQ	?2			;

		NEGW	WORK1			;
?2
		ADDBW	#40,WORK1		;77/2+2

		WAITMATH			;
		MOVEW	MATHD,WORK2		;

		LDA	WORK3			;
		STA	SIGNFLAG		;
		BEQ	?4			;

		NEGW	WORK2			;
?4
		ADDBW	#58,WORK2		;112/2+2

		RTS
*
* SHOW ENEMIES ON RADAR
*
DORADAR@
		LDY	#OBJ_X			;CALC XDIFF
		LDA	(OBJPTR),Y		;
		SEC				;
		SBC	XCOORDINATELO		;
		STA	XDIFF+0			;
		INY				;
		LDA	(OBJPTR),Y		;
		SBC	XCOORDINATEHI		;
		STA	XDIFF+1			;

		LDY	#OBJ_Y			;CALC YDIFF
		LDA	(OBJPTR),Y		;
		SEC				;
		SBC	YCOORDINATELO		;
		STA	YDIFF+0			;
		INY				;
		LDA	(OBJPTR),Y		;

*
		LIST	OFF
		INCLUDE	\PR\LYNX\INCLUDE\sys.mac
	IF	USEHSOUNDS=TRUE
		INCLUDE	\PR\LYNX\INCLUDE\HMUSIC.MAC
		INCLUDE	\PR\LYNX\INCLUDE\HSFX.MAC
	ENDIF
		INCLUDE	\PR\LYNX\INCLUDE\sprite.mac
		INCLUDE	\PR\LYNX\INCLUDE\display.mac
		INCLUDE	\PR\LYNX\INCLUDE\handymath.mac
		INCLUDE	\PR\LYNX\INCLUDE\cart.mac
		LIST	ON
*
* START OF PROGRAM
*
		ORG	SPRBUFFER
*
* SHOW MAP SCREEN
*
SHOWMAP@
		JSR	STOPERADARS@		;STOP SOUND

		PUSHB	VBTIME			;SAVE VBTIME

		SEI				;NO INTERRUPTS

		LDA	TIMER0+(AUDIO_TIMER*4)+TIM_CONTROLA
		PHA				;
		AND	#$FF-$08		;
		STA	TIMER0+(AUDIO_TIMER*4)+TIM_CONTROLA
		PUSHB	AUDIO0+CONTROL		;SAVE SOUNDS
		PUSHB	AUDIO1+CONTROL		;
		PUSHB	AUDIO2+CONTROL		;
		PUSHB	AUDIO3+CONTROL		;

		LDA	#00			;CLEAR SOUNDS
		STA	AUDIO0+CONTROL		;
		STA	AUDIO1+CONTROL		;
		STA	AUDIO2+CONTROL		;
		STA	AUDIO3+CONTROL		;

		CLI				;

		MOVEIB	$0F,PAUSEDSPR+PALETTE	;FOREGROUND

		LDA	SCORESPR1+CONTROL1	;WATCH OUT FOR LEADING ZEROS
		ORA	#REUSE_PALETTE		;
		STA	MAPSCORESPR1+CONTROL1	;

		LDA	SCORESPR1+IMAGEDATA+0	;
		STA	MAPSCORESPR1+IMAGEDATA+0
		LDA	SCORESPR1+IMAGEDATA+1	;
		STA	MAPSCORESPR1+IMAGEDATA+1

		MOVEIW	SHOWMAPCLS,FIRSTSPRITE	;POINT TO FIRST SCB

		LDA	DAMAGE			;SHOW DAMAGE LEVEL
		CMP	#24+1			;
		BLT	?1			;
		LDA	#24			;
?1
		STA	MATHD			;
		STZ	MATHC			;
		LDA	#86			;(0..24)*86/256 = (0..24)/3
		STA	MATHB			;
		STZ	MATHA			;START
		LDA	#DAMAGEY		;(WHILE IT RUNS)
		SEC				;
		WAITMATH			;
		SBC	MATHG			;
		STA	DAMAGESPR+VPOS		;

		LEA	MCOUNTSPR1,WRKPTR	;SHOW MISSILES LEFT
		MOVEB	MISSILESLEFT,WORK1	;
		CLRW	WORK1+1			;
		MOVEIB	2,WORK2			;
		JSR	PRINTDEC		;

		LEA	RCOUNTSPR1,WRKPTR	;SHOW ROCKETS LEFT
		MOVEB	ROCKETSLEFT,WORK1	;
		CLRW	WORK1+1			;
		MOVEIB	2,WORK2			;
		JSR	PRINTDEC		;

		LEA	GCOUNTSPR1,WRKPTR	;SHOW 30MM ROUNDS LEFT
		MOVEW	ROUNDSLEFT,WORK1	;
		CLRB	WORK1+2			;
		MOVEIB	4,WORK2			;
		JSR	PRINTDEC		;

		LEA	LCOUNTSPR1,WRKPTR	;SHOW LIVES LEFT
		MOVEB	LIVESLEFT,WORK1		;
		CLRW	WORK1+1			;
		MOVEIB	2,WORK2			;
		JSR	PRINTDEC		;

		JSR	HIDEERADAR@		;HIDE ENEMY RADAR MSGE

		CLRW	WXROTATION		;SET ROTATIONS FOR RADAR
		CLRW	WYROTATION		;

		MOVEW	VIEWZROT,WZROTATION	;

		JSR	GETCOSSIN1@		;GET COSINE AND SINE

		STZ	MAPOBJS			;INIT ENTRY COUNTS
		STZ	RADOBJS			;

		LEA	SPRITEBUFF,WRKPTR	;POINT TO BUFFER

		MOVEW	WRKPTR,DSTPTR		;SAVE SCB ADDRESS
		MOVEW	POSPTR,OBJPTR		;GET SBLACKHA ADDRESS

		LDY	#CONTROL0		;INIT CONTROL0
		LDA	#ONE_PER_PIXEL+NORMAL_SPRITE
		STA	(DSTPTR),Y		;

		LDY	#CONTROL1		;SET CONTROL1
		LDA	#RELOAD_NONE		;
		STA	(DSTPTR),Y		;

		LDY	#CONTROL2		;SET CONTROL2
		LDA	#00			;
		STA	(DSTPTR),Y		;

		LDY	#PALETTE-8		;INIT PALETTE
		LDA	#$04			;
		STA	(DSTPTR),Y		;

		JSR	CALCSXY@		;CALC SCREEN X,Y

		LDY	#HPOS+0			;SET HPOS
		LDA	WORK2+0			;
		SEC				;
		SBC	#2			;
		STA	(DSTPTR),Y		;
		INY				;
		LDA	WORK2+1			;
		SBC	#0			;
		STA	(DSTPTR),Y		;

		LDY	#VPOS+0			;SET VPOS
		LDA	WORK1+0			;
		SEC				;
		SBC	#2			;
		STA	(DSTPTR),Y		;
		INY				;
		LDA	WORK1+1			;
		SBC	#0			;
		STA	(DSTPTR),Y		;

		LDA	#<$240			;CALC IMAGE NUMBER 0..7
		SEC				;
		SBC	ZROTATION+0		;
		STA	WORK1+0			;
		LDA	#>$240			;
		SBC	ZROTATION+1		;
		AND	#>$3FF			;
		STA	WORK1+1			;

		LDA	WORK1+0			;
		ASL	A			;
		LDA	WORK1+1			;
		ROL	A			;
		AND	#7			;
		ASL	A			;
		TAX				;

		LDY	#IMAGEDATA+0		;
		LDA	MVXDATA+0,X		;
		STA	(DSTPTR),Y		;
		INY				;
		LDA	MVXDATA+1,X		;
		STA	(DSTPTR),Y		;

		LDY	#NEXTSPRITE		;
		LDA	WRKPTR+0		;
		CLC				;
		ADC	#(SPRSIZE-8)		;
		STA	(DSTPTR),Y		;
		INY				;
		LDA	WRKPTR+1		;
		ADC	#00			;
		STA	(DSTPTR),Y		;

		MOVEW	DSTPTR,SHOWMAPSPR2+NEXTSPRITE

		ADDBW	#(SPRSIZE-8),WRKPTR	;
		INC	MAPOBJS			;

		LEA	STARTDATABASE,OBJPTR	;POINT TO DATABASE
INITMAPSPRLOOP
		LDY	#OBJ_FLAGS		;EOT?
		LDA	(OBJPTR),Y		;
		CMP	#<EOT			;
		BNE	INITMAPSPRCONT1		;NO

		JMP	INITMAPSPRDONE		;YES - DONE
INITMAPSPRCONT1
		BIT	#2			;SKIP BIT SET?
		BNE	INITMAPSPRNEXT		;YES
		BIT	#4			;EXPLODING?
		BEQ	INITMAPSPRCONT2		;NO
INITMAPSPRNEXT
		ADDBW	#OBJUSESIZE,OBJPTR	;NEXT DATABASE ENTRY
		BRA	INITMAPSPRLOOP		;
INITMAPSPRCONT2
		LDA	MAPOBJS			;AT MAX ENTRIES?
		CLC				;
		ADC	RADOBJS			;
		CMP	#MAXMAPOBJS-1		;(-1 FOR RADAR)
		BGE	INITMAPSPRNEXT		;YES

		LDY	#OBJ_FILE		;GET FILE TYPE
		LDA	(OBJPTR),Y		;
		CMP	#STARTTARGETS		;TARGET-ABLE OBJECT?
		BLT	INITMAPSPRNEXT		;NO

		CMP	#STARTSTARGETS		;SMART TARGETS?
		BLT	?1			;NO

		MOVEIB	$30,WORKPAL		;RED
		BRA	?2			;
?1
		MOVEIB	$D0,WORKPAL		;YELLOW
?2
		LDY	#OBJ_FILE		;GET FILE TYPE
		LDA	(OBJPTR),Y		;

		CMP	#SJEEP_FILE		;MOVING?
		BEQ	?3			;YES
		CMP	#STRUCK_FILE		;
		BEQ	?3			;YES
		CMP	#SCHOPPER_FILE		;
		BEQ	?3			;YES
		CMP	#SJET1_FILE		;
		BNE	?4			;NO
?3
		LDA	WORKPAL			;SET FLAG
		ORA	#$0F			;
		STA	WORKPAL			;
?4
		JSR	DORADAR@		;DISPLAY ON RADAR SCREEN

		LDY	#PALETTE-8		;INIT PALETTE
		LDA	WORKPAL			;SET COLOR
		STA	(WRKPTR),Y		;

		LDY	#CONTROL0		;INIT CONTROL0
		LDA	#ONE_PER_PIXEL		;
		STA	(WRKPTR),Y		;

		LDY	#CONTROL1		;SET CONTROL1
		LDA	#RELOAD_NONE		;
		STA	(WRKPTR),Y		;

		LDY	#CONTROL2		;SET CONTROL2
		LDA	#00			;
		STA	(WRKPTR),Y		;

		JSR	CALCSXY@		;

		LDY	#HPOS			;SET HPOS
		LDA	WORK2+0			;
		STA	(WRKPTR),Y		;
		INY				;
		LDA	WORK2+1			;
		STA	(WRKPTR),Y		;

		LDY	#VPOS			;SET VPOS
		LDA	WORK1+0			;
		STA	(WRKPTR),Y		;
		INY				;
		LDA	WORK1+1			;
		STA	(WRKPTR),Y		;

		LDY	#IMAGEDATA		;SET IMAGEDATA
		LDA	#<DOTIMAGE2		;
		STA	(WRKPTR),Y		;
		INY				;
		LDA	#>DOTIMAGE2		;
		STA	(WRKPTR),Y		;

		LDY	#NEXTSPRITE		;
		LDA	WRKPTR+0		;
		CLC				;
		ADC	#(SPRSIZE-8)		;
		STA	(WRKPTR),Y		;
		INY				;
		LDA	WRKPTR+1		;
		ADC	#00			;
		STA	(WRKPTR),Y		;

		ADDBW	#(SPRSIZE-8),WRKPTR	;
		INC	MAPOBJS			;

		JMP	INITMAPSPRNEXT		;
INITMAPSPRDONE
		LDA	MAPOBJS			;ANY ENTRIES
		BNE	SOMEMAPENTRIES		;YES

		LDA	#<MCOUNTSPR1		;NO ENTRIES
		STA	SHOWMAPSPR2+NEXTSPRITE+0
		LDA	#>MCOUNTSPR1		;
		STA	SHOWMAPSPR2+NEXTSPRITE+1
		BRA	DONEMAPENTRIES		;
SOMEMAPENTRIES
		SUBBW	#(SPRSIZE-8),WRKPTR	;SET LAST LINK

		LDY	#NEXTSPRITE		;
		LDA	#<MCOUNTSPR1		;
		STA	(WRKPTR),Y		;
		INY				;
		LDA	#>MCOUNTSPR1		;
		STA	(WRKPTR),Y		;

		ADDBW	#(SPRSIZE-8),WRKPTR	;
DONEMAPENTRIES
		LDA	MAPOBJS			;SHOW ENEMY TARGETS LEFT
		BEQ	?1			;
		DEC	A			;
?1
		STA	WORK1			;
		CLRW	WORK1+1			;
		MOVEIB	2,WORK2			;
		LEA	ECOUNTSPR1,WRKPTR	;
		JSR	PRINTDEC		;

		MOVEIW	1*30,SLCOUNT		;SHOW TARGET FOR 1 SECOND
		JSR	SHOWLOCK		;

		JSR	DOSTROBE		;DO STROBING

		MYWAITEOF			;WAIT FOR VB

		JSR	GETJOY@			;READ CONTROLLER

		LDA	JOYVALUE		;OPTION1 STILL PRESSED?
		BIT	#OPTION1_BUTTON		;
		BNE	?2			;YES - CONTINUE

		JMP	SHOWMAPDONE		;NO - DONE
?2
		MYSPRITES			;DRAW SPRITES

		MYDBUF_DISPLAY			;"PAGE FLIP"
		MYWAITEOF			;
		MYRGB16 MXX1PAL			;UPDATE PALETTE
SHOWMAPLOOP
		MYWAITEOF			;WAIT FOR VB

		JSR	GETJOY@			;READ CONTROLLER

		LDA	JOYVALUE		;OPTION1 STILL PRESSED?
		BIT	#OPTION1_BUTTON		;
		BNE	SHOWMAPCONT		;YES - CONTINUE

		JMP	SHOWMAPDONE		;NO - DONE
SHOWMAPCONT
		BIT	#A_BUTTON		;A OR B?
		BNE	YSHOWLOCK		;YES
		BIT	#B_BUTTON		;
		BEQ	NSHOWLOCK		;NO
YSHOWLOCK
		CLRW	SLCOUNT			;
		JSR	SHOWLOCK		;SHOW IT
NSHOWLOCK
		JSR	DOSTROBE		;DO STROBING

		MYSPRITES			;DRAW SPRITES

		MYDBUF_DISPLAY			;"PAGE FLIP"
		MYWAITEOF			;

		JSR	CHECKOTHERFLAGS@	;CHECK THE OTHER FLAGS,TOO
;;NO		JSR	SELCHECKPAUSED@		;CHECK PAUSED FLAG

		JMP	SHOWMAPLOOP		;
SHOWMAPDONE
		MOVEIB	$79,PAUSEDSPR+PALETTE	;FOREGROUND

		MOVEIW	SKYSPRITE,FIRSTSPRITE	;SET UP THE SPRITE LIST

		POPB	AUDIO3+CONTROL		;RESTORE SOUNDS
		POPB	AUDIO2+CONTROL		;
		POPB	AUDIO1+CONTROL		;
		POPB	AUDIO0+CONTROL		;
		PLA				;RESTORE INTERRUPT
		STA	TIMER0+(AUDIO_TIMER*4)+TIM_CONTROLA

		POPB	VBTIME			;RESTORE VBTIME

		LDA	#<TRUE			;SET FLAGS
		STA	UPDATEPALFLAG		;
		STA	FIRSTFRAME		;

		LDA	#FALSE			;CLEAR FLAGS
		STA	OPTION1FLAG		;
		STA	OPTION2FLAG		;
		STA	ABUTTONFLAG		;

		RTS
*
* DO STROBING
*
DOSTROBE
		LDX	MAPOBJS			;ANY MAP ENTRIES?
		BEQ	?2			;NO

		LDA	COUNTER1		;
		BEQ	?1			;

		DEC	COUNTER1		;
		BRA	?2			;
?1
		MOVEIB	3,COUNTER1		;

		DEX				;
		TXA				;
		CLC				;
		ADC	RADOBJS			;
		TAX				;
		BEQ	?STROBEDONE		;

		LEA	(SPRITEBUFF+SPRSIZE-8),WRKPTR	;POINT TO BUFFER
?STROBELOOP
		LDY	#PALETTE-8		;
		LDA	(WRKPTR),Y		;
		AND	#$0F			;
		BEQ	?STROBESHOW		;

		LDY	#CONTROL1		;
		LDA	(WRKPTR),Y		;
		EOR	#SKIP_SPRITE		;
		STA	(WRKPTR),Y		;
		BRA	?STROBENEXT		;
?STROBESHOW
		LDY	#CONTROL1		;
		LDA	(WRKPTR),Y		;
		AND	#\SKIP_SPRITE		;
		STA	(WRKPTR),Y		;
?STROBENEXT
		ADDBW	#(SPRSIZE-8),WRKPTR	;
		DEX				;
		BNE	?STROBELOOP		;
?STROBEDONE
		LDY	#PALETTE-8		;STROBE THE SCB PALETTE
		LDA	(DSTPTR),Y		;
		EOR	#%1001			;%1101 <-> %0100
		STA	(DSTPTR),Y		;

		LDY	#CONTROL1		;SHOW SPRITE
		LDA	(DSTPTR),Y		;
		AND	#\SKIP_SPRITE		;
		STA	(DSTPTR),Y		;
?2
		RTS
*
* LOAD THE MAP
*
LOADTHEMAP
		LDA	MISSION			;GET MISSION NUMBER
		CLC				;
		ADC	#STARTMAPFILES		;ADD START OF SELECTION FILES
		GETDIR				;GET DIRECTORY ENTRY
		MYOPENFILE			;OPEN THE FILE
		LDA	#1			;DEST ADDRESS
		LDX	#<MAPBUFF		;
		LDY	#>MAPBUFF		;
		READFILE			;READ THE FILE

		RTS
*
* SHOW LOCKED TARGET
*
SHOWLOCK
		CMPIB	LOCKED,TARGETSTATUS	;LOCKED?
		BEQ	?SHOWLOCKCONT		;YES

		JMP	SHOWLOCKDONE		;
?SHOWLOCKCONT
		LDX	MAPOBJS			;ANY MAP ENTRIES?
		BEQ	?2			;NO

		DEX				;
		TXA				;
		CLC				;
		ADC	RADOBJS			;
		TAX				;
		BEQ	?STROBEDONE		;

		LEA	(SPRITEBUFF+SPRSIZE-8),WRKPTR	;POINT TO BUFFER
?STROBELOOP
		LDY	#HPOS			;IN MAP AREA?
		LDA	(WRKPTR),Y		;
		CMP	#117			;
		BGE	?STROBESHOW		;NO

		LDY	#CONTROL1		;
		LDA	(WRKPTR),Y		;
		ORA	#SKIP_SPRITE		;
		STA	(WRKPTR),Y		;
		BRA	?STROBENEXT		;
?STROBESHOW
		LDY	#CONTROL1		;
		LDA	(WRKPTR),Y		;
		AND	#\SKIP_SPRITE		;
		STA	(WRKPTR),Y		;
?STROBENEXT
		ADDBW	#(SPRSIZE-8),WRKPTR	;
		DEX				;
		BNE	?STROBELOOP		;
?STROBEDONE
		LDY	#CONTROL1		;HIDE SPRITE
		LDA	(DSTPTR),Y		;
		ORA	#SKIP_SPRITE		;
		STA	(DSTPTR),Y		;
?2
		LDY	#OBJ_FILE		;
		LDA	(TARGETPTR),Y		;
		SEC				;
		SBC	#STARTTARGETS		;
		TAX				;

		LDA	TVCFILES,X		;
		GETDIR				;GET DIRECTORY ENTRY
		MYOPENFILE			;OPEN THE FILE
		LDA	#1			;DEST ADDRESS
		LDX	#<MAPBUFF		;
		LDY	#>MAPBUFF		;
		READFILE			;READ THE FILE

		MYSPRITES			;DRAW SPRITES
		MYDBUF_DISPLAY			;"PAGE FLIP"
		MYWAITEOF			;WAIT VB
		MYRGB16 MXX1PAL			;UPDATE PALETTE
SHOWLOCKLOOP
		MYWAITEOF			;WAIT VB

		JSR	GETJOY@			;READ CONTROLLER

		LDA	SLCOUNT+0		;TIMER ZERO?
		ORA	SLCOUNT+1		;
		BEQ	?1			;

		DECW	SLCOUNT			;
		BRA	SHOWLOCKNEXT		;
?1
		LDA	JOYVALUE		;STILL PRESSED?

		BIT	#A_BUTTON		;A OR B?
		BNE	SHOWLOCKNEXT		;YES
		BIT	#B_BUTTON		;
		BNE	SHOWLOCKNEXT		;YES

		JMP	SHOWLOCKDONE		;NO - DONE
SHOWLOCKNEXT
		JSR	CHECKOTHERFLAGS@	;CHECK THE OTHER FLAGS,TOO
;;NO		JSR	SELCHECKPAUSED@		;CHECK PAUSED FLAG

		JMP	SHOWLOCKLOOP		;
SHOWLOCKDONE
		STZ	COUNTER1		;
		JMP	LOADTHEMAP		;NOW RELOAD THE MAP

*
* INITIALIZE SPRITES (DO ONCE AT START OF PROGRAM)
*
INITSPRS@
		MOVEIW	MAXSPR,SPRITECOUNT	;GET COUNT
		LEA	SPRBUFFER,SPRPTR	;POINT TO BUFFER
INITSPRSLOOP
		LDY	#CONTROL0		;INIT CONTROL0
		LDA	#ONE_PER_PIXEL		;
		STA	(SPRPTR),Y		;

		LDY	#CONTROL2		;SET CONTROL2
		LDA	#00			;
		STA	(SPRPTR),Y		;

		LDY	#HPOS+1			;SET HPOS+1
		LDA	#00			;
		STA	(SPRPTR),Y		;

		LDY	#VPOS+1			;SET VPOS+1
		LDA	#00			;
		STA	(SPRPTR),Y		;

		LDY	#IMAGEDATA		;SET IMAGEDATA
		LDA	#<DOTIMAGE		;
		STA	(SPRPTR),Y		;
		INY				;
		LDA	#>DOTIMAGE		;
		STA	(SPRPTR),Y		;

		ADDIW	SPRSIZE,SPRPTR		;NEXT SPRITE
		DECW	SPRITECOUNT		;

		LDA	SPRITECOUNT+0		;
		ORA	SPRITECOUNT+1		;
		BNE	INITSPRSLOOP		;

		RTS				;
*
* SET UP TO DRAW A TRIANGLE SPRITE FROM PSUEDO-PARRALLELOGRAM
*
* ENTRY:
*	X1,X2,X3,X4	FOUR X VALUES
*		X1	UPPER LEFT END POINT
*		X2	UPPER RIGHT END POINT
*		X3	LOWER LEFT END POINT
*		X4	LOWER RIGHT END POINT
*	Y1,Y2		TWO Y VALUES
*		Y1	TOP Y VALUE
*		Y2	BOTTOM Y VALUE
*
DRAWPGRAM@
		LDY	#CONTROL1		;SET CONTROL1
		LDA	#RELOAD_HVST		;
		STA	(SPRPTR),Y		;

		LDY	#HSIZE+0		;SET HSIZE+0
		LDA	#00			;
		STA	(SPRPTR),Y		;

		LDY	#VSIZE+0		;SET VSIZE+0
		LDA	#00			;
		STA	(SPRPTR),Y		;

		LDY	#PALETTE		;SET PALETTE
		LDA	COLOR			;
		ASL	A			;
		ASL	A			;
		ASL	A			;
		ASL	A			;
		STA	(SPRPTR),Y		;

		CMPB	Y1,Y2			;Y1=Y2?
		BNE	NOTHLINE		;NO

		JMP	DRAWHLINE@		;DRAW HORIZONTAL LINE
NOTHLINE
		LDA	X2+0			;CALC HSIZE
		SEC				;
		SBC	X1+0			;
		STA	WORK1+0			;

		LDA	X4+0			;
		SEC				;
		SBC	X3+0			;
		STA	WORK2+0			;

		LDY	#HSIZE+1		;SET HSIZE+1
		LDA	WORK1+0			;ALWAYS TOP SIZE FOR HSIZE
		INC	A			;CONVERT DIFF TO SIZE
		STA	(SPRPTR),Y		;

		CMPB	WORK1,WORK2		;TOP SIDE SMALLER?
		BLT	DRAWUTRIANGLE@		;NO - UPSIDE DOWN

		JMP	DRAWTRIANGLE@		;YES - RIGHT SIDE IS UP
*
* DRAW AN UPSIDE DOWN TRIANGLE SPRITE
*
DRAWUTRIANGLE@

	IF	TRUE

		LDA	X2+0			;SET NEW X2
		SEC				;
		SBC	WORK2+0			;
		STA	X2+0			;

		LDY	#HPOS+0			;SET HPOS+0
		LDA	X1+0			;
		STA	(SPRPTR),Y		;

		LDY	#VPOS+0			;SET VPOS
		LDA	Y1+0			;
		STA	(SPRPTR),Y		;

		LDA	Y2+0			;VSIZE = Y2 - Y1
		SEC				;
		SBC	Y1+0			;
		INC	A			;CONVERT DIFF TO SIZE
		STA	WORK2+0			;
		STZ	WORK2+1			;

		MOVEW	WORK2,MATHP		;SET DIVISOR

		LDY	#VSIZE+1		;SET VSIZE AND SET DIVISOR
		LDA	WORK2+0			;
		STA	(SPRPTR),Y		;

		STZ	MATHH			;CLEARS MATHG,TOO

		STZ	SIGNFLAG		;INIT SIGN VARIABLES
		STZ	SIGNADD			;

		LDA	X3+0			;TILT DIST = X3 - X1
		SEC				;
		SBC	X1+0			;
		BCS	?11			;BRANCH IF NOT SIGNED

		DEC	SIGNFLAG		;ADJUST SIGN VARIABLES
		INC	SIGNADD			;

		LDA	X1+0			;REVERSE ORDER
		SEC				;
		SBC	X3+0			;
?11
		STA	MATHF			;
		STZ	MATHE			;START THE DIVIDE

		WAITMATH			;WAIT FOR DIVIDE

		LDA	MATHD			;NEED TO ROUND UP?
		BPL	?12			;NO

		INC	SIGNADD			;YES - ADJUST ADD AMOUNT
?12
		LDY	#TILT			;SET TILT
		LDA	MATHC			;
		EOR	SIGNFLAG		;
		CLC				;
		ADC	SIGNADD			;
		STA	(SPRPTR),Y		;
		INY				;
		LDA	MATHB			;
		EOR	SIGNFLAG		;
		ADC	#0			;
		STA	(SPRPTR),Y		;
?121
		STZ	MATHH			;CLEARS MATHG,TOO

		LDA	#1			;INIT SIGN ADD
		STA	SIGNADD			;

		LDA	X2+0			;STRETCH DIST = X2 - X1
		SEC				;
		SBC	X1+0			;
		STA	MATHF			;
		STZ	MATHE			;START THE DIVIDE

		WAITMATH			;WAIT FOR THE DIVIDE

		LDA	MATHD			;NEED TO ROUND UP?
		BPL	?22			;NO

		INC	SIGNADD			;YES - ADJUST ADD AMOUNT
?22
		LDY	#STRETCH		;SET STRETCH
		LDA	MATHC			;(ALWAYS NEGATIVE)
		EOR	#$FF			;
		CLC				;
		ADC	SIGNADD			;
		STA	(SPRPTR),Y		;
		INY				;
		LDA	MATHB			;
		EOR	#$FF			;
		ADC	#0			;
		STA	(SPRPTR),Y		;
?221
		JMP	LINKNEXT@		;LINK NEXT SPRITE

	ELSE

		LDA	X2+0			;SET NEW X2
		SEC				;
		SBC	WORK2+0			;
		STA	X2+0			;

		LDY	#HPOS+0			;SET HPOS+0
		LDA	X1+0			;
		STA	(SPRPTR),Y		;

		LDY	#VPOS+0			;SET VPOS
		LDA	Y1+0			;
		STA	(SPRPTR),Y		;

		LDA	Y2+0			;VSIZE = Y2 - Y1
		SEC				;
		SBC	Y1+0			;
		INC	A			;CONVERT DIFF TO SIZE
		STA	WORK2+0			;

		TAX				;

		LDY	#VSIZE+1		;SET VSIZE AND SET DIVISOR
		LDA	WORK2+0			;
		STA	(SPRPTR),Y		;

		STZ	SIGNFLAG		;INIT SIGN VARIABLES
		STZ	SIGNADD			;

		LDA	X3+0			;TILT DIST = X3 - X1
		SEC				;
		SBC	X1+0			;
		BCS	?11			;BRANCH IF NOT SIGNED

		DEC	SIGNFLAG		;ADJUST SIGN VARIABLES
		INC	SIGNADD			;

		LDA	X1+0			;REVERSE ORDER
		SEC				;
		SBC	X3+0			;
?11
		CPX	#2			;0 OR 1?
		BGE	?111			;NO

		LDY	#TILT			;SET TILT
		EOR	SIGNFLAG		;
		CLC				;
		ADC	SIGNADD			;
		STA	(SPRPTR),Y		;
		INY				;
		LDA	#$00			;
		EOR	SIGNFLAG		;
		ADC	#0			;
		STA	(SPRPTR),Y		;
		BRA	?121			;
?111
		STA	MATHD			;
		STZ	MATHC			;

		LDA	RECIPTABLELO,X		;
		STA	MATHB			;
		LDA	RECIPTABLEHI,X		;
		STA	MATHA			;
		WAITMATH			;

		LDA	MATHG			;
		BPL	?12			;NO

		INC	SIGNADD			;YES - ADJUST ADD AMOUNT
?12
		LDY	#TILT			;SET TILT
		LDA	MATHF			;
		EOR	SIGNFLAG		;
		CLC				;
		ADC	SIGNADD			;
		STA	(SPRPTR),Y		;
		INY				;
		LDA	MATHE			;
		EOR	SIGNFLAG		;
		ADC	#0			;
		STA	(SPRPTR),Y		;
?121
		LDA	#1			;INIT SIGN ADD
		STA	SIGNADD			;

		LDA	X2+0			;STRETCH DIST = X2 - X1
		SEC				;
		SBC	X1+0			;

		CPX	#2			;0 OR 1?
		BGE	?122			;NO

		LDY	#STRETCH		;SET STRETCH
		EOR	#$FF			;
		INC	A			;
		STA	(SPRPTR),Y		;
		INY				;
		LDA	#$FF			;
		STA	(SPRPTR),Y		;
		BRA	?221			;
?122
		STA	MATHD			;
		STZ	MATHC			;

		LDA	RECIPTABLELO,X		;
		STA	MATHB			;
		LDA	RECIPTABLEHI,X		;
		STA	MATHA			;
		WAITMATH			;

		LDA	MATHG			;
		BPL	?22			;NO

		INC	SIGNADD			;YES - ADJUST ADD AMOUNT
?22
		LDY	#STRETCH		;SET STRETCH
		LDA	MATHF			;
		EOR	#$FF			;
		CLC				;
		ADC	SIGNADD			;
		STA	(SPRPTR),Y		;
		INY				;
		LDA	MATHE			;
		EOR	#$FF			;
		ADC	#0			;
		STA	(SPRPTR),Y		;
?221
		JMP	LINKNEXT@		;LINK NEXT SPRITE

	ENDIF		
*
* DRAW A TRIANGLE SPRITE
*
DRAWTRIANGLE@

	IF	TRUE

		MOVEB	X3,X2			;SET NEW X2


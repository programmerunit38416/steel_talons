*
* DRAW POLYGON USING HARDWARE MANIPULATED ONE DOT SPRITES
*
* ENTRY:
*	LINEINDEXES	LIST OF (SORTED ON Y) INDEXES INTO LINELIST
*	LINECOUNT	NUMBER OF LINES IN POLYGON
*	(SPRPTR)	POINTER TO NEXT SLOT FOR POLYGON SPRITES
* EXIT:
*	(SPRPTR)	DATA ADDED AND POINTER UPDATED
*
DRAWSPRPOLY@
		SIGNEDMATH			;SET SIGNED MATH

		STZ	DRAWNCOUNT		;INIT SPRITES DRAWN COUNT
		STZ	CURRENTINDEX		;INIT CURRENT INDEX

		MOVEB	LINECOUNT,ORGLINECOUNT	;SAVE ORIGINAL LINE COUNT

		LDA	#2			;INIT LINES NEEDED COUNT
		STA	NEEDED			;
DRAWSPRPOLYLOOP
		LDA	LINECOUNT		;DONE?
		BNE	?1			;NO
		JMP	DRAWSPRPOLYDONE		;YES
?1
		LDA	NEEDED			;SET TO DRAW?
		BNE	NOTREADY		;NO

		JSR	GETPOINTS@		;SET UP THE POINTS
		JSR	DRAWPGRAM@		;DRAW THE PGRAM
		INC	DRAWNCOUNT		;

		BRA	DRAWSPRPOLYLOOP		;
NOTREADY
		LDX	CURRENTINDEX		;GET CURRENT INDEX
		LDA	LINEINDEXES,X		;
		TAX				;

		LDA	LINELIST+1,X		;Y COORDINATES THE SAME?
		CMP	LINELIST+3,X		;
		BNE	USETHISLINE		;NO - USE THIS LINE

		LDA	DRAWNCOUNT		;WERE SPRITES DRAWN YET?
		BNE	SKIPTHISLINE		;YES - SKIP THIS LINE

		LDA	LINECOUNT		;LAST LINE?
		CMP	#1			;
		BEQ	USETHISLINE		;YES - DO NOT SKIP THIS LINE
SKIPTHISLINE
		JMP	NEXTLINE		;YES - SKIP HORZ LINE
USETHISLINE
		LDA	NEEDED			;GET POINTS NEEDED
		CMP	#1			;NEED SECOND LINE?
		BNE	GETFIRSTLINE		;NO

		LDA	LINELIST+0,X		;
		STA	WX3+0			;
		LDA	LINELIST+1,X		;
		STA	WY3+0			;

		LDA	LINELIST+2,X		;
		STA	WX4+0			;
		LDA	LINELIST+3,X		;
		STA	WY4+0			;

		DEC	NEEDED			;
		BRA	NEXTLINE		;
GETFIRSTLINE
		LDA	LINELIST+0,X		;GET FIRST LINE
		STA	WX1+0			;
		LDA	LINELIST+1,X		;
		STA	WY1+0			;

		LDA	LINELIST+2,X		;
		STA	WX2+0			;
		LDA	LINELIST+3,X		;
		STA	WY2+0			;

		DEC	NEEDED			;
NEXTLINE
		INC	CURRENTINDEX		;INCREMENT CURRENT INDEX
		DEC	LINECOUNT		;DECREMENT LINES LEFT
		JMP	DRAWSPRPOLYLOOP		;
DRAWSPRPOLYDONE
		LDA	NEEDED			;FULL POLYGON TO DRAW?
		BEQ	ONELASTPOLY		;YES - DRAW IT
		CMP	#1			;PARTIAL POLYGON TO DRAW?
		BNE	NOMOREPOLYS		;NO - ALL DONE

		JSR	SETUPALINE		;SET UP A LINE

		BRA	DRAWLASTPOLY		;
ONELASTPOLY
		JSR	GETPOINTS@		;SET UP THE POINTS
DRAWLASTPOLY
		JSR	DRAWPGRAM@		;DRAW THE PGRAM
		INC	DRAWNCOUNT		;
NOMOREPOLYS
		RTS
*
* SET UP POINTS FOR A LINE
*
SETUPALINE
		LDA	WX1+0			;SET UP THE POINTS
		STA	X1+0			;	(WILL DRAW A LINE)
		STA	X2+0			;

		LDA	WX2+0			;
		STA	X3+0			;
		STA	X4+0			;

		MOVEB	WY1,Y1			;
		MOVEB	WY2,Y2			;

		RTS
*
* SET UP X1,X2,X3,X4 AND Y1,Y2 AND ADJUST NEEDED COUNT
*
GETPOINTS@
		MOVEB	WY1,Y1		;SET Y1
		MOVEB	WX1,X1		;SET X1
		MOVEB	WX3,X2		;SET X2

		LDA	WY2+0		;
		CMP	WY4+0		;
		BLT	?3		;YES
		BNE	?2		;BRANCH IF FIRST LINE LONGER

		MOVEB	WY2,Y2		;SET Y2
		MOVEB	WX2,X3		;SET X3
		MOVEB	WX4,X4		;SET X4
		MOVEIB	2,NEEDED	;
		BRA	CHECKXORDER	;
?2
		MOVEB	WY4,Y2		;SET Y2
		MOVEB	WX4,X4		;SET X4

		JSR	CALCX3@		;CALC X3

		MOVEB	Y2,WY1		;SAVE LINE SEGMENT
		MOVEB	X3,WX1		;
		MOVEIB	1,NEEDED	;
		BRA	CHECKXORDER	;
?3
		MOVEB	WY2,Y2		;SET Y2
		MOVEB	WX2,X3		;SET X3

		JSR	CALCX4@		;CALC X4

		MOVEB	Y2,WY1		;SAVE LINE SEGMENT
		MOVEB	X4,WX1		;
		MOVEB	WX4,WX2		;
		MOVEB	WY4,WY2		;
		MOVEIB	1,NEEDED	;
CHECKXORDER
		LDA	X2+0		;X2 >= X1?
		CMP	X1+0		;
		BGE	?1		;YES

		LDA	X1+0		;NO - SWAP X1 AND X2
		LDX	X2+0		;
		STX	X1+0		;
		STA	X2+0		;
?1
		LDA	X4+0		;X4 >= X3?
		CMP	X3+0		;
		BGE	?2		;YES

		LDA	X3+0		;NO - SWAP X3 AND X4
		LDX	X4+0		;
		STX	X3+0		;
		STA	X4+0		;
?2
		RTS
*
* CALC X3
*
*	X3 = WX1 + (Y2 - WY1) * (WX2 - WX1) / (WY2 - WY1)
*
CALCX3@
		LDA	Y2+0			;CALC (Y2 - WY1)
		SEC				;
		SBC	WY1+0			;
		STA	MATHD			;
		LDA	#00			;
		BCS	?1			;
		DEC	A			;
?1
		STA	MATHC			;

		LDA	WX2+0			;CALC (WX2 - WX1)
		SEC				;
		SBC	WX1+0			;
		STA	MATHB			;
		LDA	#00			;
		BCS	?2			;
		DEC	A			;
?2
		STA	MATHA			;
		WAITMATH			;

	IF	FALSE

		MOVEL	MATHH,DIVIDEND		;

		LDA	WY2+0			;CALC (WY2 - WY1)
		SEC				;
		SBC	WY1+0			;
		STA	DIVISOR+0		;
		STZ	DIVISOR+1		;
		BCS	?3			;
		DEC	DIVISOR+1		;
?3
		JSR	SDIVIDE			;SIGNED DIVIDE

		LDA	WX1+0			;ADD IN WX1
		CLC				;
		ADC	QUOTIENT+0		;
		STA	X3+0			;

		RTS

	ELSE

		LDA	WY2+0			;CALC (WY2 - WY1)
		SEC				;
		SBC	WY1+0			;
		BCS	?3			;

		EOR	#$FF			;SIGNED DIVISOR
		INC	A			;
		TAX				;
		CPX	#2			;
		BGE	?21			;

		LDA	WX1+0			;ADD IN WX1
		SEC				;
		SBC	MATHH			;
		STA	X3+0			;

		RTS				;
?21
		LDA	RECIPTABLELO,X		;
		EOR	#$FF			;
		CLC				;
		ADC	#$01			;
		STA	MATHD			;
		LDA	RECIPTABLEHI,X		;
		EOR	#$FF			;
		ADC	#$00			;
		STA	MATHC			;
		BRA	?4			;
?3
		TAX				;UNSIGNED DIVISOR
		CPX	#2			;
		BGE	?31			;

		LDA	WX1+0			;ADD IN WX1
		CLC				;
		ADC	MATHH			;
		STA	X3+0			;

		RTS				;
?31
		LDA	RECIPTABLELO,X		;
		STA	MATHD			;
		LDA	RECIPTABLEHI,X		;
		STA	MATHC			;
?4
		MOVEW	MATHH,MATHB		;
		WAITMATH			;

		LDA	WX1+0			;ADD IN WX1
		CLC				;
		ADC	MATHF			;
		STA	X3+0			;

		RTS				;

	ENDIF

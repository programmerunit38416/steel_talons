*
* BOOT2.ASM - second stage cart loader for emulator/flash-cart images
*
* The 410 byte ROM_HEADER_SIZE area of TALONS.ROM was left empty for the
* Atari-encrypted boot header added at mastering.  For a bootable image we
* use the publicly released cc65 encrypted first stage (Karri Kaksonen,
* zlib license), which copies the next 151 bytes of the cart to $FB68 and
* jumps there.  This loader then reads directory entry 1 (the main program,
* TALONS.BIN) and runs it from its load address, the way the original
* header did.
*
		CHIP	65C02
DEFS		SECTION	REF_ONLY
		INCLUDE	\PR\LYNX\INCLUDE\HARDDEFS.I
		INCLUDE	CARTDEFS.INC
*
STAGE1SIZE	EQU	52			;ENCRYPTED FIRST STAGE
STAGE2SIZE	EQU	151			;THIS LOADER
IODAT_BOOT	EQU	$0B			;IODAT VALUE SET BY STAGE 1
*
PTR		EQU	$F0			;DESTINATION POINTER
POS		EQU	$F2			;BYTES TO END OF ROM PAGE (NEGATED)
PAGE		EQU	$F4			;CURRENT ROM PAGE
ENTRY		EQU	$F8			;DIRECTORY ENTRY (8 BYTES)
		ENDS
*
		CODE
		ORG	$FB68
START
*
* SKIP TO DIRECTORY ENTRY 1 (STILL IN ROM PAGE 0)
*
		LDX	#ROM_HEADER_SIZE+ROMDIR_ENTRY_SIZE-STAGE1SIZE-STAGE2SIZE
?SKIPDIR
		LDA	RCART_0
		DEX
		BNE	?SKIPDIR
?READENTRY
		LDA	RCART_0
		STA	ENTRY,X
		INX
		CPX	#ROMDIR_ENTRY_SIZE
		BNE	?READENTRY
*
* SELECT THE FILE'S PAGE AND SKIP TO ITS OFFSET
*
		LDA	ENTRY+ROMDIR_PAGE
		STA	PAGE
		JSR	SELPAGE
		LDX	ENTRY+ROMDIR_OFFSET
		LDY	ENTRY+ROMDIR_OFFSET+1
		INY
		INX
		BRA	?SKIPNEXT
?SKIPOFF
		JSR	RDBYTE
?SKIPNEXT
		DEX
		BNE	?SKIPOFF
		DEY
		BNE	?SKIPOFF
*
* READ THE FILE TO ITS LOAD ADDRESS AND RUN IT
*
		LDA	ENTRY+ROMDIR_DEST
		STA	PTR
		LDA	ENTRY+ROMDIR_DEST+1
		STA	PTR+1
		LDX	ENTRY+ROMDIR_SIZE
		LDY	ENTRY+ROMDIR_SIZE+1
		INY
		INX
		BRA	?READNEXT
?READ
		JSR	RDBYTE
		STA	(PTR)
		INC	PTR
		BNE	?READNEXT
		INC	PTR+1
?READNEXT
		DEX
		BNE	?READ
		DEY
		BNE	?READ
		JMP	(ENTRY+ROMDIR_DEST)
*
* READ ONE BYTE, MOVING TO THE NEXT ROM PAGE AT A PAGE BOUNDARY
*
RDBYTE
		LDA	RCART_0
		INC	POS
		BNE	?DONE
		INC	POS+1
		BNE	?DONE
		PHA
		INC	PAGE
		LDA	PAGE
		JSR	SELPAGE
		PLA
?DONE
		RTS
*
* SELPAGE - A = ROM PAGE.  SHIFTS THE PAGE NUMBER INTO THE CART ADDRESS
* COUNTER (SAME SEQUENCE AS THE CC65 LOADER)
*
SELPAGE
		PHX
		PHY
		LDY	#IODAT_BOOT&$FC
		LDX	#(IODAT_BOOT&$FC)+CART_ADDR_DATA
		SEC
		BRA	?SHIFT
?BIT
		BCC	?ZERO
		STX	IODAT
		CLC
?ZERO
		INX
		STX	SYSCTL1
		DEX
?SHIFT
		STX	SYSCTL1
		ROL	A
		STY	IODAT
		BNE	?BIT
		LDA	#IODAT_BOOT
		STA	IODAT
		STZ	POS
		LDA	#-(>ROMPAGESIZE)
		STA	POS+1
		PLY
		PLX
		RTS
ENDLOADER
	IF	ENDLOADER-START>STAGE2SIZE
	.BYTE	OH_NO_LOADER_TOO_BIG
	ENDIF
		BLKB	STAGE2SIZE-(ENDLOADER-START),0

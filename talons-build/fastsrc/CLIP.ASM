*
* CLIP ENDPOINTS FOR 3D POINTS
*
* ENTRY:
*	WX1,WY1,WZ1	FIRST 3D ENDPOINT
*	WX2,WY2,WZ2	SECOND 3D ENDPOINT
* EXIT:
*	WX1,WY1,WZ1	CLIPPED IF NECESSARY
*	WX2,WY2,WZ2	CLIPPED IF NECESSARY
*	ACC	-1	CANNOT CLIP END POINTS (BOTH BAD)
*		0	BOTH OKAY
*		1	CLIPPED WX1,WY1,WZ1 ONLY
*		2	CLIPPED WX2,WY2,WZ2 ONLY
*
CLIP3D@
		SIGNEDMATH

		LDA	WX1+1			;X1 IN BACK?
		BMI	?11			;YES
		CMPW	WINDOWDEPTH,WX1		;
		BLT	?11			;YES
		JMP	OKAYX1_3D		;NO - TRY X2
?11
		LDA	WX2+1			;X2 IN BACK?
		BMI	?12			;YES
		CMPW	WINDOWDEPTH,WX2		;
		BGE	CLIPX1_3D		;NO - CLIP X1 ONLY
?12
		LDA	#-1			;RETURN CODE
		RTS				;EXIT
CLIPX1_3D
		SUBW	WY1,WY2,MATHD		;(WY1 - WY2)
		SUBW	WINDOWDEPTH,WX2,MATHB	;(WINDOWDEPTH - WX2) START
		SUBW	WX1,WX2,DIVISOR		;(WX1 - WX2) WHILE IT RUNS
		JSR	SDIVPREP@		;
		WAITMATH			;

		MOVEL	MATHH,DIVIDEND		;
		JSR	SDIVGO@			;
		SUBW	WZ1,WZ2,FACTOR1		;(WZ1 - WZ2) WHILE IT RUNS
		SUBW	WINDOWDEPTH,WX2,FACTOR2	;(WINDOWDEPTH - WX2)
		JSR	SDIVEND@		;

		MOVEW	FACTOR1,MATHD		;START (WZ1 - WZ2) * (WD - WX2)
		MOVEW	FACTOR2,MATHB		;
		ADDW	QUOTIENT+0,WY2,WY1	;SET NEW WY1 WHILE IT RUNS
		WAITMATH			;

		MOVEL	MATHH,DIVIDEND		;
		JSR	SDIVGO@			;
		MOVEW	WINDOWDEPTH,WX1		;SET NEW WX1 WHILE IT RUNS
		JSR	SDIVEND@		;

		ADDW	QUOTIENT+0,WZ2,WZ1	;SET NEW WZ1

		LDA	#1			;CLIPPED WX1,WY1,WZ1
		RTS				;EXIT
OKAYX1_3D
		LDA	WX2+1			;X2 IN BACK?
		BMI	CLIPX2_3D		;YES - CLIP X2
		CMPW	WINDOWDEPTH,WX2		;
		BLT	CLIPX2_3D		;YES

		LDA	#0			;BOTH OKAY
		RTS				;EXIT
CLIPX2_3D
		SUBW	WY2,WY1,MATHD		;(WY2 - WY1)
		SUBW	WINDOWDEPTH,WX1,MATHB	;(WINDOWDEPTH - WX1) START
		SUBW	WX2,WX1,DIVISOR		;(WX2 - WX1) WHILE IT RUNS
		JSR	SDIVPREP@		;
		WAITMATH			;

		MOVEL	MATHH,DIVIDEND		;
		JSR	SDIVGO@			;
		SUBW	WZ2,WZ1,FACTOR1		;(WZ2 - WZ1) WHILE IT RUNS
		SUBW	WINDOWDEPTH,WX1,FACTOR2	;(WINDOWDEPTH - WX1)
		JSR	SDIVEND@		;

		MOVEW	FACTOR1,MATHD		;START (WZ2 - WZ1) * (WD - WX1)
		MOVEW	FACTOR2,MATHB		;
		ADDW	QUOTIENT+0,WY1,WY2	;SET NEW WY2 WHILE IT RUNS
		WAITMATH			;

		MOVEL	MATHH,DIVIDEND		;
		JSR	SDIVGO@			;
		MOVEW	WINDOWDEPTH,WX2		;SET NEW WX2 WHILE IT RUNS
		JSR	SDIVEND@		;

		ADDW	QUOTIENT+0,WZ1,WZ2	;SET NEW WZ2

		LDA	#2			;CLIPPED WX2,WY2,WZ2
		RTS				;EXIT
*
* CLIP 2D ENDPOINTS ON LEFT AND RIGHT ONLY
*
* ENTRY:
*	_X1,_Y1		FIRST 2D END POINT
*	_X2,_Y2		SECOND 2D END POINT
* EXIT:
*	_X1,_Y1		CLIPPED IF NECCESSARY
*	_X2,_Y2		CLIPPED IF NECCESSARY
*	ACC	-1	CANNOT CLIP END POINTS (BOTH BAD)
*		0	BOTH END POINTS OKAY
*		1	CLIPPED FIRST END POINT ONLY
*		2	CLIPPED SECOND END POINT ONLY
*		3	CLIPPED BOTH END POINTS
*
CLIP2DX@
		SIGNEDMATH			;SET SIGNED MATH

		LDA	_X1+1			;X1 LEFT?
		BPL	X1NOTLEFT1		;NO
X1ISLEFT1
		LDA	_X2+1			;X2 LEFT?
		BPL	X2NOTLEFT1		;NO
X2ISLEFT1
		LDA	#-1			;CANNOT CLIP END POINTS
		RTS				;
X2NOTLEFT1
		JSR	CLIPX1LEFT		;CLIP X1 AGAINST LEFT SIDE

		CMPIW	CLIPCOLS+1,_X2		;X2 RIGHT?
		BGE	X2ISRIGHT1		;YES

		LDA	#1			;X1 CLIPPED ONLY
		RTS				;
X2ISRIGHT1
		JSR	CLIPX2RIGHT		;CLIP X2 AGAINST RIGHT SIDE

		LDA	#1+2			;X1 AND X2 CLIPPED
		RTS				;
X1NOTLEFT1
		CMPIW	CLIPCOLS+1,_X1		;X1 RIGHT?
		BLT	X1NOTRIGHT2		;NO
X1ISRIGHT2
		LDA	_X2+1			;
		BMI	X2NOTRIGHT2		;

		CMPIW	CLIPCOLS+1,_X2		;X2 RIGHT?
		BLT	X2NOTRIGHT2		;NO
X2ISRIGHT2
		LDA	#-1			;CANNOT CLIP END POINTS
		RTS				;
X2NOTRIGHT2
		JSR	CLIPX1RIGHT		;CLIP X1 AGAINST RIGHT SIDE

		LDA	_X2+1			;X2 LEFT?
		BMI	X2ISLEFT2		;YES

		LDA	#1			;X1 CLIPPED ONLY
		RTS				;
X2ISLEFT2
		JSR	CLIPX2LEFT		;CLIP X2 AGAINST LEFT SIDE

		LDA	#1+2			;X1 AND X2 CLIPPED
		RTS				;
X1NOTRIGHT2
		LDA	_X2+1			;X2 LEFT?
		BPL	X2NOTLEFT3		;NO
X2ISLEFT3
		JSR	CLIPX2LEFT		;CLIP X2 AGAINST LEFT SIDE

		LDA	#2			;X2 CLIPPED ONLY
		RTS				;
X2NOTLEFT3
		CMPIW	CLIPCOLS+1,_X2		;X2 RIGHT?
		BLT	X2NOTRIGHT3		;NO
X2ISRIGHT3
		JSR	CLIPX2RIGHT		;CLIP X2 AGAINST RIGHT SIDE

		LDA	#2			;X2 CLIPPED ONLY
		RTS				;
X2NOTRIGHT3
		LDA	#0			;BOTH POINTS OKAY
		RTS				;
*
* CLIP _X2 AGAINST LEFT SIDE
*
CLIPX2LEFT
		SUBW	_Y2,_Y1,MATHD		;(Y2 - Y1)
		SUBIW	00,_X1,MATHB		;(00 - X1) START
		SUBW	_X2,_X1,DIVISOR		;(X2 - X1) WHILE IT RUNS
		JSR	SDIVPREP@		;
		WAITMATH			;

		MOVEL	MATHH,DIVIDEND		;
		JSR	SDIVGO@			;
		CLRW	_X2			;SET NEW X2 WHILE IT RUNS
		JSR	SDIVEND@		;

		ADDW	QUOTIENT+0,_Y1,_Y2	;SET NEW Y2

		RTS
*
* CLIP _X2 AGAINST RIGHT SIDE
*
CLIPX2RIGHT
		SUBW	_Y2,_Y1,MATHD		;(Y2 - Y1)
		SUBIW	CLIPCOLS,_X1,MATHB	;(CLIPCOLS - X1) START
		SUBW	_X2,_X1,DIVISOR		;(X2 - X1) WHILE IT RUNS
		JSR	SDIVPREP@		;
		WAITMATH			;

		MOVEL	MATHH,DIVIDEND		;
		JSR	SDIVGO@			;
		MOVEIW	CLIPCOLS,_X2		;SET NEW X2 WHILE IT RUNS
		JSR	SDIVEND@		;

		ADDW	QUOTIENT+0,_Y1,_Y2	;SET NEW Y2

		RTS
*
* CLIP _X1 AGAINST LEFT SIDE
*
CLIPX1LEFT
		SUBW	_Y1,_Y2,MATHD		;(Y1 - Y2)
		SUBIW	00,_X2,MATHB		;(00 - X2) START
		SUBW	_X1,_X2,DIVISOR		;(X1 - X2) WHILE IT RUNS
		JSR	SDIVPREP@		;
		WAITMATH			;

		MOVEL	MATHH,DIVIDEND		;
		JSR	SDIVGO@			;
		CLRW	_X1			;SET NEW X1 WHILE IT RUNS
		JSR	SDIVEND@		;

		ADDW	QUOTIENT+0,_Y2,_Y1	;SET NEW Y1

		RTS
*
* CLIP _X1 AGAINST RIGHT SIDE
*
CLIPX1RIGHT
		SUBW	_Y1,_Y2,MATHD		;(Y1 - Y2)
		SUBIW	CLIPCOLS,_X2,MATHB	;(CLIPCOLS - X2) START
		SUBW	_X1,_X2,DIVISOR		;(X1 - X2) WHILE IT RUNS
		JSR	SDIVPREP@		;
		WAITMATH			;

		MOVEL	MATHH,DIVIDEND		;
		JSR	SDIVGO@			;
		MOVEIW	CLIPCOLS,_X1		;SET NEW X1 WHILE IT RUNS
		JSR	SDIVEND@		;

		ADDW	QUOTIENT+0,_Y2,_Y1	;SET NEW Y1

		RTS
*
* CLIP 2D ENDPOINTS ON TOP AND BOTTOM ONLY
*
* ENTRY:

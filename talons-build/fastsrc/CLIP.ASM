Y2ISTOP3
		JSR	CLIPY2TOP		;CLIP Y2 AGAINST TOP SIDE

		LDA	#2			;Y2 CLIPPED ONLY
		RTS				;
Y2NOTTOP3
		CMPIW	CLIPROWS+1,__Y2		;Y2 BOTTOM?
		BLT	Y2NOTBOTTOM3		;NO
Y2ISBOTTOM3
		JSR	CLIPY2BOTTOM		;CLIP Y2 AGAINST BOTTOM SIDE

		LDA	#2			;Y2 CLIPPED ONLY
		RTS				;
Y2NOTBOTTOM3
		LDA	#0			;BOTH POINTS OKAY
		RTS				;
*
* CLIP __Y2 AGAINST TOP SIDE
*
CLIPY2TOP

		RTS				;
Y2NOTTOP1
		JSR	CLIPY1TOP		;CLIP Y1 AGAINST TOP SIDE

		CMPIW	CLIPROWS+1,__Y2		;Y2 BOTTOM?
		BGE	Y2ISBOTTOM1		;YES

		LDA	#1			;Y1 CLIPPED ONLY
		RTS				;
Y2ISBOTTOM1
		JSR	CLIPY2BOTTOM		;CLIP Y2 AGAINST BOTTOM SIDE

		LDA	#1+2			;Y1 AND Y2 CLIPPED
		RTS				;
Y1NOTTOP1

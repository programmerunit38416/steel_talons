*
* SIGNED 32 BIT = 32 BIT / 16 BIT DIVIDE, IN THREE PARTS SO THE CALLER
* CAN WORK WHILE SUZY DIVIDES:
*
*	SDIVPREP@	ABS(DIVISOR) AND ITS SIGN.  DOES NOT TOUCH SUZY, SO IT
*			CAN RUN WHILE A MULTIPLY IS IN PROGRESS.
*	SDIVGO@		START DIVIDEND / DIVISOR (SUZY MUST BE IDLE)
*	SDIVEND@	WAIT, QUOTIENT = SIGNED RESULT
*
* DIVIDE BY ZERO RETURNS THE DIVIDEND.
*
SDIVPREP@
		STZ	DIVSIGN			;
		LDA	DIVISOR+0		;
		LDX	DIVISOR+1		;SIGNED?
		BPL	?1			;NO

		DEC	DIVSIGN			;
		EOR	#$FF			;NEGATE
		CLC				;
		ADC	#$01			;
		PHA				;
		TXA				;
		EOR	#$FF			;
		ADC	#$00			;
		TAX				;
		PLA				;
?1
		STA	DIVABS+0		;
		STX	DIVABS+1		;
		RTS
*
SDIVGO@
		LDA	DIVABS+0		;DIVIDE BY 0?
		ORA	DIVABS+1		;
		BNE	?1			;NO

		MOVEW	DIVIDEND,QUOTIENT	;RETURN DIVIDEND
		MOVEW	DIVIDEND+2,QUOTIENT+2	;
		LDA	#1			;(TELLS SDIVEND@)
		STA	SIGNFLAG		;
		RTS				;
?1
		LDA	DIVABS+0		;SET UP DIVISOR
		STA	MATHP			;
		LDA	DIVABS+1		;
		STA	MATHN			;

		LDA	DIVSIGN			;
		STA	SIGNFLAG		;
		LDA	DIVIDEND+3		;SIGNED?
		BPL	?4			;NO

		LDA	SIGNFLAG		;TOGGLE FLAG
		EOR	#$FF			;
		STA	SIGNFLAG		;

		LDA	DIVIDEND+0		;
		EOR	#$FF			;
		CLC				;
		ADC	#$01			;
		STA	MATHH			;
		LDA	DIVIDEND+1		;
		EOR	#$FF			;
		ADC	#$00			;
		STA	MATHG			;
		LDA	DIVIDEND+2		;
		EOR	#$FF			;
		ADC	#$00			;
		STA	MATHF			;
		LDA	DIVIDEND+3		;
		EOR	#$FF			;
		ADC	#$00			;
		STA	MATHE			;START DIVIDE
		RTS
?4
		LDA	DIVIDEND+0		;
		STA	MATHH			;
		LDA	DIVIDEND+1		;
		STA	MATHG			;
		LDA	DIVIDEND+2		;
		STA	MATHF			;
		LDA	DIVIDEND+3		;
		STA	MATHE			;START DIVIDE
		RTS
*
SDIVEND@
		LDA	SIGNFLAG		;DIVIDE BY 0?
		CMP	#1			;
		BEQ	?9			;YES - QUOTIENT IS SET

		WAITMATH			;WAIT UNTIL COMPLETE

		LDA	SIGNFLAG		;SIGNED QUOTIENT?
		BEQ	?6			;NO

		LDA	MATHD			;GET QUOTIENT
		EOR	#$FF			;
		CLC				;
		ADC	#$01			;
		STA	QUOTIENT+0		;
		LDA	MATHC			;
		EOR	#$FF			;
		ADC	#$00			;
		STA	QUOTIENT+1		;
		LDA	MATHB			;
		EOR	#$FF			;
		ADC	#$00			;
		STA	QUOTIENT+2		;
		LDA	MATHA			;
		EOR	#$FF			;
		ADC	#$00			;
		STA	QUOTIENT+3		;
		RTS				;
?6
		LDA	MATHD			;GET QUOTIENT
		STA	QUOTIENT+0		;
		LDA	MATHC			;
		STA	QUOTIENT+1		;
		LDA	MATHB			;
		STA	QUOTIENT+2		;
		LDA	MATHA			;
		STA	QUOTIENT+3		;
?9
		RTS

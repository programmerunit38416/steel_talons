*
* DRAW ONE POLYGON FOR AN OBJECT
*
* ENTRY:
*	OBJECTX		OBJECT'S RELATIVE X COORDINATE
*	OBJECTY		OBJECT'S RELATIVE Y COORDINATE
*	OBJECTZ		OBJECT'S RELATIVE Z COORDINATE
*	NPOINTS		NUMBER OF INCOMING 3D POINTS
*	POINTBUFF	INCOMING 3D POINT NUMBERS
*
DRAWONEPOLY@
		LDA	NPOINTS			;SAVE NUMBER OF POINTS TO READ
		STA	READPOINTS		;

		LDA	#0			;INIT NEW POINTS COUNT
		STA	NPTS			;

		LDA	#00			;INIT OTHER VARS
		STA	PSAVEDPTSX		;
		STA	PSAVEDPTSY		;

		LDA	#00			;
		STA	LINEINDEX		;INIT WRITE VARIABLES
		STA	LINECOUNT		;
		STA	POINTBUFFINDEX		;INIT POINT INDEX
PREPONEPOLYLOOP
		LDA	READPOINTS		;DONE?
		BNE	PREPONEPOLYCONT		;NO
		JMP	PREPONEPOLYDONE		;YES
PREPONEPOLYCONT
		LDY	POINTBUFFINDEX		;POINT TO THIS POINT
		LDA	POINTBUFF,Y		;GET 1ST POINT
		TAX				;

		LDA	POINTLISTXL,X		;GET 3D COORDINATE
		STA	WX1+0			;
		LDA	POINTLISTXH,X		;
		STA	WX1+1			;

		LDA	POINTLISTYL,X		;
		STA	WY1+0			;
		LDA	POINTLISTYH,X		;
		STA	WY1+1			;

		LDA	POINTLISTZL,X		;
		STA	WZ1+0			;
		LDA	POINTLISTZH,X		;
		STA	WZ1+1			;

		LDA	SCREENXYLISTXL,X	;GET 2D COORDINATE
		STA	X1+0			;
		LDA	SCREENXYLISTXH,X	;
		STA	X1+1			;
		LDA	SCREENXYLISTYL,X	;
		STA	Y1+0			;
		LDA	SCREENXYLISTYH,X	;
		STA	Y1+1			;

		INY				;

		LDA	READPOINTS		;LAST POINT?
		CMP	#1			;
		BNE	NOTLASTRP		;NO

		STZ	POINTBUFFINDEX		;YES - USE ORG 1ST FOR 2ND PNT
		LDY	#00			;
NOTLASTRP
		LDA	POINTBUFF,Y		;GET 2ND POINT
		TAX				;

		LDA	POINTLISTXL,X		;GET 3D COORDINATE
		STA	WX2+0			;
		LDA	POINTLISTXH,X		;
		STA	WX2+1			;

		LDA	POINTLISTYL,X		;
		STA	WY2+0			;
		LDA	POINTLISTYH,X		;
		STA	WY2+1			;

		LDA	POINTLISTZL,X		;
		STA	WZ2+0			;
		LDA	POINTLISTZH,X		;
		STA	WZ2+1			;

		LDA	SCREENXYLISTXL,X	;GET 2D COORDINATE
		STA	X2+0			;
		LDA	SCREENXYLISTXH,X	;
		STA	X2+1			;
		LDA	SCREENXYLISTYL,X	;
		STA	Y2+0			;
		LDA	SCREENXYLISTYH,X	;
		STA	Y2+1			;

		JSR	CLIP3D@			;CLIP 3D VIEW
		STA	CLIP3DRESULT		;SAVE RETURN CODE

		CMP	#-1			;BOTH BAD?
		BNE	TRYADDLINE		;NO
		JMP	SKIPADDLINE		;YES - AVOID THIS LINE
TRYADDLINE
		LDA	CLIP3DRESULT		;GET RETURN CODE
		CMP	#0			;BOTH OKAY?
		BNE	ONEWASBAD		;NO
		JMP	ADDTHELINE		;YES - ADD THE LINE
ONEWASBAD
		LDA	NPTS			;FIRST ONE?
		BNE	THISISOLD		;NO
		JMP	THISISNEW		;YES
THISISOLD
		LDA	#0			;RESET
		STA	NPTS			;

		LDA	CLIP3DRESULT		;GET RETURN CODE
		CMP	#1			;1 CLIPPED?
		BNE	TWOCLIPPED1		;NO
ONECLIPPED1
		JSR	GETSCREENXY1@		;GET X1,Y1

		MOVEW	X1,_X2			;SET END POINTS
		MOVEW	Y1,_Y2			;
		MOVEW	NX,_X1			;
		MOVEW	NY,_Y1			;
		INC	READPOINTS		;CANNOT BE LAST POINT YET
		JSR	ADDLINE2DX@		;ADD THE LINE
		DEC	READPOINTS		;MAY BE LAST POINT NOW

		MOVEW	X1,_X1			;SET END POINTS
		MOVEW	Y1,_Y1			;
		MOVEW	X2,_X2			;
		MOVEW	Y2,_Y2			;
		JSR	ADDLINE2DX@		;ADD THE LINE

		JMP	SKIPADDLINE		;
TWOCLIPPED1
		JSR	GETSCREENXY2@		;GET X2,Y2

		MOVEW	X1,_X1			;SET END POINTS
		MOVEW	Y1,_Y1			;
		MOVEW	X2,_X2			;
		MOVEW	Y2,_Y2			;
		INC	READPOINTS		;CANNOT BE LAST POINT YET
		JSR	ADDLINE2DX@		;ADD THE LINE
		DEC	READPOINTS		;MAY BE LAST POINT NOW

		MOVEW	X2,_X1			;SET END POINTS
		MOVEW	Y2,_Y1			;
		MOVEW	NX,_X2			;
		MOVEW	NY,_Y2			;
		JSR	ADDLINE2DX@		;ADD THE LINE

		JMP	SKIPADDLINE		;
THISISNEW
		LDA	CLIP3DRESULT		;1 CLIPPED?
		CMP	#1			;
		BNE	TWOCLIPPED2		;NO
ONECLIPPED2
		JSR	GETSCREENXY1@		;GET X1,Y1

		MOVEW	X1,NX			;SAVE POINT 1
		MOVEW	Y1,NY			;
		INC	NPTS			;
		BRA	ADDTHELINE		;ADD THE CURRENT LINE
TWOCLIPPED2
		JSR	GETSCREENXY2@		;GET X2,Y2

		MOVEW	X2,NX			;SAVE POINT 2
		MOVEW	Y2,NY			;
		INC	NPTS			;
ADDTHELINE
		MOVEW	X1,_X1			;SET END POINTS
		MOVEW	Y1,_Y1			;
		MOVEW	X2,_X2			;
		MOVEW	Y2,_Y2			;
		JSR	ADDLINE2DX@		;ADD THE LINE
SKIPADDLINE
		LDA	NPOINTS			;JUST TWO?
		CMP	#2			;(I.E. LINE)
		BEQ	PREPONEPOLYDONE		;YES

		DEC	READPOINTS		;NEXT INCOMING 3D POINT
		INC	POINTBUFFINDEX		;

		JMP	PREPONEPOLYLOOP		;
PREPONEPOLYDONE
*
* CHECK FOR ADDING LAST LINES
*
		LDA	PSAVEDPTSX		;TWO MORE POINTS AVAILABLE?
		CMP	#3			;
		BNE	NOLASTLINEX		;NO

		MOVEB	SX2,__X1		;SET END POINTS
		MOVEW	SY2,__Y1		;
		MOVEB	SX1,__X2		;
		MOVEW	SY1,__Y2		;
		JSR	ADDLINE2DY@		;ADD THIS LINE
NOLASTLINEX
		LDA	PSAVEDPTSY		;TWO MORE POINTS AVAILABLE?
		CMP	#3			;
		BNE	NOLASTLINEY		;NO

		MOVEB	SSX2,___X1		;SET END POINTS
		MOVEB	SSY2,___Y1		;
		MOVEB	SSX1,___X2		;
		MOVEB	SSY1,___Y2		;
		JSR	ADDTHISLINE@		;ADD THIS LINE
NOLASTLINEY
		LDA	LINECOUNT		;ANY LINES?
		BNE	GOTLINES		;YES

		RTS				;DONE
GOTLINES
		CMP	#2			;AT LEAST TWO LINES TO SORT?
		BLT	SORTDONE		;NO - ALREADY SORTED

		DEC	A			;COUNT - 1
		STA	COUNTER1		;

		LDY	#00			;INIT INDEX
		STY	COUNTER2		;INIT FURTHEST INDEX
SORTLOOP
		LDX	LINEINDEXES,Y		;GET FIRST INDEX

		LDA	LINELIST+1,X		;GET FIRST Y COORD
		STA	WORK1+0			;
		LDA	LINELIST+3,X		;
		STA	WORK1+1			;

		LDX	LINEINDEXES+1,Y		;GET SECOND INDEX

		LDA	WORK1+0			;Y1 IN ASCENDING ORDER?
		CMP	LINELIST+1,X		;
		BLT	SORTNEXT		;YES
		BNE	SORTSWAP		;NO

		LDA	WORK1+1			;Y2 IN ASCENDING ORDER?
		CMP	LINELIST+3,X		;
		BEQ	SORTNEXT		;YES
		BLT	SORTNEXT		;YES
SORTSWAP
		LDA	LINEINDEXES+0,Y		;SWAP INDEXES
		PHA				;
		LDA	LINEINDEXES+1,Y		;
		STA	LINEINDEXES+0,Y		;
		PLA				;
		STA	LINEINDEXES+1,Y		;

		CPY	#00			;AT TOP OF LIST?
		BEQ	SORTNEXT		;YES

		DEY				;PREVIOUS ENTRY
		BRA	SORTLOOP		;
SORTNEXT
		INC	COUNTER2		;NEXT ENTRY
		LDY	COUNTER2		;
		DEC	COUNTER1		;
		BNE	SORTLOOP		;
SORTDONE
		JMP	DRAWSPRPOLY@		;DRAW HARDWARE POLYS
*
* ADD LINE _X1,_Y1 AND _X2,_Y2 TO 2DX CLIPPING
*
ADDLINE2DX@
		LDA	#00			;INIT FLAGS
		STA	SAVEDCURRENTX		;

		LDA	PSAVEDPTSX		;
		STA	SAVEDPTSX		;

		JSR	CLIP2DX@		;CLIP 2D LEFT AND RIGHT
		STA	CLIP2DXRESULT		;
		CMP	#-1			;BOTH BAD?
		BNE	NOTBOTHBAD2DX		;NO

		RTS				;SKIP THIS LINE COMPLETELY
NOTBOTHBAD2DX
		CMP	#00			;BOTH GOOD?
		BNE	ONEWASBAD2DX		;NO

		MOVEB	_X1,__X1		;SET END POINTS
		MOVEW	_Y1,__Y1		;
		MOVEB	_X2,__X2		;
		MOVEW	_Y2,__Y2		;
		JMP	ADDLINE2DY@		;YES - ADD THIS LINE
ONEWASBAD2DX
		LDA	CLIP2DXRESULT		;GET RETURN CODE
		BIT	#1			;CLIPPED 1?
		BNE	?1			;YES
		JMP	DONE12DX		;NO
?1
		LDA	PSAVEDPTSX		;PREVIOUSLY SAVED POINT 2?
		BIT	#2			;
		BEQ	SAVE12DX		;NO - SAVE POINT 1

		LDA	SAVEDPTSX		;REMOVE SAVED POINT
		AND	#\2			;
		STA	SAVEDPTSX		;

		MOVEB	_X1,__X2		;SET END POINTS
		MOVEW	_Y1,__Y2		;
		MOVEB	SX2,__X1		;
		MOVEW	SY2,__Y1		;
		JSR	ADDLINE2DY@		;ADD SAVED LINE

		MOVEB	_X1,__X1		;SET END POINTS
		MOVEW	_Y1,__Y1		;
		MOVEB	_X2,__X2		;
		MOVEW	_Y2,__Y2		;
		JSR	ADDLINE2DY@		;ADD CURRENT LINE

		INC	SAVEDCURRENTX		;INCREMENT FLAG
		BRA	DONE12DX		;
SAVE12DX
		MOVEB	_X1,SX1			;SAVE POINT 1
		MOVEW	_Y1,SY1			;

		LDA	SAVEDPTSX		;
		ORA	#1			;
		STA	SAVEDPTSX		;
DONE12DX
		LDA	CLIP2DXRESULT		;GET RETURN CODE
		BIT	#2			;CLIPPED 2?
		BEQ	DONE22DX		;NO

		LDA	PSAVEDPTSX		;PREVIOUSLY SAVED POINT 1?
		BIT	#1			;
		BEQ	SAVE22DX		;NO - SAVE POINT 2

		LDA	READPOINTS		;LAST POINT?
		CMP	#1			;
		BNE	SAVE22DX		;NO SAVE THIS POINT

		LDA	SAVEDPTSX		;REMOVE SAVED POINT
		AND	#\1			;
		STA	SAVEDPTSX		;

		LDA	SAVEDCURRENTX		;ALREADY SAVED THIS ONE?
		BNE	SKIP2NDSAVEX		;YES

		MOVEB	_X1,__X1		;SET END POINTS
		MOVEW	_Y1,__Y1		;
		MOVEB	_X2,__X2		;
		MOVEW	_Y2,__Y2		;
		JSR	ADDLINE2DY@		;ADD CURRENT LINE
		INC	SAVEDCURRENTX		;INCREMENT FLAG
SKIP2NDSAVEX
		MOVEB	_X2,__X1		;SET END POINTS
		MOVEW	_Y2,__Y1		;
		MOVEB	SX1,__X2		;
		MOVEW	SY1,__Y2		;
		JSR	ADDLINE2DY@		;ADD SAVED LINE
		BRA	DONE22DX		;
SAVE22DX
		MOVEB	_X2,SX2			;SAVE POINT 2
		MOVEW	_Y2,SY2			;

		LDA	SAVEDPTSX		;
		ORA	#2			;
		STA	SAVEDPTSX		;
DONE22DX
		LDA	SAVEDPTSX		;SET NEW SAVES
		STA	PSAVEDPTSX		;

		LDA	SAVEDCURRENTX		;DID WE SAVE THE CURRENT LINE?
		BNE	?1			;YES

		MOVEB	_X1,__X1		;SET END POINTS
		MOVEW	_Y1,__Y1		;
		MOVEB	_X2,__X2		;
		MOVEW	_Y2,__Y2		;
		BRA	ADDLINE2DY@		;ADD CURRENT LINE
?1
		RTS				;EXIT
*
* ADD LINE __X1,__Y1 AND __X2,__Y2 TO 2DY CLIPPING
*
ADDLINE2DY@
		STZ	__X1+1			;CLEAR HIGH BYTE OF X VALUES
		STZ	__X2+1			;

		LDA	#00			;INIT FLAGS
		STA	SAVEDCURRENTY		;

		LDA	PSAVEDPTSY		;
		STA	SAVEDPTSY		;

		JSR	CLIP2DY@		;CLIP 2D TOP AND BOTTOM
		STA	CLIP2DYRESULT		;SAVE RESULT
		CMP	#-1			;BOTH BAD?
		BNE	NOTBOTHBAD2DY		;NO

		RTS				;SKIP THIS LINE COMPLETELY
NOTBOTHBAD2DY
		CMP	#00			;BOTH POINTS GOOD?
		BNE	ONEWASBAD2DY		;NO

		MOVEB	__X1,___X1		;SET END POINTS
		MOVEB	__Y1,___Y1		;
		MOVEB	__X2,___X2		;
		MOVEB	__Y2,___Y2		;
		JMP	ADDTHISLINE@		;ADD THIS LINE
ONEWASBAD2DY
		LDA	CLIP2DYRESULT		;GET RETURN CODE
		BIT	#1			;CLIPPED 1?
		BNE	?1			;YES
		JMP	DONE12DY		;NO
?1
		LDA	PSAVEDPTSY		;PREVIOUSLY SAVED POINT 2?
		BIT	#2			;
		BEQ	SAVE12DY		;NO - SAVE POINT 1

		LDA	SAVEDPTSY		;REMOVE SAVED POINT
		AND	#\2			;
		STA	SAVEDPTSY		;

		MOVEB	__X1,___X2		;SET END POINTS
		MOVEB	__Y1,___Y2		;
		MOVEB	SSX2,___X1		;
		MOVEB	SSY2,___Y1		;
		JSR	ADDTHISLINE@		;ADD SAVED LINE

		MOVEB	__X1,___X1		;SET END POINTS
		MOVEB	__Y1,___Y1		;
		MOVEB	__X2,___X2		;
		MOVEB	__Y2,___Y2		;
		JSR	ADDTHISLINE@		;ADD CURRENT LINE
		INC	SAVEDCURRENTY		;INCREMENT FLAG
		BRA	DONE12DY		;
SAVE12DY
		MOVEB	__X1,SSX1		;SAVE POINT 1
		MOVEB	__Y1,SSY1		;

		LDA	SAVEDPTSY		;
		ORA	#1			;
		STA	SAVEDPTSY		;
DONE12DY
		LDA	CLIP2DYRESULT		;GET RETURN CODE
		BIT	#2			;CLIPPED 2?
		BEQ	DONE22DY		;NO

		LDA	PSAVEDPTSY		;PREVIOUSLY SAVED POINT 1?
		BIT	#1			;
		BEQ	SAVE22DY		;NO - SAVE POINT 2

		LDA	READPOINTS		;LAST POINT?
		CMP	#1			;
		BNE	SAVE22DY		;NO SAVE THIS POINT

		LDA	SAVEDPTSY		;REMOVE SAVED POINT
		AND	#\1			;
		STA	SAVEDPTSY		;

		LDA	SAVEDCURRENTY		;ALREADY SAVED THIS ONE?
		BNE	SKIP2NDSAVEY		;YES

		MOVEB	__X1,___X1		;SET END POINTS
		MOVEB	__Y1,___Y1		;
		MOVEB	__X2,___X2		;
		MOVEB	__Y2,___Y2		;
		JSR	ADDTHISLINE@		;ADD CURRENT LINE
		INC	SAVEDCURRENTY		;INCREMENT FLAG
SKIP2NDSAVEY
		MOVEB	__X2,___X1		;SET NEW END POINTS
		MOVEB	__Y2,___Y1		;
		MOVEB	SSX1,___X2		;
		MOVEB	SSY1,___Y2		;
		JSR	ADDTHISLINE@		;ADD SAVED LINE
		BRA	DONE22DY		;
SAVE22DY
		MOVEB	__X2,SSX2		;SAVE POINT 2
		MOVEB	__Y2,SSY2		;

		LDA	SAVEDPTSY		;
		ORA	#2			;
		STA	SAVEDPTSY		;
DONE22DY
		LDA	SAVEDPTSY		;SET NEW SAVES
		STA	PSAVEDPTSY		;

		LDA	SAVEDCURRENTY		;DID WE SAVE THE CURRENT LINE?
		BNE	?1			;YES

		MOVEB	__X1,___X1		;SET END POINTS
		MOVEB	__Y1,___Y1		;
		MOVEB	__X2,___X2		;
		MOVEB	__Y2,___Y2		;
		BRA	ADDTHISLINE@		;ADD CURRENT LINE
?1
		RTS				;EXIT
*
* ADD LINE ___X1,___Y1 TO ___X2,___Y2 TO LIST
*
ADDTHISLINE@
		LDX	LINEINDEX		;GET CURRENT INDEX

		LDA	___Y1+0			;Y'S IN ORDER?
		CMP	___Y2+0			;
		BEQ	GOODORDER		;YES
		BLT	GOODORDER		;YES

		LDA	___X1+0			;SAVE END POINTS SWAPPED
		STA	LINELIST+2,X		;
		LDA	___Y1+0			;
		STA	LINELIST+3,X		;

		LDA	___X2+0			;
		STA	LINELIST+0,X		;
		LDA	___Y2+0			;
		STA	LINELIST+1,X		;

		BRA	INCTHECOUNT		;
GOODORDER
		LDA	___X1+0			;SAVE END POINTS
		STA	LINELIST+0,X		;
		LDA	___Y1+0			;
		STA	LINELIST+1,X		;

		LDA	___X2+0			;
		STA	LINELIST+2,X		;
		LDA	___Y2+0			;
		STA	LINELIST+3,X		;
INCTHECOUNT
		LDY	LINECOUNT		;SAVE INDEX FOR SORTING
		LDA	LINEINDEX		;
		STA	LINEINDEXES,Y		;

		INC	LINECOUNT		;INCREMENT COUNT

		LDA	LINEINDEX		;INCREMENT INDEX
		CLC				;
		ADC	#4			;
		STA	LINEINDEX		;

		RTS				;

*
* MATRIX TRANSFORMS FOR DRAWING OBJECTS. REPLACES THE ROTATE-ONE-AXIS-AT-
* A-TIME CODE (5 ROTATIONS = 20 MULTIPLIES PER POINT) WITH ONE 3X3 MATRIX
* PER OBJECT (9 MULTIPLIES PER POINT), AND THE CAMERA SPACE NORMALS WITH
* AN OBJECT SPACE HIDDEN SURFACE TEST.
*
* MATRICES ARE ROW MAJOR, 6 BYTES PER ROW, 16 BIT 1.15 FIXED POINT
* (ONE = 1.0).  ROWS 0-2 TAKE AN OBJECT POINT TO VIEW SPACE, ROW 3 IS THE
* SUN ROW (DOT WITH A NORMAL GIVES ITS SHADE) AND ROW 4 (WORKM ONLY) IS
* THE VIEW POSITION IN OBJECT SPACE, NEGATED AND DIVIDED BY 4.
*
* SUZY: EVERY MULTIPLY OR DIVIDE IS STARTED, THEN CPU WORK THAT DOES NOT
* TOUCH THE MATH REGISTERS IS DONE, AND ONLY THEN IS IT POLLED (WAITMATH).
* A MULTIPLY TAKES ABOUT 13 CPU CYCLES, A DIVIDE ABOUT 58.
*
ONE		EQU	32767			;1.0 IN 1.15
*
* SET UP BASEM AND BASEG FOR THIS FRAME
*
*	BASEM = XV * YV * ZV  (+ SUN ROW = (0,0,1) * XS * YS)
*	BASEG = XV * YV       (+ SAME SUN ROW)
*
SETUPVIEWM@
		LDX	#4*6-1			;START WITH THE IDENTITY
?1
		LDA	IDENTITYM,X		;
		STA	BASEM,X			;
		DEX				;
		BPL	?1			;

		LEA	BASEM,RRBASE		;VIEW ROLL AND PITCH
		LDA	#3			;
		STA	RRROWS			;
		LDX	VIEWXROT+0		;
		LDY	VIEWXROT+1		;
		JSR	ROTX			;
		LDX	VIEWYROT+0		;
		LDY	VIEWYROT+1		;
		JSR	ROTY			;

		LEA	BASEM+3*6,RRBASE	;SUN ROLL AND PITCH
		LDA	#1			;
		STA	RRROWS			;
		LDX	SUNXROT+0		;
		LDY	SUNXROT+1		;
		JSR	ROTX			;
		LDX	SUNYROT+0		;
		LDY	SUNYROT+1		;
		JSR	ROTY			;

		LDX	#4*6-1			;GROUND HAS NO VIEW YAW
?2
		LDA	BASEM,X			;
		STA	BASEG,X			;
		DEX				;
		BPL	?2			;

		LEA	BASEM,RRBASE		;VIEW YAW
		LDA	#3			;
		STA	RRROWS			;
		LDX	VIEWZROT+0		;
		LDY	VIEWZROT+1		;
		JSR	ROTZ			;

		NOACCMATH			;
		RTS
*
IDENTITYM	DW	ONE,0,0
		DW	0,ONE,0
		DW	0,0,ONE
		DW	0,0,ONE
*
* RIGHT MULTIPLY RRROWS ROWS AT RRBASE BY A ROTATION ABOUT X, Y OR Z
*
* ENTRY:
*	X,Y	ANGLE (LO,HI)
*
ROTX
		LDA	#1*2			;ROLL CHANGES COLUMNS 1,2
		STA	RRI			;
		LDA	#2*2			;
		BRA	ROTCOMMON		;
ROTY
		STZ	RRI			;PITCH CHANGES COLUMNS 0,2
		LDA	#2*2			;
		BRA	ROTCOMMON		;
ROTZ
		STZ	RRI			;YAW CHANGES COLUMNS 0,1
		LDA	#1*2			;
ROTCOMMON
		STA	RRJ			;
		JSR	ANGLECS			;
		BEQ	?1			;NO ROTATION
		MOVEW	RRBASE,RRPTR		;
		MOVEB	RRROWS,RRN		;
		JMP	RIGHTROT		;
?1
		RTS
*
* COSINE AND SINE OF AN ANGLE ($000-$3FF) AS 8.8 VALUES (SAME AS _COS1
* AND _SIN1)
*
* ENTRY:
*	X,Y	ANGLE (LO,HI)
* EXIT:
*	RRC,RRS,RRNS	COSINE, SINE AND NEGATED SINE
*	Z		SET IF THE ANGLE IS ZERO (RRC,RRS,RRNS NOT SET)
*
ANGLECS
		STX	RRT+0			;ANY ROTATION?
		TYA				;
		ORA	RRT+0			;
		BEQ	?9			;NO
		STY	RRT+1			;

		LDA	COSDIR,Y		;COSINE
		JSR	CSLOOKUP		;
		LDY	RRT+1			;
		LDA	COSSIGN,Y		;
		JSR	CSSIGN			;
		STX	RRC+0			;
		STA	RRC+1			;

		LDY	RRT+1			;SINE
		LDA	SINDIR,Y		;
		JSR	CSLOOKUP		;
		LDY	RRT+1			;
		LDA	SINSIGN,Y		;
		JSR	CSSIGN			;
		STX	RRS+0			;
		STA	RRS+1			;

		TXA				;NEGATED SINE
		EOR	#$FF			;
		CLC				;
		ADC	#$01			;
		STA	RRNS+0			;
		LDA	RRS+1			;
		EOR	#$FF			;
		ADC	#$00			;
		STA	RRNS+1			;

		LDA	#1			;CLEAR Z
?9
		RTS
*
* RRA = COSSIN TABLE VALUE FOR ANGLE LO RRT+0 (A = 1 TO INVERT INDEX)
*
CSLOOKUP
		STZ	RRA+1			;
		TAX				;INVERT?
		BEQ	?1			;NO

		LDA	#255			;YES - INVERT INDEX
		SEC				;
		SBC	RRT+0			;
		TAX				;

		LDA	COSSINLO+1,X		;NOTE: +1,X
		STA	RRA+0			;
		BNE	?3			;
		CPX	#255			;
		BEQ	?3			;
		BRA	?2			;
?1
		LDX	RRT+0			;
		LDA	COSSINLO,X		;
		STA	RRA+0			;
		BNE	?3			;
?2
		INC	RRA+1			;
?3
		RTS
*
* RETURN RRA (NEGATED IF A <> 0) IN X (LO) AND A (HI)
*
CSSIGN
		TAY				;
		BEQ	?1			;
		LDA	RRA+0			;
		EOR	#$FF			;
		CLC				;
		ADC	#$01			;
		TAX				;
		LDA	RRA+1			;
		EOR	#$FF			;
		ADC	#$00			;
		RTS
?1
		LDX	RRA+0			;
		LDA	RRA+1			;
		RTS
*
* RIGHT MULTIPLY RRN ROWS AT (RRPTR) BY A ROTATION ABOUT ONE AXIS
*
* ENTRY:
*	RRPTR		FIRST ROW
*	RRN		NUMBER OF ROWS
*	RRI,RRJ		BYTE OFFSETS OF THE TWO COLUMNS THAT CHANGE
*	RRC,RRS,RRNS	COSINE, SINE AND NEGATED SINE (8.8)
* EXIT:
*	EACH ROW	A(I) = C*A(I) - S*A(J)
*			A(J) = S*A(I) + C*A(J)
*	ACCUMULATE MATH IS ON
*
RIGHTROT
		SIGNEDACCMATH			;SET SIGNED ACCUMULATE MATH
RRROWLOOP
		LDY	RRI			;BOTH COLUMNS ZERO?
		LDA	(RRPTR),Y		;
		INY				;
		ORA	(RRPTR),Y		;
		LDY	RRJ			;
		ORA	(RRPTR),Y		;
		INY				;
		ORA	(RRPTR),Y		;
		BNE	?DO			;
		JMP	RRNEXTROW		;YES - ROW DOES NOT CHANGE
?DO
		CLEARACCUM			;
		LDY	RRI			;A(I) * C
		LDA	(RRPTR),Y		;
		STA	MATHD			;
		STA	RRA+0			;
		INY				;
		LDA	(RRPTR),Y		;
		STA	MATHC			;
		STA	RRA+1			;
		LDA	RRC+0			;
		STA	MATHB			;
		LDA	RRC+1			;
		STA	MATHA			;START
		LDY	RRJ			;GET A(J) WHILE IT RUNS
		LDA	(RRPTR),Y		;
		STA	RRB+0			;
		INY				;
		LDA	(RRPTR),Y		;
		STA	RRB+1			;
		WAITMATH			;
		LDA	RRB+0			;+ A(J) * -S
		STA	MATHD			;
		LDA	RRB+1			;
		STA	MATHC			;
		LDA	RRNS+0			;
		STA	MATHB			;
		LDA	RRNS+1			;
		STA	MATHA			;START
		LDY	RRI			;(FOR RRSTORE)
		WAITMATH			;
		JSR	RRSAVE			;SAVE NEW A(I), CLEAR ACCUMULATOR
		LDA	RRA+0			;A(I) * S
		STA	MATHD			;
		LDA	RRA+1			;
		STA	MATHC			;
		LDA	RRS+0			;
		STA	MATHB			;
		LDA	RRS+1			;
		STA	MATHA			;START
		JSR	RRSTORE			;STORE NEW A(I) WHILE IT RUNS
		WAITMATH			;
		LDA	RRB+0			;+ A(J) * C
		STA	MATHD			;
		LDA	RRB+1			;
		STA	MATHC			;
		LDA	RRC+0			;
		STA	MATHB			;
		LDA	RRC+1			;
		STA	MATHA			;START
		LDY	RRJ			;(FOR RRSTORE)
		WAITMATH			;
		JSR	RRSAVE			;
		JSR	RRSTORE			;STORE NEW A(J)
RRNEXTROW
		ADDBW	#6,RRPTR		;NEXT ROW
		DEC	RRN			;
		BEQ	?9			;
		JMP	RRROWLOOP		;
?9

		RTS
*
* SAVE ACCUMULATOR/256 IN RRT AND CLEAR THE ACCUMULATOR
*
RRSAVE
		LDA	MATHL			;
		STA	RRT+0			;
		LDA	MATHK			;
		STA	RRT+1			;
		LDA	MATHJ			;
		STA	RRT+2			;
		CLEARACCUM			;
		RTS
*
* STORE RRT AT (RRPTR),Y, LIMITED TO +/- ONE
*
RRSTORE
		LDA	RRT+2			;
		BMI	?NEG			;
		BNE	?POSBAD			;
		LDA	RRT+1			;
		BPL	?OKAY			;
?POSBAD
		LDA	#<ONE			;
		LDX	#>ONE			;
		BRA	?STORE			;
?NEG
		CMP	#$FF			;
		BNE	?NEGBAD			;
		LDA	RRT+1			;
		BMI	?OKAY			;
?NEGBAD
		LDA	#<-ONE			;
		LDX	#>-ONE			;
		BRA	?STORE			;
?OKAY
		LDA	RRT+0			;
		LDX	RRT+1			;
?STORE
		STA	(RRPTR),Y		;
		INY				;
		TXA				;
		STA	(RRPTR),Y		;
		RTS
*
* ROTATE A VIEW RELATIVE POSITION INTO VIEW SPACE
*	(REPLACES DOROTATEV)
*
* ENTRY:
*	XDIFF,YDIFF,ZDIFF	POSITION RELATIVE TO VIEW
*	SORTINDEX		0 FOR THE GROUND (NO VIEW YAW)
* EXIT:
*	TPRIME			24 BIT X,Y,Z IN VIEW SPACE
*	XDIFF,YDIFF,ZDIFF	SAME, LIMITED TO MINCOORD-MAXCOORD
*
VIEWXFORM@
		LEA	BASEM,XFBASE		;
		LDA	SORTINDEX		;GROUND?
		BNE	?1			;NO
		LEA	BASEG,XFBASE		;
?1
		SIGNEDACCMATH			;SET SIGNED ACCUMULATE MATH
		LDY	#0			;MATRIX INDEX
		LDX	#0			;TPRIME INDEX
VXROWLOOP
		CLEARACCUM			;
		LDA	XDIFF+0			;X * M(R,0)
		STA	MATHD			;
		LDA	XDIFF+1			;
		STA	MATHC			;
		LDA	(XFBASE),Y		;
		STA	MATHB			;
		INY				;
		LDA	(XFBASE),Y		;
		STA	MATHA			;START
		INY				;
		CPX	#0			;FINISH THE LAST ROW WHILE IT RUNS
		BEQ	?1			;
		JSR	TPSTORE			;
?1
		WAITMATH			;
		LDA	YDIFF+0			;+ Y * M(R,1)
		STA	MATHD			;
		LDA	YDIFF+1			;
		STA	MATHC			;
		LDA	(XFBASE),Y		;
		STA	MATHB			;
		INY				;
		LDA	(XFBASE),Y		;
		STA	MATHA			;START
		INY				;
		WAITMATH			;
		LDA	ZDIFF+0			;+ Z * M(R,2)
		STA	MATHD			;
		LDA	ZDIFF+1			;
		STA	MATHC			;
		LDA	(XFBASE),Y		;
		STA	MATHB			;
		INY				;
		LDA	(XFBASE),Y		;
		STA	MATHA			;START
		INY				;
		INX				;
		INX				;
		INX				;
		WAITMATH			;
		LDA	MATHL			;ACCUMULATOR/256
		STA	RRT+0			;
		LDA	MATHK			;
		STA	RRT+1			;
		LDA	MATHJ			;
		STA	RRT+2			;
		CPY	#3*6			;
		BNE	VXROWLOOP		;

		JSR	TPSTORE			;
		NOACCMATH			;

		LDX	#0			;LIMIT TO 16 BITS
		LDY	#0			;
?2
		LDA	TPRIME+0,X		;
		STA	RV+0			;
		LDA	TPRIME+1,X		;
		STA	RV+1			;
		LDA	TPRIME+2,X		;
		STA	RV+2			;
		JSR	LIMITRV			;
		LDA	RV+0			;
		STA	XDIFF+0,Y		;
		LDA	RV+1			;
		STA	XDIFF+1,Y		;
		INX				;
		INX				;
		INX				;
		INY				;
		INY				;
		CPY	#3*2			;
		BNE	?2			;

		RTS
*
* STORE RRT (ACCUMULATOR/256) AS ACCUMULATOR/32768 AT TPRIME-3,X
*
TPSTORE
		LDA	RRT+0			;
		ASL	A			;
		LDA	RRT+1			;
		ROL	A			;
		STA	TPRIME-3+0,X		;
		LDA	RRT+2			;
		ROL	A			;
		STA	TPRIME-3+1,X		;
		LDA	RRT+2			;SIGN EXTEND
		ASL	A			;
		LDA	#$FF			;
		ADC	#0			;
		EOR	#$FF			;
		STA	TPRIME-3+2,X		;
		RTS
*
* LIMIT RV (24 BIT) TO MINCOORD-MAXCOORD (AS ROTCHK)
*
LIMITRV
		LDA	RV+2			;
		BMI	?NEG			;
		BNE	?POSBAD			;
		LDA	RV+1			;
		CMP	#>MAXCOORD		;
		BLT	?OKAY			;
?POSBAD
		MOVEIW	MAXCOORD,RV		;
		RTS
?NEG
		CMP	#$FF			;
		BNE	?NEGBAD			;
		LDA	RV+1			;
		CMP	#>MINCOORD		;
		BGE	?OKAY			;
?NEGBAD
		MOVEIW	MINCOORD,RV		;
?OKAY
		RTS
*
* BUILD THIS OBJECT'S MATRIX
*
*	WORKM ROWS 0-3 = BASE * ZO * YO * XO
*	WORKM ROW 4    = (OBJECT OFFSET/4) * ZO * YO * XO
*
* ENTRY:
*	XFBASE			BASEM OR BASEG (SET BY VIEWXFORM@)
*	OBJECTX,OBJECTY,OBJECTZ	OBJECT OFFSET FROM VIEW
*	WXROTATION,WYROTATION,WZROTATION
*
OBJMATRIX@
		LDY	#4*6-1			;COPY THE BASE
?1
		LDA	(XFBASE),Y		;
		STA	WORKM,Y			;
		DEY				;
		BPL	?1			;

		LDX	#2*2			;ROW 4 = OFFSET/4
?2
		LDA	OBJECTX+1,X		;
		CMP	#$80			;
		ROR	A			;
		STA	RRT+1			;
		LDA	OBJECTX+0,X		;
		ROR	A			;
		STA	RRT+0			;
		LDA	RRT+1			;
		CMP	#$80			;
		ROR	A			;
		STA	WORKM+4*6+1,X		;
		LDA	RRT+0			;
		ROR	A			;
		STA	WORKM+4*6+0,X		;
		DEX				;
		DEX				;
		BPL	?2			;

		LEA	WORKM,RRBASE		;OBJECT YAW, PITCH, ROLL
		LDA	#5			;
		STA	RRROWS			;
		LDX	WZROTATION+0		;
		LDY	WZROTATION+1		;
		JSR	ROTZ			;
		LDX	WYROTATION+0		;
		LDY	WYROTATION+1		;
		JSR	ROTY			;
		LDX	WXROTATION+0		;
		LDY	WXROTATION+1		;
		JMP	ROTX			;
*
* DRAW THE POLYGONS
*
* ENTRY:
*	DEFPTR		POINTS TO POLYGONS (READOBJFILE@ DONE)
*	TPRIME,XFBASE	SET BY VIEWXFORM@
*
DRAWPOLYGONS@
		CMPIW	MAXSPR,SPRITECOUNT	;AT MAX?
		BLT	?1			;NO
		RTS				;YES - ABORT
?1
		JSR	OBJMATRIX@		;
		JSR	FINDVISIBLE@		;
		JSR	XFORMPOINTS@		;
		JMP	DRAWVISIBLE@		;
*
* FIND THE FACES THAT ARE CLOSE ENOUGH AND FACE THE VIEW, AND THE POINTS
* THEY USE
*
* EXIT:
*	VISFACELO/HI	NVISFACES FACE POINTERS
*	XFPOINTLIST	NXFPOINTS POINT NUMBERS (POINTUSE SET FOR EACH)
*	NORMALSHADE	SET FOR THE NORMALS OF SHADED VISIBLE FACES
*
FINDVISIBLE@
		SIGNEDACCMATH			;SET SIGNED ACCUMULATE MATH

		STZ	NVISFACES		;
		STZ	NXFPOINTS		;
		MOVEB	POLYGONCOUNT,FACESLEFT	;
FVFACELOOP
		LDY	#3			;GET POINT COUNT
		LDA	(DEFPTR),Y		;
		STA	NPOINTS			;

		LDY	#0			;WITHIN VIEW POLY DISTANCE?
		LDA	(DEFPTR),Y		;
		CMP	VPDISTANCE		;
		BLT	FVSKIP			;NO ($FF ALWAYS SEEN)

		INY				;GET NORMAL
		LDA	(DEFPTR),Y		;
		STA	NORMALINDEX		;
		TAX				;

		LDA	NPOINTS			;JUST TWO POINTS?
		CMP	#2			;
		BNE	?1			;NO
		LDA	NORMALUSE,X		;PRIOR SURFACE HIDDEN?
		CMP	#-2			;
		BEQ	FVSKIP			;YES
		CMP	#-3			;PRIOR SURFACE OKAY?
		BEQ	FVVISIBLE		;YES
?1
		LDA	#-2			;INIT TO HIDDEN
		STA	NORMALUSE,X		;

		JSR	TESTHIDDEN		;
		BCS	FVSKIP			;HIDDEN

		LDX	NORMALINDEX		;
		LDA	#-3			;SET PRIOR USE OKAY
		STA	NORMALUSE,X		;
FVVISIBLE
		LDX	NVISFACES		;SAVE THE FACE
		CPX	#MAXVISFACES		;
		BGE	FVSKIP			;
		LDA	DEFPTR+0		;
		STA	VISFACELO,X		;
		LDA	DEFPTR+1		;
		STA	VISFACEHI,X		;
		INC	NVISFACES		;

		JSR	FACESHADE		;

		LDA	NPOINTS			;QUEUE ITS POINTS
		CLC				;
		ADC	#4			;
		STA	PEND			;
		LDY	#4			;
?2
		LDA	(DEFPTR),Y		;GET POINT NUMBER
		TAX				;
		LDA	POINTUSE,X		;ALREADY QUEUED?
		BNE	?3			;YES
		DEC	POINTUSE,X		;
		TXA				;
		LDX	NXFPOINTS		;
		STA	XFPOINTLIST,X		;
		INC	NXFPOINTS		;
?3
		INY				;
		CPY	PEND			;
		BNE	?2			;
FVSKIP
		LDA	NPOINTS			;NEXT FACE
		CLC				;
		ADC	#4			;
		ADC	DEFPTR+0		;
		STA	DEFPTR+0		;
		BCC	?1			;
		INC	DEFPTR+1		;
?1
		DEC	FACESLEFT		;
		BEQ	?9			;
		JMP	FVFACELOOP		;
?9

		RTS
*
* POINT NRMPTR AT THIS FACE'S NORMAL
*
SETNRMPTR
		LDX	NORMALINDEX		;
		LDA	STARTOFNORMALS+0	;
		CLC				;
		ADC	MULT6LO,X		;
		STA	NRMPTR+0		;
		LDA	STARTOFNORMALS+1	;
		ADC	MULT6HI,X		;
		STA	NRMPTR+1		;
		RTS
*
* CHECK FOR HIDDEN FACE IN OBJECT SPACE
*
*	HIDDEN IF NORMAL . (FIRST POINT/4 + WORKM ROW 4) > 0
*
* THIS IS THE SAME TEST AS NORMAL . FIRST POINT IN VIEW SPACE, WITHOUT
* ROTATING THE NORMAL OR THE POINT.  ZERO NORMAL TERMS ARE SKIPPED.
*
* EXIT:
*	CARRY	SET - FACE IS HIDDEN
*
TESTHIDDEN
		JSR	SETNRMPTR		;

		LDY	#4			;POINT TO FIRST POINT
		LDA	(DEFPTR),Y		;
		TAX				;
		LDA	STARTOFPOINTS+0		;
		CLC				;
		ADC	MULT6LO,X		;
		STA	WRKPTR+0		;
		LDA	STARTOFPOINTS+1		;
		ADC	MULT6HI,X		;
		STA	WRKPTR+1		;


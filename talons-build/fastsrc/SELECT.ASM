*
* FILE - SELECT.ASM
* DATE - 10/07/91
*
;;		GLOBALS	ON
;;		SYMBOLS	ON
*
* DO MISSION SELECT
*
* NOTE: OUTPUT IS A "RAW" TYPE FILE FOR LYNXROM!!
*
		CHIP	65C02
*
* EQUATES AND MACROS
*
		INCLUDE	TALONS.EQU
		INCLUDE	MACROS.INC
*
* SYSTEM INCLUDES
*
		LIST	OFF
		INCLUDE	\PR\LYNX\INCLUDE\sys.mac
	IF	USEHSOUNDS=TRUE
		INCLUDE	\PR\LYNX\INCLUDE\HMUSIC.MAC
		INCLUDE	\PR\LYNX\INCLUDE\HSFX.MAC
	ENDIF
		INCLUDE	\PR\LYNX\INCLUDE\sprite.mac
		INCLUDE	\PR\LYNX\INCLUDE\display.mac
		INCLUDE	\PR\LYNX\INCLUDE\handymath.mac
		INCLUDE	\PR\LYNX\INCLUDE\cart.mac
		LIST	ON
*
* START OF PROGRAM
*
		ORG	SOURCEBUFFER
*
* SELECT MISSION
*
* ENTRY:
*	MISSIONLIST	LIST OF MISSION COMPLETION INFO
*	-1	NOT SELECTABLE, NOT PLAYED
*	0	SELECTABLE, NOT PLAYED
*	1	SELECTABLE, FAILED
*	2	NOT SELECTABLE, PASSED
*	3	NOT SELECTABLE, ACED
* EXIT:
*	ZERO FLAG	(BEQ) SET IF TIMED OUT
*			(BNE) CLEARED IF A OR B PRESSED
*
SELECTMISSION@
		STZ	MISSION			;INIT MISSION

		LDX	#1			;FIND FIRST NON-PLAYED MISSION
?FMLOOP
		CPX	#12+1			;
		BGE	RESELECTMISSION		;

		LDA	MISSIONLIST,X		;
		BEQ	?FMDONE			;

		INX				;
		BRA	?FMLOOP			;
?FMDONE
		STX	MISSION			;
RESELECTMISSION
		MOVEIW	15*60,ATRACTTIMER	;SET TIME OUT VALUE

		LDA	FIRSTMISSION		;FIRST MISSION?
		BEQ	?1			;YES

		MOVEIW	120*60,ATRACTTIMER	;SET TIME OUT VALUE
?1
		MOVEIW	SELECTSPR,FIRSTSPRITE	;POINT TO FIRST SCB

		LDA	MISSION		;GET MISSION NUMBER
		CLC			;
		ADC	#STARTSELFILES	;ADD START OF SELECTION FILES
		GETDIR			;GET DIRECTORY ENTRY
		MYOPENFILE		;OPEN THE FILE
		LDA	#1		;DEST ADDRESS
		LDX	#<STARTDATABASE	;
		LDY	#>STARTDATABASE	;
		READFILE		;READ THE FILE

		SPRITES	FIRSTSPRITE,1	;DRAW SPRITES

		MYDBUF_DISPLAY		;"PAGE FLIP"
		MYWAITEOF		;
		MYRGB16	STARTDATABASE	;UPDATE PALETTE

		LDX	#15		;SHORT DELAY
SELECTWAITLOOP
		MYWAITEOF		;
		DEX			;
		BNE	SELECTWAITLOOP	;
SELECTLOOP
		MYWAITEOF		;
		JSR	GETJOY@		;READ CONTROLLER

		LDA	JOYVALUE	;GET UNDEBOUNCED

		BIT	#B_BUTTON	;B BUTTON PRESSED?
		BNE	SELECTEDMISSION	;YES
		BIT	#A_BUTTON	;A BUTTON PRESSED?
		BNE	SELECTEDMISSION	;YES

		LDA	DJOYVALUE	;GET DEBOUNCED

		BIT	#JOY_UP		;INCREASE MISSION?
		BNE	NEXTMISSION	;YES
		BIT	#JOY_RIGHT	;
		BEQ	NOTNEXTMISSION	;NO
NEXTMISSION
		MOVEB	MISSION,LASTMISSION
		INC	MISSION		;
		JSR	FINDMISSIONI	;
		BCS	NOTNEXTMISSION	;

		JMP	RESELECTMISSION	;
NOTNEXTMISSION
		LDA	DJOYVALUE	;GET DEBOUNCED

		BIT	#JOY_DOWN	;DECREASE MISSION?
		BNE	PREVMISSION	;YES
		BIT	#JOY_LEFT	;
		BEQ	NOTPREVMISSION	;NO
PREVMISSION
		MOVEB	MISSION,LASTMISSION
		DEC	MISSION		;
		JSR	FINDMISSIOND	;
		BCS	NOTPREVMISSION	;

		JMP	RESELECTMISSION	;
NOTPREVMISSION
		JSR	CHECKOTHERFLAGS@ ;CHECK FLAGS FOR SPECIAL INPUT
		JSR	SELCHECKPAUSED@	;SELECT CHECK FOR PAUSE REQUEST

		DECW	ATRACTTIMER	;DECREMENT TIMER

		LDA	ATRACTTIMER+0	;TIMED OUT?
		ORA	ATRACTTIMER+1	;
		BEQ	SELECTDONE	;YES

		JMP	SELECTLOOP	;
SELECTEDMISSION
		LDX	MISSION			;GET MISSION NUMBER

		LDA	MISSIONTLK,X		;
		GETDIR				;GET DIRECTORY ENTRY
		MYOPENFILE			;OPEN THE FILE
		LDA	#1			;DEST ADDRESS
		LDX	#<STARTDATABASE		;
		LDY	#>STARTDATABASE		;
		READFILE			;READ THE FILE

		STX	DIGCNT+0		;SAVE ENDING ADDRESS
		STY	DIGCNT+1		;

		LEA	STARTDATABASE,DIGPTR	;START
		SUBW	DIGPTR,DIGCNT		;CONVERT ENDING ADDR TO COUNT
		JSR	PLAYDIG			;PLAY DIGITIZED EFFECT
?1
		LDA	#1			;
		RTS				;
SELECTDONE
		RTS
*
* FIND NEXT SELECTABLE MISSION AFTER INCREMENT
*
* ENTRY:
*	LASTMISSION	MISSION BEFORE MODIFICATION
*
FINDMISSIONI
		LDX	MISSION			;GET MISSION
?FILOOP
		CPX	#12+1			;TOO HIGH?
		BGE	?FIHI			;YES

		LDA	MISSIONLIST,X		;SELECTABLE?
		BMI	?FINEXT			;NO
		CMP	#2			;
		BGE	?FINEXT			;NO

		STX	MISSION			;RETURN MISSION NUMBER
		CLC				;
		RTS				;
?FINEXT
		INX				;NEXT MISSION
		BRA	?FILOOP			;
?FIHI
		MOVEB	LASTMISSION,MISSION	;RESTORE MISSION
		SEC				;
		RTS
*
* FIND NEXT SELECTABLE MISSION AFTER DECREMENT
*
* ENTRY:
*	LASTMISSION	MISSION BEFORE MODIFICATION
*
FINDMISSIOND
		LDX	MISSION			;GET MISSION
?FDLOOP
		CPX	#-1			;TOO LOW?
		BEQ	?FDLO			;YES

		LDA	MISSIONLIST,X		;SELECTABLE?
		BMI	?FDPREV			;NO
		CMP	#2			;
		BGE	?FDPREV			;NO

		STX	MISSION			;RETURN MISSION NUMBER
		CLC				;
		RTS				;
?FDPREV
		DEX				;PREVIOUS MISSION
		BRA	?FDLOOP			;
?FDLO
		MOVEB	LASTMISSION,MISSION	;RESTORE MISSION
		SEC				;
		RTS
*
* MISSION TLK FILES
*
MISSIONTLK	DB	YOUGOT_FILE		;TRAINING
		DB	MILKRUN_FILE		;1
		DB	WASTE_FILE		;2
		DB	RIVER_FILE		;3
		DB	ROUTE_FILE		;4
		DB	TV_FILE			;5
		DB	JETS_FILE		;6
		DB	LETSGO_FILE		;7
		DB	STAYHIGH_FILE		;8
		DB	JETS_FILE		;9
		DB	BOGEYS_FILE		;A
		DB	FOG_FILE		;B
		DB	EXAM_FILE		;C
*
* THE SELECT SCB
*
SELECTSPR	.BYTE	FOUR_PER_PIXEL+BACKNONCOLL_SPRITE ; Control 0
		.BYTE	RELOAD_HVST			; Control 1
		.BYTE	$00				; Control 2
		.WORD	PAUSEDSPR			; Next sprite's address
		.WORD	STARTDATABASE+32		; ImageData
		.WORD	0				; HPos
		.WORD	0				; VPos
		.WORD	$0100				; HSize
		.WORD	$0100				; VSize
		.WORD	$0000				; Stretch
		.WORD	$0000				; Tilt
		.BYTE	$01,$23,$45,$67,$89,$AB,$CD,$EF	; Palette
ENDSELECT

	IF	ENDSELECT>ENDSOURCEBUFFER
	.WORD	ENDSELECT-ENDSOURCEBUFFER,OH_SHIT_SELECT_OVERFLOW
	ENDIF

		ORA	MATHB			;
		BEQ	?23			;NO

		MOVEIB	0,WORK5			;YES - SET TO MIN DEGREE
		JMP	?5			;
?23
		MOVEW	MATHD,WORK2		;

		MOVEW	WORK3,MATHD		;ZDIFF*400 FOR TAN TABLE
		MOVEIW	400,MATHB		;


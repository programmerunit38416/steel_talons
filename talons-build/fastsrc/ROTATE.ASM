*
* COMPUTE ATAN FROM VALUE IN WORK1
*
* ENTER:
*	WORK1 - (Y*400/X)
* EXIT:
*	WORK1 - ANGLE (0-255)
* USES:
*	WORK2
*
GETATAN@
		LDY	#8			;MAX COUNT
		LDX	#128			;INIT INDEX
		LDA	#64			;INIT INDEX ADJUSTMENT
		STA	WORK2			;
FINDDZLOOP
		LDA	WORK2			;INDEX ADJUSTMENT 0?
		BEQ	FINDDZDONE		;YES

		LDA	WORK1+1			;CHECK AT CURRENT INDEX
		CMP	TANHI,X			;NOTE: TAN TABLE ENTRIES ARE
		BNE	?1			;MULTIPLIED BY WHEELBASE
		LDA	WORK1+0			;OF 400 TO AVOID DIVIDING
		CMP	TANLO,X			;
		BEQ	FINDDZDONE		;
?1
		BLT	DECINDEX		;
INCINDEX
		TXA				;ADJUST INDEX
		CLC				;
		ADC	WORK2			;
		TAX				;

		LSR	WORK2			;HALF INDEX ADJUSTMENT
		BRA	FINDDZLOOP		;
DECINDEX
		TXA				;ADJUST INDEX
		SEC				;
		SBC	WORK2			;
		TAX				;

		LSR	WORK2			;HALF INDEX ADJUSTMENT
		BRA	FINDDZLOOP		;
FINDDZDONE
		STX	WORK1+0			;SAVE DELTA ROTATION

		RTS
*
* CALC YAW
*
* ENTRY:
*	WORK1	+/- XDIFF
*	WORK2	+/- YDIFF
* EXIT:
*	WORK4	YAW  ($000-$3FF)
*
CALCYAW@
		UNSIGNEDMATH			;SET UNSIGNED MATH

		PUSHW	WORK1			;SAVE XDIFF AND YDIFF
		PUSHW	WORK2			;

		LDA	WORK2+1			;SET UP HIGH BYTE OF YAW
		BPL	?YPOS			;
?YNEG
		NEGW	WORK2			;

		LDA	WORK1+1			;
		BPL	?XPOS1			;
?XNEG1
		NEGW	WORK1			;
		MOVEIB	2,WORK4+1		;
		BRA	?XYSET			;
?XPOS1
		MOVEIB	3,WORK4+1		;
		BRA	?XYSET			;
?YPOS
		LDA	WORK1+1			;
		BPL	?XPOS2			;
?XNEG2
		NEGW	WORK1			;
		MOVEIB	1,WORK4+1		;
		BRA	?XYSET			;
?XPOS2
		MOVEIB	0,WORK4+1		;
?XYSET
		MOVEW	WORK1,MATHD		;XDIFF*400 FOR TAN TABLE
		MOVEIW	400,MATHB		;

		LDA	WORK2+0			;YDIFF=0?
		ORA	WORK2+1			;
		BNE	?3			;NO

		MOVEIB	255,WORK4		;YES - SET TO MAX DEGREE
		BRA	?5			;
?3
		WAITMATH			;WAIT FOR MULTIPLY

		MOVEW	WORK2,MATHP		;

		MOVEB	MATHE,MATHE		;START THE DIVIDE

		WAITMATH			;WAIT FOR DIVIDE

		LDA	MATHA			;REAL HIGH QUOTIENT?
		ORA	MATHB			;
		BEQ	?4			;NO

		MOVEIB	255,WORK4		;YES - SET TO MAX DEGREE
		BRA	?5			;
?4
		MOVEW	MATHD,WORK1		;GET XDIFF*400/YDIFF
		JSR	GETATAN@		;GET ATAN DEGREES
		MOVEB	WORK1,WORK4		;
?5
		LDA	WORK4+1			;SHOULD WE INVERT YAW?
		CMP	#1			;
		BEQ	YAWDONE			;NO
		CMP	#3			;
		BEQ	YAWDONE			;NO

		LDA	#255			;YES
		SEC				;
		SBC	WORK4+0			;
		STA	WORK4+0			;
YAWDONE
		POPW	WORK2			;RESTORE XDIFF AND YDIFF
		POPW	WORK1			;

		LDA	#<$400			;ZROT NEEDED
		SEC				;
		SBC	WORK4+0			;
		STA	WORK4+0			;
		LDA	#>$400			;
		SBC	WORK4+1			;
		AND	#>$3FF			;
		STA	WORK4+1			;

		RTS
*
* GET YAW AND PITCH
*
* ENTRY:
*	WORK1	+/- XDIFF
*	WORK2	+/- YDIFF
*	WORK3	+/- ZDIFF
* EXIT:
*	WORK4	YAW  ($000-$3FF)
*	WORK5	PITCH ($000-$3FF)
*
GETYP@
		JSR	CALCYAW@		;CALC YAW

		MOVEIB	0,WORK5+1		;

		LDA	WORK3+1			;
		BPL	?1			;

		NEGW	WORK3			;
		MOVEIB	3,WORK5+1		;
?1
		LDX	WORK4+1			;GET HIGH BYTE INDEX

		LDA	COSSIGN,X		;SET SIGN FOR COSINE
		STA	WORK6			;

		STZ	WORK2+1			;INIT HIGH BYTE

		LDA	COSDIR,X		;INVERT?
		BEQ	?MLBL1			;NO

		LDA	#255			;YES - INVERT INDEX
		SEC				;
		SBC	WORK4+0			;
		TAX				;

		LDA	COSSINLO+1,X		;GET COSINE EFFECT
		STA	WORK2+0			;NOTE: +1,X
		BNE	?MLBL3			;
		CPX	#255			;
		BEQ	?MLBL3			;
		BRA	?MLBL2			;
?MLBL1
		LDX	WORK4+0			;GET LOW BYTE INDEX

		LDA	COSSINLO,X		;GET COSINE EFFECT
		STA	WORK2+0			;
		BNE	?MLBL3			;
?MLBL2
		INC	WORK2+1			;
?MLBL3

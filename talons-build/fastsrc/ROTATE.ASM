* ROTATE ABOUT OBJECT X AXIS ROLL
*
*	NEWY = Y*CEFFECT + Z*SEFFECT, NEWZ = Z*CEFFECT - Y*SEFFECT
*
* ENTRY:
*	SIGNED ACCUMULATE MATH ON (DOROTATE1)
*
ROTATEX1@
		NOP				;(RTS IF NO ROTATION)

		CLEARACCUM			;
		MOVEW	YDIFF,MATHD		;Y * C
		MOVEW	XCEFFECT1,MATHB		;START
		LDA	ZDIFF+0			;GET NEXT OPERAND WHILE IT RUNS
		STA	RRB+0			;
		LDA	ZDIFF+1			;
		STA	RRB+1			;
		WAITMATH			;
		MOVEW	RRB,MATHD		;+ Z * S
		MOVEW	XSEFFECT1,MATHB		;START
		WAITMATH			;
		LDA	MATHL			;NEW Y/256
		STA	ROTWORK+0		;
		LDA	MATHK			;
		STA	ROTWORK+1		;
		LDA	MATHJ			;
		STA	ROTWORK+2		;
		CLEARACCUM			;
		MOVEW	RRB,MATHD		;Z * C
		MOVEW	XCEFFECT1,MATHB		;START
		ROTCHK	WORK1			;LIMIT NEW Y WHILE IT RUNS
		WAITMATH			;
		MOVEW	YDIFF,MATHD		;+ Y * -S
		MOVEW	XNSEFFECT1,MATHB	;START
		MOVEW	WORK1,YDIFF		;SAVE NEW Y WHILE IT RUNS
		WAITMATH			;
		LDA	MATHL			;NEW Z
		STA	ROTWORK+0		;
		LDA	MATHK			;
		STA	ROTWORK+1		;
		LDA	MATHJ			;
		STA	ROTWORK+2		;
		ROTCHK	ZDIFF			;

		RTS

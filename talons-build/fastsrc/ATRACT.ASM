;;		GLOBALS	ON
;;		SYMBOLS	ON
*
* DO ATRACT SEQUENCE
*
* NOTE: OUTPUT IS A "RAW" TYPE FILE FOR LYNXROM!!
*
		CHIP	65C02
*
* EQUATES AND MACROS
*
		INCLUDE	TALONS.EQU
		INCLUDE	MACROS.INC
*
* SYSTEM INCLUDES
*
		LIST	OFF
		INCLUDE	\PR\LYNX\INCLUDE\sys.mac
	IF	USEHSOUNDS=TRUE
		INCLUDE	\PR\LYNX\INCLUDE\HMUSIC.MAC
		INCLUDE	\PR\LYNX\INCLUDE\HSFX.MAC
	ENDIF
		INCLUDE	\PR\LYNX\INCLUDE\sprite.mac
		INCLUDE	\PR\LYNX\INCLUDE\display.mac
		INCLUDE	\PR\LYNX\INCLUDE\handymath.mac
		INCLUDE	\PR\LYNX\INCLUDE\cart.mac
		LIST	ON
*
* START OF PROGRAM
*
		ORG	SOURCEBUFFER
*
* SHOW ATRACT SCREENS
*
* EXIT:
*	ZERO FLAG	(BEQ) SET IF TIMED OUT
*			(BNE) CLEARED IF A OR B PRESSED
*
DOATRACT@
		CMPIB	TRUE,BOOTFLAG	;JUST BOOTED CART?
		BEQ	DONETITLE	;YES

		LDA	#0		;SHOW TITLE SCREEN
		JSR	LOADSCREEN@	;

		MOVEIW	5*60,ATRACTTIMER
		JSR	ATRACTSCREEN@	;
		BEQ	DONETITLE	;

		RTS			;EXIT
DONETITLE
		MOVEIB	FALSE,BOOTFLAG	;CLEAR FLAG

		LDA	#CREDITS_FILE	;SHOW CREDITS SCREEN
		JSR	LOADSCREEN@	;

		MOVEIW	5*60,ATRACTTIMER
		JSR	ATRACTSCREEN@	;
		BEQ	DONECREDITS	;

		RTS
DONECREDITS
		LDA	#HISCORE_FILE	;SHOW HISCORE SCREEN
		GETDIR			;GET DIRECTORY ENTRY
		MYOPENFILE		;OPEN THE FILE
		LDA	#1		;DEST ADDRESS
		LDX	#<STARTDATABASE	;
		LDY	#>STARTDATABASE	;
		READFILE		;READ THE FILE

		LDA	#00		;JUST SHOWING
		JSR	STARTDATABASE	;
		BEQ	DONEHSCORE	;

		RTS
DONEHSCORE
		RTS
*
* SHOW ATRACT MODE SCREEN
*
* ENTRY:
*	ATRACTTIMER	SET TO NUMBER OF JIFFIES TO WAIT
* EXIT:
*	ZERO FLAG	(BEQ) SET IF TIMED OUT
*			(BNE) CLEARED IF A OR B PRESSED
*
ATRACTSCREEN@
ATRACTLOOP
		MYWAITEOF		;WAIT FOR JIFFY COUNTER TO CHANGE
		JSR	GETJOY@		;READ CONTROLLER

		LDA	JOYVALUE	;GET UNDEBOUNCED

		BIT	#B_BUTTON	;B BUTTON PRESSED?
		BNE	ATRACTDONE	;YES
		BIT	#A_BUTTON	;A BUTTON PRESSED?
		BNE	ATRACTDONE	;YES

		JSR	CHECKOTHERFLAGS@ ;CHECK FLAGS FOR SPECIAL INPUT
		JSR	SELCHECKPAUSED@	;SELECT CHECK FOR PAUSE REQUEST

		DECW	ATRACTTIMER	;DECREMENT TIMER

		LDA	ATRACTTIMER+0	;TIMED OUT?
		ORA	ATRACTTIMER+1	;
		BNE	ATRACTLOOP	;NO
ATRACTDONE
		PHP			;
		JSR	FADEBLACK@	;FADE TO BLACK (COLOR 0)
		PLP			;

		RTS			;
*
* LOAD AND RELOCAT DISPLAYABLE TITLE FORMAT FILE
*
* ENTRY:
*	ACC	FILE NUMBER
*
LOADSCREEN@
		GETDIR			;GET DIRECTORY ENTRY
		MYOPENFILE		;OPEN THE FILE
		LDA	#1		;DEST ADDRESS
		LDX	#<STARTDATABASE	;
		LDY	#>STARTDATABASE	;
		READFILE		;READ THE FILE

		LDA	#<STARTDATABASE	;
		STA	SRCPTR+0	;
		SEC			;
		SBC	#<$2400		;
		STA	WORK1+0		;
		LDA	#>STARTDATABASE	;
		STA	SRCPTR+1	;
		SBC	#>$2400		;
		STA	WORK1+1		;

		ADDBW	#32,SRCPTR	;

		MOVEW	SRCPTR,FIRSTSPRITE

		LDY	#IMAGEDATA+0	;
		LDA	(SRCPTR),Y	;
		CLC			;
		ADC	WORK1+0		;
		STA	(SRCPTR),Y	;
		INY			;
		LDA	(SRCPTR),Y	;
		ADC	WORK1+1		;
		STA	(SRCPTR),Y	;

		LDY	#NEXTSPRITE+0	;
		LDA	(SRCPTR),Y	;
		CLC			;
		ADC	WORK1+0		;
		STA	(SRCPTR),Y	;
		STA	WRKPTR+0	;
		INY			;
		LDA	(SRCPTR),Y	;
		ADC	WORK1+1		;
		STA	(SRCPTR),Y	;
		STA	WRKPTR+1	;

		LDY	#IMAGEDATA+0	;
		LDA	(WRKPTR),Y	;
		CLC			;
		ADC	WORK1+0		;
		STA	(WRKPTR),Y	;
		INY			;
		LDA	(WRKPTR),Y	;
		ADC	WORK1+1		;
		STA	(WRKPTR),Y	;

		LDY	#NEXTSPRITE+0	;
		LDA	#<PAUSEDSPR	;
		STA	(WRKPTR),Y	;
		INY			;
		LDA	#>PAUSEDSPR	;
		STA	(WRKPTR),Y	;

		SPRITES	STARTDATABASE+32,0 ;DRAW SPRITES

		MYDBUF_DISPLAY		;"PAGE FLIP"
		MYWAITEOF		;
		MYRGB16	STARTDATABASE	;UPDATE PALETTE

		LDX	#15		;SHORT DELAY
LOADSCNWAITLOOP
		MYWAITEOF		;
		DEX			;
		BNE	LOADSCNWAITLOOP	;

		RTS
ENDATRACT

	IF	ENDATRACT>ENDSOURCEBUFFER
	.WORD	ENDATRACT-ENDSOURCEBUFFER,OH_SHIT_ATRACT_OVERFLOW
	ENDIF

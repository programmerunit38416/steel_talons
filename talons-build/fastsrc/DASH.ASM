	.BYTE	RELOAD_HVST 			; Control 1
	.BYTE	$00 				; Control 2
	.WORD	CURSORSPR			; Next Sprite
	.WORD	TARGET.BBMDATA			; ImageData
	.WORD	TARGETCX			; HPos
	.WORD	TARGETCY			; VPos
	.WORD	$0100				; HSize
	.WORD	$0100				; VSize
	.WORD	$0000				; Stretch
	.WORD	$0000				; Tilt
	.BYTE	$09				; Palette
*
CURSORSPR
	.BYTE	ONE_PER_PIXEL+NORMAL_SPRITE	;
	.BYTE	RELOAD_NONE 			; Control 1
	.BYTE	$00 				; Control 2
	.WORD	COMPASS0SPR			; Next Sprite
	.WORD	CURSOR.BBMDATA			; ImageData
	.WORD	TARGETCX			; HPos
	.WORD	TARGETCY			; VPos
	.BYTE	$09				; Palette
*
COMPASS0SPR
	.BYTE	ONE_PER_PIXEL+NORMAL_SPRITE	;
	.BYTE	RELOAD_NONE			; Control 1
	.BYTE	$00 				; Control 2
	.WORD	COMPASS1SPR			; Next Sprite

* DRAW DASH
*
* ENTRY:
*	SPRPTR	OFFSET TO LAST LINK IN SCB LIST
*
DRAWDASH@
		LDY	#NEXTSPRITE		;POINT LAST LINK TO DASH SPRS
		LDA	#<DASHSPR3		;
		STA	(SPRPTR),Y		;
		INY				;
		LDA	#>DASHSPR3		;
		STA	(SPRPTR),Y		;(WILL END IN PAUSEDSPR)

		JSR	HIDEXSCORE@		;CHECK FOR HIDING SCORE
;;
;; DO ENEMY RADAR
;;
		JSR	SETERADAR@		;CHECK FOR IN ENEMY RADAR
;;
;; CHECK FOR LANDED
;;
		LDA	LANDEDSPR+CONTROL1	;INIT TO HIDE SPRITE
		ORA	#SKIP_SPRITE		;
		STA	LANDEDSPR+CONTROL1	;

		LDA	LANDEDTIMER		;TIMER ZERO?
		BEQ	NOTLANDED		;YES

		DEC	LANDEDTIMER		;NO - DECREMENT DELAY

		LDA	CRASHFLAG		;CRASHING?
		BNE	NOTLANDED		;YES - SKIP SPRITE

		LDA	LANDEDSPR+CONTROL1	;SHOW SPRITE
		AND	#\SKIP_SPRITE		;
		STA	LANDEDSPR+CONTROL1	;
NOTLANDED
;;
;; DO TURN INDICATOR
;;
		LDA	TURNTOGGLE		;CYCLE FLASHING
		INC	A			;
		AND	#3			;
		STA	TURNTOGGLE		;

		LDA	LTURNSPR+CONTROL1	;HIDE THE SPRITES
		ORA	#SKIP_SPRITE		;
		STA	LTURNSPR+CONTROL1	;
		STA	RTURNSPR+CONTROL1	;

		LDA	MISSION			;TRAINING?
		BEQ	?NOTURNS		;YES

		CMPIB	TRUE,INENEMYRADAR	;ENEMIES CLOSE BY?
		BNE	?NOTURNS		;NO

		LDA	TARGETSTATUS		;ALREADY HAVE ENEMY IN SIGHT?
		CMP	#LOCKED			;
		BEQ	?NOTURNS		;YES
		CMP	#TRACKING		;
		BEQ	?NOTURNS		;YES

		LDA	TURNTOGGLE		;FLASHED OFF?
		CMP	#2			;
		BGE	?NOTURNS		;YES

		CMPIB	TRUE,LEFTTURN		;LEFT TURN?
		BEQ	?LTURN			;YES
?RTURN
		LDA	RTURNSPR+CONTROL1	;RIGHT
		AND	#\SKIP_SPRITE		;
		STA	RTURNSPR+CONTROL1	;
		BRA	?NOTURNS		;
?LTURN
		LDA	LTURNSPR+CONTROL1	;LEFT
		AND	#\SKIP_SPRITE		;
		STA	LTURNSPR+CONTROL1	;
?NOTURNS
;;
;; DO COMPASS HUD
;;
		LDA	ZROTATION+0		;
		LSR	A			;
		LSR	A			;
		TAY				;
		LDX	COMPASSTABLE,Y		;

		LDA	COMPASS0SPRXS,X		;
		STA	COMPASS0SPR+HPOS	;

		LDA	COMPASS1SPRILOS,X	;
		STA	COMPASS1SPR+IMAGEDATA+0	;
		LDA	COMPASS1SPRIHIS,X	;
		STA	COMPASS1SPR+IMAGEDATA+1	;

		LDA	COMPASS2SPRILOS,X	;
		STA	COMPASS2SPR+IMAGEDATA+0	;
		LDA	COMPASS2SPRIHIS,X	;
		STA	COMPASS2SPR+IMAGEDATA+1	;

		LDA	ZROTATION+0		;NORTH
		STA	WORK1+0			;
		LDA	ZROTATION+1		;
		CLC				;
		ADC	#2			;
		AND	#3			;
		STA	WORK1+1			;
		LEA	COMPASSNSPR,DSTPTR	;
		JSR	SETCOMPASS@		;

		MOVEW	ZROTATION,WORK1		;SOUTH
		LEA	COMPASSSSPR,DSTPTR	;
		JSR	SETCOMPASS@		;

		LDA	ZROTATION+0		;EAST
		STA	WORK1+0			;
		LDA	ZROTATION+1		;
		CLC				;
		ADC	#3			;
		AND	#3			;
		STA	WORK1+1			;
		LEA	COMPASSESPR,DSTPTR	;
		JSR	SETCOMPASS@		;

		LDA	ZROTATION+0		;WEST
		STA	WORK1+0			;
		LDA	ZROTATION+1		;
		CLC				;
		ADC	#1			;
		AND	#3			;
		STA	WORK1+1			;
		LEA	COMPASSWSPR,DSTPTR	;
		JSR	SETCOMPASS@		;
;;
;; DO SCORE
;;
		CMPIB	TRUE,SCOREFLAG		;
		BNE	DOSCOREDONE		;

		MOVEIB	FALSE,SCOREFLAG		;

		STZ	WORK1			;

		LEA	SCORESPR1,WRKPTR	;
		LDX	#0			;
DOSCORELOOP
		CPX	#7			;
		BGE	DOSCOREDONE		;

		PHX				;
		LDA	SCORE,X			;

		BNE	?1			;NON-ZERO
		CPX	#6			;LAST DIGIT?
		BEQ	?1			;YES
		LDX	WORK1			;ALREADY NON-ZERO?
		BNE	?1			;YES

		LDY	#CONTROL1		;HIDE THE SPRITE
		LDA	(WRKPTR),Y		;
		ORA	#SKIP_SPRITE		;
		STA	(WRKPTR),Y		;
		BRA	?2			;
?1
		TAX				;

		LDY	#CONTROL1		;SHOW THE SPRITE
		LDA	(WRKPTR),Y		;
		AND	#\SKIP_SPRITE		;
		STA	(WRKPTR),Y		;

		INC	WORK1			;

		LDY	#IMAGEDATA+0		;
		LDA	XDIGITLO,X		;
		STA	(WRKPTR),Y		;
		INY				;
		LDA	XDIGITHI,X		;
		STA	(WRKPTR),Y		;
?2
		LDY	#NEXTSPRITE+0		;
		LDA	(WRKPTR),Y		;
		PHA				;
		INY				;
		LDA	(WRKPTR),Y		;
		STA	WRKPTR+1		;
		PLA				;
		STA	WRKPTR+0		;

		PLX				;
		INX				;
		BRA	DOSCORELOOP		;
DOSCOREDONE
;;
;; DO ALT, CURRENT MIN ALT AND SPEED HUD.  THREE DIVIDES: EACH ONE
;; RUNS WHILE THE LAST RESULT IS FINISHED AND THE NEXT IS SET UP.
;;
		LDA	MAXZ+0			;SET UP Z RANGE
		SEC				;
		SBC	#<MINZ			;
		STA	MATHP			;
		LDA	MAXZ+1			;
		SBC	#>MINZ			;
		STA	MATHN			;

		CLRW	MATHH			;ZCOORDINATE/MAXZ
		LDA	ZCOORDINATE+0		;
		SEC				;
		SBC	#<MINZ			;
		STA	MATHF			;
		LDA	ZCOORDINATE+1		;
		SBC	#>MINZ			;
		STA	MATHE			;START

		LDA	CMINZ+0			;CURRENT MINZ - MINZ (0 IF
		SEC				;	BELOW) WHILE IT RUNS
		SBC	#<MINZ			;
		TAX				;
		LDA	CMINZ+1			;
		SBC	#>MINZ			;
		BCS	?CMOK1			;
		LDA	#0			;
		TAX				;
?CMOK1
		STX	WORK2+0			;
		STA	WORK2+1			;

		WAITMATH			;
		LDX	MATHC			;
		LDY	MATHB			;
		CLRW	MATHH			;CURRENT MINZ/MAXZ
		LDA	WORK2+0			;
		STA	MATHF			;
		LDA	WORK2+1			;
		STA	MATHE			;START

		TYA				;ALT WHILE IT RUNS
		JSR	HUDPOS			;
		STA	ALTZSPR+VPOS		;

		LDA	SPEED+0			;SPEED - MINSPEED
		SEC				;
		SBC	#<MINSPEED		;
		STA	WORK3+0			;
		LDA	SPEED+1			;
		SBC	#>MINSPEED		;
		STA	WORK3+1			;

		WAITMATH			;
		LDX	MATHC			;
		LDY	MATHB			;
		LDA	#<(MAXSPEED-MINSPEED)	;SET UP SPEED RANGE
		STA	MATHP			;
		LDA	#>(MAXSPEED-MINSPEED)	;
		STA	MATHN			;
		CLRW	MATHH			;SPEED/SPEED RANGE
		LDA	WORK3+0			;
		STA	MATHF			;
		LDA	WORK3+1			;
		STA	MATHE			;START

		TYA				;CURRENT MIN ALT WHILE IT RUNS
		JSR	HUDPOS			;
		STA	ALTGSPR+VPOS		;

		WAITMATH			;
		LDX	MATHC			;SPEED
		LDA	MATHB			;
		JSR	HUDPOS			;
		STA	SPEEDSPR+VPOS		;
;;
;; DO DEBUG DISPLAY
;;
		LEA	DASHSPR3,WRKPTR		;SHOW FRAME TIME (DECIMAL)
		MOVEB	DEBUGVALUE0,WORK1	;
		CLRW	WORK1+1			;
		MOVEIB	2,WORK2			;
		JSR	PRINTDEC		;
;;
;; DO TARGETING SPRITES
;;
		LDA	TARGETSTATUS		;GET TARGET STATUS

		CMP	#IDLE			;TARGET IDLEING?
		BNE	?TNOTIDLE		;NO

		CLRB	TARGETX			;CENTER
		CLRB	TARGETY			;

		JMP	?TDONE			;
?TNOTIDLE
		CMP	#LOCKED			;LOCKED?
		BNE	?TNOTLOCKED		;NO

		MOVEB	NTARGETX,TARGETX	;SET POSITION
		MOVEB	NTARGETY,TARGETY	;

		JMP	?TDONE			;
?TNOTLOCKED
		CMP	#TRACKING		;TRACKING TO LOCK?
		BNE	?TNOTTRACKING		;

		LDX	#2			;INIT FLAG

		LDA	NTARGETX		;CALC DISTANCE TO X LOCK
		SEC				;
		SBC	TARGETX			;
		BPL	?TL1			;

		CMP	#-MTARGET		;
		BGE	?TL2			;

		SUBIB	MTARGET,TARGETX		;
		BRA	?TL3			;
?TL1
		CMP	#MTARGET+1		;
		BLT	?TL2			;

		ADDIB	MTARGET,TARGETX		;
		BRA	?TL3			;
?TL2
		MOVEB	NTARGETX,TARGETX	;X LOCKED
		DEX				;DECREMENT FLAG
?TL3
		LDA	NTARGETY		;CALC DISTANCE TO Y LOCK
		SEC				;
		SBC	TARGETY			;
		BPL	?TL4			;

		CMP	#-MTARGET		;
		BGE	?TL5			;

		SUBIB	MTARGET,TARGETY		;
		BRA	?TL6			;
?TL4
		CMP	#MTARGET+1		;
		BLT	?TL5			;

		ADDIB	MTARGET,TARGETY		;
		BRA	?TL6			;
?TL5
		MOVEB	NTARGETY,TARGETY	;Y LOCKED
		DEX				;DECREMENT FLAG
?TL6
		CPX	#00			;X AND Y LOCKED?
		BNE	?TL7			;NO

		MOVEIB	LOCKED,TARGETSTATUS	;YES - SET TO LOCKED
?TL7
		JMP	?TDONE			;
?TNOTTRACKING
		LDA	TARGETX			;RETURNING X
		BPL	?TR1			;

		CLC				;
		ADC	#MTARGET		;
		BMI	?TR2			;

		LDA	#00			;
		BRA	?TR2			;
?TR1
		BEQ	?TR2			;

		SEC				;
		SBC	#MTARGET		;
		BPL	?TR2			;

		LDA	#00			;
?TR2
		STA	TARGETX			;

		LDA	TARGETY			;RETURNING Y
		BPL	?TR3			;

		CLC				;
		ADC	#MTARGET		;
		BMI	?TR4			;

		LDA	#00			;
		BRA	?TR4			;
?TR3
		BEQ	?TR4			;

		SEC				;
		SBC	#MTARGET		;
		BPL	?TR4			;

		LDA	#00			;
?TR4
		STA	TARGETY			;

		LDA	TARGETX			;CENTERED?
		ORA	TARGETY			;
		BNE	?TDONE			;NO

		MOVEIB	IDLE,TARGETSTATUS	;YES - SET TO IDLE
?TDONE
		LDA	TARGETX			;SET TARGET HPOS
		CLC				;
		ADC	#TARGETCX		;
		STA	TARGETSPR+HPOS+0	;

		LDA	TARGETY			;SET TARGET VPOS
		CLC				;
		ADC	#TARGETCY		;
		STA	TARGETSPR+VPOS+0	;

		CMPIB	LOCKED,TARGETSTATUS	;LOCKED?
		BNE	?T1			;NO

		MOVEIW	LOCK.BBMDATA,TARGETSPR+IMAGEDATA
		MOVEIB	$03,TARGETSPR+PALETTE	;RED

		JSR	CALCTDIST@		;
		BRA	?T2			;
?T1
		MOVEIW	TARGET.BBMDATA,TARGETSPR+IMAGEDATA
		MOVEIB	$09,TARGETSPR+PALETTE	;WHITE
?T2
		LDA	ZOOMLEVEL		;ZOOMED IN?
		BEQ	NEEDCURSOR		;YES

		CMPIB	IDLE,TARGETSTATUS	;IDLE?
		BNE	SKIPONLYCURSOR		;YES - JUST SKIP CURSOR

		LDA	TARGETSPR+CONTROL1	;HIDE TARGET SPRITE
		ORA	#SKIP_SPRITE		;
		STA	TARGETSPR+CONTROL1	;
		BRA	SKIPPEDTARGET		;
SKIPONLYCURSOR
		LDA	TARGETSPR+CONTROL1	;SHOW TARGET SPRITE
		AND	#\SKIP_SPRITE		;
		STA	TARGETSPR+CONTROL1	;
SKIPPEDTARGET
		LDA	CURSORSPR+CONTROL1	;HIDE CURSOR SPRITE
		ORA	#SKIP_SPRITE		;
		STA	CURSORSPR+CONTROL1	;

		BRA	DONECURSOR		;
NEEDCURSOR
		LDA	TARGETSPR+CONTROL1	;SHOW TARGET SPRITE
		AND	#\SKIP_SPRITE		;
		STA	TARGETSPR+CONTROL1	;

		LDA	CURSORSPR+CONTROL1	;SHOW CURSOR SPRITE
		AND	#\SKIP_SPRITE		;
		STA	CURSORSPR+CONTROL1	;
DONECURSOR
		RTS
*
* CALC DISTANCE TO TARGET WHEN LOCKED
*
* IF DISTANCE > $3000 THEN SET TARGET SPRITE COLOR TO WHITE
*
CALCTDIST@
		LDY	#OBJ_X			;
		LDA	(TARGETPTR),Y		;
		SEC				;
		SBC	XCOORDINATE+0		;
		STA	WORK1+0			;
		INY				;
		LDA	(TARGETPTR),Y		;
		SBC	XCOORDINATE+1		;
		STA	WORK1+1			;

		LDY	#OBJ_Y			;
		LDA	(TARGETPTR),Y		;
		SEC				;
		SBC	YCOORDINATE+0		;
		STA	WORK2+0			;
		INY				;
		LDA	(TARGETPTR),Y		;
		SBC	YCOORDINATE+1		;
		STA	WORK2+1			;

		SIGNEDACCMATH			;INIT MATH
		CLEARACCUM			;

		LDA	WORK1+0			;
		STA	MATHD			;
		STA	MATHB			;
		LDA	WORK1+1			;
		STA	MATHC			;
		STA	MATHA			;START
		LDY	WORK2+1			;GET NEXT OPERAND WHILE IT RUNS
		WAITMATH			;

		LDA	WORK2+0			;
		STA	MATHD			;
		STA	MATHB			;
		STY	MATHC			;
		STY	MATHA			;START
		WAITMATH			;

		NOACCMATH			;

		LDA	MATHJ			;IN RANGE?
		CMP	#$0E			;($2A54**2)*2
		BLT	?INRANGE		;YES

		MOVEIB	$09,TARGETSPR+PALETTE	;WHITE
?INRANGE
		RTS
*
* DISPLAY MISSION LEVEL
*
DISPMISSION@
		LDA	MISSION			;PRINT MISSION NUMBER
		AND	#$0F			;
		CMP	#00			;TRAINING?
		BNE	?1			;NO

		LDA	#<DIGITT.BBMDATA	;T
		STA	DASHSPR1+IMAGEDATA+0	;
		LDA	#>DIGITT.BBMDATA	;
		STA	DASHSPR1+IMAGEDATA+1	;

		LDA	#<DIGITR.BBMDATA	;R
		STA	DASHSPR2+IMAGEDATA+0	;
		LDA	#>DIGITR.BBMDATA	;
		STA	DASHSPR2+IMAGEDATA+1	;
		BRA	?3			;
?1
		LEA	DASHSPR1,WRKPTR		;SHOW MISSION NUMBER
		MOVEB	MISSION,WORK1		;
		CLRW	WORK1+1			;
		MOVEIB	2,WORK2			;
		JSR	PRINTDEC		;
?3
		RTS
*
* SET COMPASS
*
* ENTRY:
*	WORK1	ROTATION FROM CENTER OF SCREEN
*		(-64 TO +64)
*
SETCOMPASS@
		LDA	WORK1+1			;
		AND	#3			;
		TAX				;

		LDA	NEGROT,X		;
		LSR	A			;
		ROR	WORK1+0			;
		LSR	A			;
		ROR	WORK1+0			;

		LDA	WORK1+0			;
		BPL	?1			;

		LDA	#64			;
		CLC				;
		ADC	WORK1+0			;
		CMP	#65			;
		BGE	?3			;

		TAX				;
		LDA	#45			;
		BRA	?2			;
?1
		CMP	#68			;
		BGE	?3			;

		TAX				;
		LDA	#81			;
?2
		CLC
		ADC	COMPASSDTABLE,X		;
		LDY	#HPOS			;
		STA	(DSTPTR),Y		;

		LDY	#CONTROL1		;
		LDA	(DSTPTR),Y		;
		AND	#\SKIP_SPRITE		;
		STA	(DSTPTR),Y		;

		RTS
?3
		LDY	#CONTROL1		;
		LDA	(DSTPTR),Y		;
		ORA	#SKIP_SPRITE		;
		STA	(DSTPTR),Y		;

		RTS
*
* HIDE XSCORE SPRITES
*
HIDEXSCORE@
		LDA	XSCORECOUNT		;
		BEQ	?HIDEIT			;

		DEC	XSCORECOUNT		;
		RTS				;
?HIDEIT
		LDA	XSCORESPR1+CONTROL1	;HIDE SCORE SPRITES
		ORA	#SKIP_SPRITE		;
		STA	XSCORESPR1+CONTROL1	;
		STA	XSCORESPR2+CONTROL1	;
		STA	XSCORESPR3+CONTROL1	;
		STA	XSCORESPR4+CONTROL1	;

		RTS
*
* DASH BOARD SPRITES
*
DASHSPR3
	.BYTE	TWO_PER_PIXEL+NORMAL_SPRITE	; Control 0
	.BYTE	RELOAD_HVST 			; Control 1
	.BYTE	$00 				; Control 2
	.WORD	DASHSPR4			; Next Sprite
	.WORD	DIGIT0.BBMDATA			; ImageData
	IF	DEBUG=FALSE
	.WORD	CLIPCOLS+1
	ELSE
	.WORD	2				; HPos
	ENDIF
	.WORD	2				; VPos
	.WORD	$0100				; HSize
	.WORD	$0100				; VSize
	.WORD	$0000				; Stretch
	.WORD	$0000				; Tilt
	.BYTE	$09,$70				; Palette
*
DASHSPR4
	.BYTE	TWO_PER_PIXEL+NORMAL_SPRITE	; Control 0
	.BYTE	RELOAD_HVST 			; Control 1
	.BYTE	$00 				; Control 2
	.WORD	TARGETSPR			; Next Sprite
	.WORD	DIGIT0.BBMDATA			; ImageData
	IF	DEBUG=FALSE
	.WORD	CLIPCOLS+6
	ELSE
	.WORD	2+5				; HPos
	ENDIF
	.WORD	2				; VPos
	.WORD	$0100				; HSize
	.WORD	$0100				; VSize
	.WORD	$0000				; Stretch
	.WORD	$0000				; Tilt
	.BYTE	$09,$70				; Palette
*
TARGETSPR

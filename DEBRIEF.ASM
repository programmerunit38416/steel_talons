DEBRIEF
		MOVEIB	$03,PAUSEDSPR+PALETTE	;FOREGROUND

		LEA	MISSION1PFA,WRKPTR	;

		LDX	#01			;MISSION INDEX
?DEBRIEFINITLOOP
		CPX	#12+1			;DONE?
		BGE	?DEBRIEFINITDONE	;YES


		LDA	MISSIONLIST,X		;GET MISSION RESULT
		BNE	?1			;
?DEBRIEFSKIP
		LDY	#CONTROL1		;
		LDA	(WRKPTR),Y		;
		ORA	#SKIP_SPRITE		;
		STA	(WRKPTR),Y		;
		BRA	?2			;
?1
		CMP	#-1			;
		BEQ	?DEBRIEFSKIP		;

		DEC	A			;
		ASL	A			;
		TAY				;
		LDA	PFADATA+1,Y		;
		PHA				;
		LDA	PFADATA+0,Y		;
		LDY	#IMAGEDATA		;
		STA	(WRKPTR),Y		;
		INY				;
		PLA				;
		STA	(WRKPTR),Y		;

		LDA	MISSIONLIST,X		;
		DEC	A			;
		TAY				;
		LDA	PFACOLOR,Y		;
		LDY	#PALETTE-8		;
		STA	(WRKPTR),Y		;
?2
		LDY	#NEXTSPRITE+0		;
		LDA	(WRKPTR),Y		;
		PHA				;
		INY				;
		LDA	(WRKPTR),Y		;
		STA	WRKPTR+1		;
		PLA				;
		STA	WRKPTR+0		;

		INX				;
		BRA	?DEBRIEFINITLOOP	;
?DEBRIEFINITDONE
		MOVEIW	DEBRIEFSPR,FIRSTSPRITE	;POINT TO FIRST SCB

		MYSPRITES			;DRAW SPRITES

		MYDBUF_DISPLAY			;"PAGE FLIP"
		MYWAITEOF			;
		MYRGB16	DEBRIEFPAL		;UPDATE PALETTE

		INITHMUSIC			;STOP MUSIC

		LDA	#INITIALDNL_FILE	;LOAD HISCORE SCREEN MUSIC
		GETDIR				;GET DIRECTORY ENTRY
		MYOPENFILE			;OPEN THE FILE
		LDA	#1			;DEST ADDRESS
		LDX	#<SPRBUFFER		;
		LDY	#>SPRBUFFER		;
		READFILE			;READ THE FILE

		LDA	#<SPRBUFFER		;START THE MUSIC
		LDX	#>SPRBUFFER		;
		PLAYMUSIC			;

		LDX	#15			;SHORT DELAY
?DEBRIEFWAITLOOP2
		MYWAITEOF			;
		DEX				;
		BNE	?DEBRIEFWAITLOOP2	;

		MOVEIB	12,COUNTER1		;
		MOVEIB	1,LASTMISSION		;
DEBRIEFLOOP
		LDA	MISSIONC1+VSIZE+1	;
		SEC				;
		SBC	#7			;
		STA	MISSIONC1+VSIZE+1	;
		LDA	MISSIONC1+VPOS+0	;
		CLC				;
		ADC	#7			;
		STA	MISSIONC1+VPOS+0	;

		JSR	DEBRIEFWAIT1		;WAIT 1 SECOND OR BUTTON PRESS

		LDA	MISSIONC2+VSIZE+1	;
		SEC				;
		SBC	#7			;
		STA	MISSIONC2+VSIZE+1	;
		LDA	MISSIONC2+VPOS+0	;
		CLC				;
		ADC	#7			;
		STA	MISSIONC2+VPOS+0	;

		JSR	DEBRIEFWAIT1		;WAIT 1 SECOND OR BUTTON PRESS

		LDA	MISSIONC3+VSIZE+1	;
		SEC				;
		SBC	#7			;
		STA	MISSIONC3+VSIZE+1	;
		LDA	MISSIONC3+VPOS+0	;
		CLC				;
		ADC	#7			;
		STA	MISSIONC3+VPOS+0	;

		LDX	LASTMISSION		;
		LDA	MISSIONLIST,X		;
		CMP	#1			;
		BNE	?1			;

		LDX	#WOW_SOUND		;FAILED!
		BRA	?2			;
?1
		CMP	#2			;
		BEQ	?3			;

		LDX	#MISSILE_SOUND		;ACED!
?2
		JSR	STARTSOUND@		;
?3
		JSR	DEBRIEFWAIT2		;WAIT 2 SECONDS OR BUTTON PRESS

		INC	LASTMISSION		;
		DEC	COUNTER1		;
		BNE	DEBRIEFLOOP		;

		LDX	#240			;4 SECONDS
		JMP	DEBRIEFWAITLOOP		;
*
* WAIT FOR 2 SECONDS OR A OR B BUTTON
*
DEBRIEFWAIT1
		MYSPRITES			;DRAW SPRITES
		MYDBUF_DISPLAY			;"PAGE FLIP"

		LDX	#30*1			;1/2 SECOND
		JMP	DEBRIEFWAITLOOP		;
*
* WAIT FOR 2 SECONDS OR A OR B BUTTON
*
DEBRIEFWAIT2
		MYSPRITES			;DRAW SPRITES
		MYDBUF_DISPLAY			;"PAGE FLIP"

		LDX	#30*3			;1 1/2 SECONDS
DEBRIEFWAITLOOP
		MYWAITEOF			;
		JSR	GETJOY@			;READ CONTROLLER

		LDA	DJOYVALUE		;GET DEBOUNCED

		BIT	#B_BUTTON		;B BUTTON PRESSED?
		BNE	DEBRIEFWAITDONE		;YES
		BIT	#A_BUTTON		;A BUTTON PRESSED?
		BNE	DEBRIEFWAITDONE		;YES

		PHX				;
		JSR	CHECKOTHERFLAGS@	;CHECK FLAGS FOR SPECIAL INPUT
		JSR	SELCHECKPAUSED@		;SELECT CHECK FOR PAUSE REQUEST
		PLX				;

		DEX				;
		BNE	DEBRIEFWAITLOOP		;
DEBRIEFWAITDONE
		RTS

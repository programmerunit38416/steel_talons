* GET YAW AND PITCH
*
* ENTRY:
*	WORK1	+/- XDIFF
*	WORK2	+/- YDIFF
*	WORK3	+/- ZDIFF
* EXIT:
*	WORK4	YAW  ($000-$3FF)
*	WORK5	PITCH ($000-$3FF)
*
GETYP@
		JSR	CALCYAW@		;CALC YAW

		MOVEIB	0,WORK5+1		;

		LDA	WORK3+1			;
		BPL	?1			;

		NEGW	WORK3			;
		MOVEIB	3,WORK5+1		;
?1
		LDX	WORK4+1			;GET HIGH BYTE INDEX

		LDA	COSSIGN,X		;SET SIGN FOR COSINE
		STA	WORK6			;

		STZ	WORK2+1			;INIT HIGH BYTE

		LDA	COSDIR,X		;INVERT?
		BEQ	?MLBL1			;NO

		LDA	#255			;YES - INVERT INDEX
		SEC				;
		SBC	WORK4+0			;
		TAX				;

		LDA	COSSINLO+1,X		;GET COSINE EFFECT
		STA	WORK2+0			;NOTE: +1,X
		BNE	?MLBL3			;
		CPX	#255			;
		BEQ	?MLBL3			;
		BRA	?MLBL2			;
?MLBL1
		LDX	WORK4+0			;GET LOW BYTE INDEX

		LDA	COSSINLO,X		;GET COSINE EFFECT
		STA	WORK2+0			;
		BNE	?MLBL3			;
?MLBL2
		INC	WORK2+1			;
?MLBL3

STARTPGM@
		JMP	STARTUPINIT@		;DO STARTUP INIT
STARTUPCONT@
		JMP	RESTART@		;CONTINUE BY RESTART
*
* RESTART POINT OF PROGRAM
*
RESTART@
		JMP	RESTARTINIT@		;DO RESTART INIT
RESTARTCONT@
		LDA	#FALSE			;CLEAR SPECIAL FLAGS
		STA	RESTARTFLAG		;
		STA	FLIPFLAG		;
		STA	PAUSEDFLAG		;
		STA	TOGPAUSEDFLAG		;
		STA	OPTION1FLAG		;
		STA	OPTION2FLAG		;
		STA	ABUTTONFLAG		;

		STZ	CRASHFLAG		;
		STZ	REDPALFLAG		;

		MOVEIB	TRUE,FIRSTFRAME		;SET FLAG

		MOVEB	VBTIME,THISTIME		;
MAINLOOP@
		MOVEB	THISTIME,LASTTIME	;SAVE VARIABLES
		MOVEB	VBTIME,THISTIME		;

		LDA	THISTIME		;CALCULATE FRAME TIME
		SEC				;
		SBC	LASTTIME		;
		STA	FRAMETIME		;

		JSR	SETUPVIEW@		;SET UP VIEW COORDINATES

		CMPIB	TRUE,FIRSTFRAME		;FIRST FRAME?
		BNE	NOANIMOBJS		;NO

		JSR	ANIMOBJECTS@		;ANIMATE OBJECTS
		MOVEIB	FALSE,FIRSTFRAME	;CLEAR FLAG
NOANIMOBJS
		JSR	SORTOBJECTS@		;SORT OBJECTS
		JSR	DRAWOBJECTS@		;DRAW OBJECTS

		MOVEB	FRAMETIME,DEBUGVALUE0	;DEBUG - DISPLAY FRAME TIME

		JSR	DRAWDASH@		;DRAW THE DASHBOARD

		MYSPRITES			;DRAW SPRITES
		MYDBUF_DISPLAY			;"PAGE FLIP"

		LDA	REDPALFLAG		;
		BEQ	NOREDPAL		;
		CMP	#1			;
		BEQ	DORESTPAL		;

		DEC	REDPALFLAG		;
		MOVEIB	FALSE,UPDATEPALFLAG	;CLEAR FLAG
		MYWAITEOF			;SMOOTH
		MYRGB16	REDPAL			;UPDATE HARDWARE PALETTE
		JMP	SKIPRESTPALETTE		;
NOREDPAL
		CMPIB	TRUE,UPDATEPALFLAG	;SHOULD WE UPDATE THE PALETTE?
		BNE	SKIPRESTPALETTE		;NO
DORESTPAL
		STZ	REDPALFLAG		;
		MOVEIB	FALSE,UPDATEPALFLAG	;CLEAR FLAG
		MYWAITEOF			;SMOOTH
		MYRGB16	DEFPAL			;UPDATE HARDWARE PALETTE
SKIPRESTPALETTE
WAITVBCOUNTER
		LDA	VBCOUNTER		;FRAME DONE?
		BNE	WAITVBCOUNTER		;NO CONTINUE TO WAIT

		MOVEIB	DEFFRAMETIME,VBCOUNTER	;RESET COUNTER

		JSR	CHECKCRASH@		;CHECK FOR CRASH

		JSR	CHECKOTHERFLAGS@	;CHECK FLAGS FOR SPECIAL INPUT
		JSR	CHECKPAUSED@		;CHECK FOR PAUSE REQUEST

		JSR	MOVEMENT@		;MOVE THE VIEW AROUND
		JSR	UPDATEPOS@		;UPDATE POSITION IN DATABASE

		JSR	ANIMOBJECTS@		;ANIMATE OBJECTS

		JSR	UPDTIMER@		;UPDATE TIMER

		CMPIB	TRUE,MISSIONOVER	;FLAG SET?
		BNE	?1			;NO

		LDA	MISSIONOVERC		;COUNTER ZERO?
		BEQ	MAINDONE		;YES - DONE

		DEC	MISSIONOVERC		;DECREMENT COUNTER
?1
		JMP	MAINLOOP@		;
MAINDONE
		RTS				;EXIT
